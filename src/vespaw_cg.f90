      SUBROUTINE CG_INTERNAL_ORTHO_BATCH(NGL,PSI1,NLOW,EIGVEC,NB)
!     ******************************************************************
!     ** ORTHOGONALIZES PSI1 AGAINST THE FIRST NLOW ALREADY-CONVERGED  **
!     ** BANDS EIGVEC(:,1:NLOW), REPLACING NLOW SEPARATE CALLS TO      **
!     ** CG_INTERNAL_ORTHO_PSI WITH ONE BATCHED PLANEWAVE$SCALARPRODUCT**
!     ** CALL. MATHEMATICALLY IDENTICAL TO THE SEQUENTIAL DO IB1=1,NLOW**
!     ** LOOP IT REPLACES: EIGVEC(:,1:NLOW) ARE ALREADY MUTUALLY       **
!     ** O-ORTHONORMAL (EACH WAS ITSELF ORTHOGONALIZED AGAINST ALL     **
!     ** EARLIER ONES BEFORE IT CONVERGED), SO PROJECTING OUT AN       **
!     ** ORTHONORMAL SET GIVES THE SAME RESULT ONE VECTOR AT A TIME    **
!     ** OR ALL AT ONCE -- ONLY THE CALL/LOOP OVERHEAD CHANGES.        **
!     ******************************************************************
      USE CG_INTERFACE_MODULE, ONLY: OPSIOLD
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN)    :: NGL
      COMPLEX(8),INTENT(INOUT) :: PSI1(NGL)
      INTEGER(4),INTENT(IN)    :: NLOW
      INTEGER(4),INTENT(IN)    :: NB
      COMPLEX(8),INTENT(IN)    :: EIGVEC(NGL,NB)
      COMPLEX(8),ALLOCATABLE   :: OTMP(:,:)
      COMPLEX(8)               :: CVAR(1,NLOW)
      INTEGER(4)                :: IB1
!     ******************************************************************
      IF(NLOW.LT.1) RETURN
      ALLOCATE(OTMP(NGL,NLOW))
      DO IB1=1,NLOW
        OTMP(:,IB1)=OPSIOLD(IB1,:)
      END DO
      CALL PLANEWAVE$SCALARPRODUCT(' ',NGL,1,1,PSI1,NLOW,OTMP,CVAR)
      CALL MPE$COMBINE('K','+',CVAR)
      DO IB1=1,NLOW
        PSI1(:)=PSI1(:)-CONJG(CVAR(1,IB1))*EIGVEC(:,IB1)
      END DO
      DEALLOCATE(OTMP)
      RETURN
      END SUBROUTINE CG_INTERNAL_ORTHO_BATCH
