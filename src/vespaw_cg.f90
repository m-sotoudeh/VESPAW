      SUBROUTINE RMM_DIIS_COEFF(NGL,NDIM,NH,XH,RH,XOUT,ROUT)
!     ******************************************************************
!     ** PULAY-STYLE DIIS EXTRAPOLATION FOR A SINGLE BAND'S HISTORY OF   **
!     ** NH TRIAL VECTORS XH(:,:,1:NH) AND RESIDUALS RH(:,:,1:NH):       **
!     ** SOLVE MIN C^T*B*C S.T. SUM(C)=1, B_JK=RE(<RH_J|RH_K>) (REAL     **
!     ** SYMMETRIC, POSITIVE SEMI-DEFINITE -- THE IMAGINARY PART OF THE  **
!     ** HERMITIAN FORM CANCELS IN THE SYMMETRIC DOUBLE SUM FOR REAL     **
!     ** COEFFICIENTS C), VIA THE SAME CLOSED FORM THE PULAY DENSITY     **
!     ** MIXER USES (PAW_MIXER.F90): C=AINV*1/(1^T*AINV*1). RETURNS THE  **
!     ** EXTRAPOLATED XOUT=SUM C*XH, ROUT=SUM C*RH (VALID BY LINEARITY   **
!     ** OF THE RESIDUAL OPERATOR R=H-EPS*O IN ITS ARGUMENT).            **
!     ******************************************************************
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NGL
      INTEGER(4),INTENT(IN) :: NDIM
      INTEGER(4),INTENT(IN) :: NH
      COMPLEX(8),INTENT(IN) :: XH(NGL,NDIM,NH)
      COMPLEX(8),INTENT(IN) :: RH(NGL,NDIM,NH)
      COMPLEX(8),INTENT(OUT):: XOUT(NGL,NDIM)
      COMPLEX(8),INTENT(OUT):: ROUT(NGL,NDIM)
      COMPLEX(8)             :: BMATC(NH,NH)
      REAL(8)                :: BMAT(NH,NH),BINV(NH,NH)
      REAL(8)                :: ALPHA(NH),SVAR
      REAL(8)                :: REGVAR
      INTEGER(4)              :: J,K
!     ******************************************************************
      IF(NH.EQ.1) THEN
        XOUT=XH(:,:,1)
        ROUT=RH(:,:,1)
        RETURN
      END IF
      CALL PLANEWAVE$SCALARPRODUCT('=',NGL,NDIM,NH,RH(:,:,1:NH),NH,RH(:,:,1:NH),BMATC)
      CALL MPE$COMBINE('K','+',BMATC)
      BMAT=REAL(BMATC,KIND=8)
!     == TIKHONOV-REGULARIZE BEFORE INVERTING -- SAME FIX AS THE PULAY/     ==
!     == ANDERSON DENSITY MIXERS (WAVES_MIXRHO_PUL/_ANDERSON, PAW_MIXER.F90)==
!     == FOR THE SAME FAILURE MODE: NEAR-PARALLEL HISTORY RESIDUALS (MORE   ==
!     == LIKELY NOW THAT NRMMX, AND HENCE NH, IS USER-TUNABLE) MAKE BMAT    ==
!     == NEAR-SINGULAR, PRODUCING HUGE EXTRAPOLATION COEFFICIENTS AND A     ==
!     == DIVERGING TRIAL BAND VECTOR MID-SWEEP.                             ==
      REGVAR=0.D0
      DO J=1,NH
        REGVAR=REGVAR+BMAT(J,J)
      END DO
      REGVAR=MAX(REGVAR/REAL(NH,KIND=8)*1.D-6,1.D-12)
      DO J=1,NH
        BMAT(J,J)=BMAT(J,J)+REGVAR
      END DO
      CALL LIB$INVERTR8(NH,BMAT,BINV)
      SVAR=SUM(BINV)
      DO J=1,NH
        ALPHA(J)=SUM(BINV(J,:))/SVAR
      END DO
      XOUT=(0.D0,0.D0)
      ROUT=(0.D0,0.D0)
      DO K=1,NH
        XOUT=XOUT+CMPLX(ALPHA(K),0.D0,KIND=8)*XH(:,:,K)
        ROUT=ROUT+CMPLX(ALPHA(K),0.D0,KIND=8)*RH(:,:,K)
      END DO
      RETURN
      END SUBROUTINE RMM_DIIS_COEFF
