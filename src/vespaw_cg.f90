      SUBROUTINE CG_PROJECTIONS(MAP,GSET,NAT,R,NGL,NDIM,NB,NPRO,PSI,PROPSI)
!     ******************************************************************
!     **  <P|PSI> SUMMED OVER THE TASKS OF THE K-GROUP. WAVES_PROJECTIONS **
!     **  RETURNS ONLY THE CONTRIBUTION OF THE LOCAL PLANE WAVES; WITHOUT **
!     **  THE SUM THE SOLVERS WERE WRONG WHENEVER THE PLANE WAVES OF A    **
!     **  K-POINT ARE DISTRIBUTED (SI8 AT GAMMA ON 4 TASKS: 6.6 H LOW).   **
!     ******************************************************************
      USE WAVES_MODULE, ONLY : MAP_TYPE,GSET_TYPE
      USE MPE_MODULE
      IMPLICIT NONE
      TYPE(MAP_TYPE) ,INTENT(IN) :: MAP
      TYPE(GSET_TYPE),INTENT(IN) :: GSET
      INTEGER(4)     ,INTENT(IN) :: NAT,NGL,NDIM,NB,NPRO
      REAL(8)        ,INTENT(IN) :: R(3,NAT)
      COMPLEX(8)     ,INTENT(IN) :: PSI(NGL,NDIM,NB)
      COMPLEX(8)     ,INTENT(OUT):: PROPSI(NDIM,NB,NPRO)
      CALL WAVES_PROJECTIONS(MAP,GSET,NAT,R,NGL,NDIM,NB,NPRO,PSI,PROPSI)
      CALL MPE$COMBINE('K','+',PROPSI)
      RETURN
      END SUBROUTINE CG_PROJECTIONS
