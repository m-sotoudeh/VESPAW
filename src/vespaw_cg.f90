      SUBROUTINE EDFT_BUILDHPHYS(NGL,NDIM,NB,NPRO,PSI,PROJ,HPHYS)
!     ******************************************************************
!     **  BUILDS HPHYS(NB,NB)=<PSI_I|H|PSI_J> FOR THE CURRENT PSI/PROJ, **
!     **  USING THE SAME WAVES_HPSI/PLANEWAVE$SCALARPRODUCT PRIMITIVES  **
!     **  DAVIDSON_BLOCK_SWEEP ITSELF USES TO BUILD ITS OWN SUBSPACE    **
!     **  HAMILTONIAN (SUBH). MEANT TO BE CALLED RIGHT AFTER A COMPLETED**
!     **  DAVIDSON_BLOCK_SWEEP, WHERE ITS OWN RAYLEIGH-RITZ GUARANTEE   **
!     **  PSI^H*O*PSI=I (SEE THAT ROUTINE'S HEADER COMMENT) MAKES THE   **
!     **  OVERLAP MATRIX IRRELEVANT: HPHYS IS THEN EXACTLY THE PHYSICAL **
!     **  HAMILTONIAN EXPRESSED IN AN ORTHONORMAL BASIS, THE FORM       **
!     **  EDFT$HAUXFORCE/EDFT$OCCUPATIONS (ORDINARY, NOT GENERALIZED,   **
!     **  DIAGONALIZATION VIA LIB$DIAGC8) EXPECT. CALLING THIS ON A PSI **
!     **  THAT IS NOT O-ORTHONORMAL WOULD BE PHYSICALLY MEANINGLESS.    **
!     **  USED ONLY BY THE EDFT SHADOW-MODE DIAGNOSTIC IN               **
!     **  DAVIDSON$STATE_BY_BLOCK FOR NOW -- SEE THE DEV NOTES.     **
!     ******************************************************************
      USE CG_INTERFACE_MODULE, ONLY: NAT,LMNXX,DH,NRL,V,ISPIN
      USE WAVES_MODULE, ONLY: MAP,GSET,NDIMD
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NGL
      INTEGER(4),INTENT(IN) :: NDIM
      INTEGER(4),INTENT(IN) :: NB
      INTEGER(4),INTENT(IN) :: NPRO
      COMPLEX(8),INTENT(IN) :: PSI(NGL,NDIM,NB)
      COMPLEX(8),INTENT(IN) :: PROJ(NDIM,NB,NPRO)
      COMPLEX(8),INTENT(OUT):: HPHYS(NB,NB)
      COMPLEX(8),ALLOCATABLE:: HPSI(:,:,:)
      REAL(8)   ,ALLOCATABLE:: R0(:,:)
!     ******************************************************************
      ALLOCATE(R0(3,NAT))
      CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,R0)
      ALLOCATE(HPSI(NGL,NDIM,NB))
      CALL WAVES_HPSI(MAP,GSET,ISPIN,NGL,NDIM,NDIMD,NB,NPRO,LMNXX,NAT &
     &                ,NRL,PSI,V(1,ISPIN),R0,PROJ,DH,HPSI)
      CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,PSI,NB,HPSI,HPHYS)
      CALL MPE$COMBINE('K','+',HPHYS)
      HPHYS(:,:)=0.5D0*(HPHYS(:,:)+CONJG(TRANSPOSE(HPHYS(:,:))))
      DEALLOCATE(R0)
      DEALLOCATE(HPSI)
      RETURN
      END SUBROUTINE EDFT_BUILDHPHYS
!
!     ..................................................................
      SUBROUTINE DAVIDSON_BLOCK_SWEEP(NGL,NB,NDIM,NPRO,CONV,NSWEEPX,G2,R0 &
     &                                ,EPS,PSI,PROJ,F,TCONV)
!     ******************************************************************
!     ** BLOCKED DAVIDSON ITERATIVE DIAGONALIZER (KRESSE & FURTHMUELLER, **
!     ** COMP. MATER. SCI. 6, 15 (1996)) WITH BAND LOCKING/DEFLATION.    **
!     ** UNLIKE CG_STATE_BY_STATE (ONE BAND AT A TIME, RE-APPLYING H/O   **
!     ** FOUR TIMES PER BAND PER INNER ITERATION), THIS ROUTINE APPLIES  **
!     ** H/O TO A BLOCK OF BANDS AT ONCE VIA THE ALREADY-BATCHED         **
!     ** WAVES_HPSI/WAVES_OPSI, EXPANDS THE TRIAL SUBSPACE WITH          **
!     ** PRECONDITIONED RESIDUAL VECTORS EACH SWEEP, AND CONTRACTS BACK  **
!     ** VIA A RAYLEIGH-RITZ STEP (SAME MATH AS CG_SUBSPACEROTATE).      **
!     **                                                                 **
!     ** HISTORY (WHY LOCKING, NOT JUST EXCLUSION): AN EARLIER VERSION   **
!     ** EXCLUDED CONVERGED BANDS FROM GETTING A FRESH CORRECTION EACH    **
!     ** SWEEP TO SAVE WORK, BUT LEFT THEIR PSI COLUMN UNPROTECTED IN THE **
!     ** SHARED RAYLEIGH-RITZ BASIS -- WITHOUT A CORRECTION OF ITS OWN,   **
!     ** AN EXCLUDED BAND COULD BE ROTATED INTO A WORSE STATE BY OTHER    **
!     ** BANDS' CORRECTIONS (OBSERVED: A REPRODUCIBLE ~20X RESIDUAL       **
!     ** SPIKE ON PRMNO3). THE FIX AT THE TIME WAS TO STOP EXCLUDING      **
!     ** ANYONE (ALWAYS CORRECT ALL NB BANDS, NORMALIZING EVERY           **
!     ** CORRECTION DIRECTION SO A NEAR-CONVERGED BAND'S NOISE DOESN'T    **
!     ** PRODUCE A SPURIOUS LOW-EIGENVALUE STATE) -- CORRECT, BUT IT      **
!     ** THREW AWAY THE SPEEDUP FROM SHRINKING WORK AS BANDS CONVERGE.    **
!     **                                                                 **
!     ** PROPER LOCKING RECOVERS THAT SPEEDUP SAFELY: ONCE A BAND'S       **
!     ** RESIDUAL DROPS BELOW CONV, IT IS REMOVED FROM THE ACTIVE         **
!     ** WORKING SET ENTIRELY (NOT JUST SKIPPED FOR CORRECTION) -- ITS    **
!     ** PSI/EPS/PROJ ARE FROZEN AND IT NO LONGER PARTICIPATES IN THE     **
!     ** ACTIVE RAYLEIGH-RITZ AT ALL, SO IT CANNOT BE DESTABILIZED BY     **
!     ** OTHER BANDS' CORRECTIONS (UNLIKE THE OLD BUGGY EXCLUSION, WHICH  **
!     ** LEFT IT IN THE SHARED BASIS). NEW CORRECTION DIRECTIONS FOR THE  **
!     ** STILL-ACTIVE BANDS ARE EXPLICITLY O-PROJECTED AGAINST ALL LOCKED **
!     ** BANDS' PSI (THEMSELVES MUTUALLY O-ORTHONORMAL, SINCE EVERY       **
!     ** RAYLEIGH-RITZ STEP GUARANTEES U^H*S*U=I) SO THE ACTIVE SUBSPACE  **
!     ** CANNOT DRIFT BACK INTO REPRESENTING A DIRECTION A LOCKED BAND     **
!     ** ALREADY OWNS. H/O IMAGES OF LOCKED BANDS ARE CACHED ONCE AT THE   **
!     ** MOMENT OF LOCKING (THEY CAN'T CHANGE SINCE THE BAND IS FROZEN),   **
!     ** SO LOCKED BANDS NEVER COST ANOTHER WAVES_HPSI/WAVES_OPSI CALL.    **
!     **                                                                 **
!     ** NO EXPLICIT GRAM-SCHMIDT AMONG THE CORRECTION VECTORS THEMSELVES **
!     ** IS NEEDED: LIB$GENERALEIGENVALUEC8 SOLVES A GENERALIZED          **
!     ** EIGENPROBLEM VALID FOR ANY (EVEN NON-ORTHONORMAL) TRIAL BASIS -- **
!     ** THE OVERLAP MATRIX SUBO ENCODES WHATEVER NON-ORTHONORMALITY      **
!     ** EXISTS. A SMALL TIKHONOV REGULARIZATION ON SUBO'S DIAGONAL       **
!     ** GUARDS AGAINST RESIDUAL ILL-CONDITIONING.                        **
!     **                                                                 **
!     ** OCCUPATION-WEIGHTED LOCKING (F, ENSEMBLE-DFT PROTOTYPE, SEE      **
!     ** THE DEV NOTES): F(IB) IS A RELATIVE OCCUPATION WEIGHT IN     **
!     ** [0,1] FOR BAND IB (1=FULLY WEIGHTED, SAME AS BEFORE THIS WAS     **
!     ** ADDED). A BAND'S EFFECTIVE LOCKING TOLERANCE IS CONV SCALED BY   **
!     ** 1/FEFF, WHERE FEFF=FWEIGHTFLOOR+F(IB)*(1-FWEIGHTFLOOR) IS A      **
!     ** LINEAR RAMP: FEFF=1 EXACTLY AT F=1 (FULLY-OCCUPIED BANDS KEEP    **
!     ** TODAY'S EXACT CRITERION, NO APPROXIMATION), FEFF=FWEIGHTFLOOR AT **
!     ** F=0 (MAXIMUM LOOSENING, A NEARLY-EMPTY BAND LOCKS WITH A MUCH    **
!     ** LARGER ALLOWED RESIDUAL), AND EVERYTHING IN BETWEEN IS A SINGLE  **
!     ** SMOOTH FORMULA -- NO KINK AT SOME THRESHOLD F, UNLIKE AN         **
!     ** EARLIER MAX(F,FLOOR) VERSION (SEE THE DEV NOTES, THE         **
!     ** "PROPERLY TUNE THE FLOOR"/"SMOOTH THE CLAMP" FOLLOW-UP): THAT    **
!     ** EARLIER VERSION, TESTED WITH A REAL (BUT BUGGY, SEE BELOW)       **
!     ** OCCUPATION SOURCE, PRODUCED A DISCONTINUOUS ENERGY JUMP EVERY    **
!     ** OUTER ITERATION AT THE MOMENT A LOW-F BAND CROSSED THE HARD      **
!     ** THRESHOLD AND LOCKED WHILE STILL UNDER-CONVERGED.                **
!     **                                                                 **
!     ** THIS DOES *NOT* SCALE THE RESIDUAL/CORRECTION VECTOR ITSELF -- A **
!     ** NAIVE SCALE-THEN-NORMALIZE ATTEMPT WAS CONSIDERED AND REJECTED   **
!     ** SINCE THE PER-VECTOR O-NORMALIZATION FURTHER BELOW WOULD ERASE   **
!     ** ANY UNIFORM SCALAR APPLIED TO A CORRECTION DIRECTION BEFORE IT.  **
!     ** WHY THE LOCKING TOLERANCE INSTEAD: IT'S THE ONE PLACE A PER-BAND **
!     ** WEIGHT SURVIVES THE NORMALIZATION AND GENUINELY CHANGES WHICH    **
!     ** BANDS KEEP CONSUMING SWEEPS.                                    **
!     **                                                                 **
!     ** F ITSELF, WHEN FED FROM DYNOCC$GETR8A('OCC',...), MUST BE        **
!     ** DIVIDED BY BOTH FMAX *AND* WKPT(IKPT), NOT JUST FMAX -- 'OCC'    **
!     ** RETURNS FMAX*WKPT(IKPT)*(BARE OCCUPATION FRACTION) (SEE          **
!     ** DYNOCC_WGHT), NOT A BARE PER-BAND NUMBER. GETTING THIS WRONG     **
!     ** SILENTLY SCALES *EVERY* BAND'S WEIGHT DOWN BY ~1/NKPT, NOT JUST  **
!     ** LOW-OCCUPATION ONES -- THE BUG BEHIND THE FIRST, MISLEADING      **
!     ** "OCCUPATION-WEIGHTED LOCKING HURTS" RESULT (SEE THE DESIGN).    **
!     ******************************************************************
      USE CG_INTERFACE_MODULE, ONLY: NAT,LMNXX,DH,NRL,V,ISPIN,TREALSUB
      USE WAVES_MODULE, ONLY: MAP,GSET,NDIMD
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4)               :: IDIMP
      INTEGER(4),INTENT(IN)    :: NGL
      INTEGER(4),INTENT(IN)    :: NB
      INTEGER(4),INTENT(IN)    :: NDIM
      INTEGER(4),INTENT(IN)    :: NPRO
      REAL(8)   ,INTENT(IN)    :: CONV
      INTEGER(4),INTENT(IN)    :: NSWEEPX
      REAL(8)   ,INTENT(IN)    :: G2(NGL)
      REAL(8)   ,INTENT(IN)    :: R0(3,NAT)
      REAL(8)   ,INTENT(INOUT) :: EPS(NB)
      COMPLEX(8),INTENT(INOUT) :: PSI(NGL,NDIM,NB)
      COMPLEX(8),INTENT(INOUT) :: PROJ(NDIM,NB,NPRO)
      REAL(8)   ,INTENT(IN)    :: F(NB)
      LOGICAL(4),INTENT(OUT)   :: TCONV
      LOGICAL(4),SAVE          :: TFLOORCHECKED=.FALSE.
      REAL(8)   ,SAVE          :: FWEIGHTFLOOR=6.D-1 ! DEFAULT, SEE THE DEV NOTES
      CHARACTER(16)            :: CENVFLOOR
      REAL(8)                  :: FEFF
      REAL(8)                  :: EFFCONV
      INTEGER(4)               :: NTOT,NACT,NACTOLD,NLOCK,NSURV
      INTEGER(4)               :: ISWEEP,IB,IB1,IB2,IC,K
      INTEGER(4)               :: IACT(NB),IACTOLD(NB),LOCKIDX(NB)
      COMPLEX(8),ALLOCATABLE   :: PB(:,:,:),HB(:,:,:),OB(:,:,:)
      COMPLEX(8),ALLOCATABLE   :: D(:,:,:),HD(:,:,:),OD(:,:,:),W(:,:,:)
      COMPLEX(8),ALLOCATABLE   :: PRB(:,:,:),PD(:,:,:),PWORK(:,:,:)
      REAL(8)   ,ALLOCATABLE   :: EPSACT(:),RNORMACT(:)
      COMPLEX(8),ALLOCATABLE   :: SUBH(:,:),SUBO(:,:),SUBVEC(:,:)
      REAL(8)   ,ALLOCATABLE   :: SUBEPS(:)
      COMPLEX(8),ALLOCATABLE   :: RNORMMAT(:,:)
      COMPLEX(8),ALLOCATABLE   :: SLOCK(:,:),CMAT(:,:)
      LOGICAL(4)               :: TLOCKNOW(NB)
      INTEGER(4)               :: NG,LB,NNEW,J,IS
      REAL(8)                  :: REGVAR
!     == DAV+ANDERSON SCAN0R INSTABILITY DIAGNOSTIC (2026-09-09): OPT-IN,     ==
!     == FOLLOW-UP TO VESPAW_SCAN0R_SWAP_DIAG -- INSTRUMENTS THE SUBSPACE     ==
!     == GENERALIZED EIGENPROBLEM ITSELF (SUBEPS SPREAD, SUBO CONDITION       ==
!     == NUMBER) INSTEAD OF THE ONSITE SWAP TERM. SEE THE DEV NOTES,      ==
!     == "WHY IS DAV+ANDERSON UNSTABLE FOR DCTYPE.NE.TYPE".                   ==
      LOGICAL(4),SAVE          :: TDAVCONDDIAGCHECKED=.FALSE.
      LOGICAL(4),SAVE          :: TDAVCONDDIAG=.FALSE.
      INTEGER(4),SAVE          :: DAVCONDDIAGCALL=0
      CHARACTER(16)            :: CENVDAVCONDDIAG
      COMPLEX(8),ALLOCATABLE   :: SOIDENT(:,:),SOVEC(:,:)
      REAL(8)   ,ALLOCATABLE   :: SOEIG(:)
!     == TUNABLE SUBO TIKHONOV FLOOR (2026-09-09): OPT-IN OVERRIDE OF THE     ==
!     == RELATIVE REGULARIZATION FACTOR BELOW (DEFAULT UNCHANGED, 1.D-10) -- ==
!     == VESPAW_DAV_COND_DIAG MEASURED SUBO CONDITION NUMBERS UP TO ~2E5 ON  ==
!     == THE SCAN0R DAV+ANDERSON INSTABILITY DECK AGAINST THAT DEFAULT,      ==
!     == WHICH IS TOO SMALL TO MEANINGFULLY BOUND A GAP THAT WIDE. SEE       ==
!     == THE DEV NOTES, "WHY IS DAV+ANDERSON UNSTABLE...".               ==
      LOGICAL(4),SAVE          :: TSUBOREGCHECKED=.FALSE.
      REAL(8)   ,SAVE          :: SUBOREGFAC=0.D0   ! 0: OFF -- BASIS IS O-ORTHONORMAL NOW
!     == ROBUST-SUBSPACE WORK ARRAYS AND THRESHOLDS (SEE THE SWEEP LOOP) ==
      REAL(8)   ,PARAMETER     :: DCANCEL=1.D-20  ! NORM**2 LOST TO CANCELLATION
      REAL(8)   ,PARAMETER     :: ECANON=1.D-10   ! CANONICAL-ORTHOGONALIZATION CUTOFF
      COMPLEX(8),ALLOCATABLE   :: SACT(:,:),GMAT(:,:),GVEC(:,:),TMAT(:,:)
      REAL(8)   ,ALLOCATABLE   :: GEIG(:),DNORM0(:),DSCALE(:)
      COMPLEX(8)               :: CSCAL(1,1)
      REAL(8)                  :: SVARN
      INTEGER(4)               :: IPASS,NKEEP
      CHARACTER(16)            :: CENVSUBOREG
!     == (THE 2026-09-11 ABSOLUTE RESIDUAL-NORM DEFLATION, DELTAREGVARMIN,  ==
!     == WAS REPLACED 2026-09-23 BY PROPER ORTHOGONALIZATION -- SEE THE     ==
!     == "ROBUST SUBSPACE" BLOCK IN THE SWEEP LOOP AND THE DEV NOTES.)  ==
      INTEGER(4)               :: NGOOD,GOODIDX(NB)
!     ******************************************************************
      IF(.NOT.TFLOORCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_LOCK_FLOOR',CENVFLOOR)
        IF(LEN_TRIM(CENVFLOOR).GT.0) READ(CENVFLOOR,*) FWEIGHTFLOOR
        TFLOORCHECKED=.TRUE.
      END IF
      IF(.NOT.TDAVCONDDIAGCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_DAV_COND_DIAG',CENVDAVCONDDIAG)
        TDAVCONDDIAG=(LEN_TRIM(CENVDAVCONDDIAG).GT.0)
        TDAVCONDDIAGCHECKED=.TRUE.
        IF(TDAVCONDDIAG) THEN
          PRINT*,'VESPAW_DAV_COND_DIAG SET -- PRINTING SUBEPS SPREAD AND' &
     &          ,' SUBO CONDITION NUMBER EACH DAVIDSON SWEEP'
        END IF
      END IF
      IF(TDAVCONDDIAG) DAVCONDDIAGCALL=DAVCONDDIAGCALL+1
      IF(.NOT.TSUBOREGCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_DAV_SUBO_REG',CENVSUBOREG)
        IF(LEN_TRIM(CENVSUBOREG).GT.0) READ(CENVSUBOREG,*) SUBOREGFAC
        TSUBOREGCHECKED=.TRUE.
        IF(LEN_TRIM(CENVSUBOREG).GT.0) THEN
          PRINT*,'VESPAW_DAV_SUBO_REG SET -- SUBO TIKHONOV FACTOR=',SUBOREGFAC
        END IF
      END IF
      TCONV=.FALSE.
      IF(NB.LT.1) RETURN
!
!     ==================================================================
!     == STORAGE (2026-09-27): SEVEN WAVE-FUNCTION-SIZED ARRAYS OF NB  ==
!     == COLUMNS, DOWN FROM TWENTY-THREE (SI216: 16.5 GB FOOTPRINT).   ==
!     ==   PB,HB,OB,PRB: BAND PSI, H|PSI>, O|PSI>, <P|PSI>.  ACTIVE     ==
!     ==     (SURVIVING) BANDS IN COLUMNS 1:NACT, LOCKED BANDS IN      ==
!     ==     COLUMNS LB:NB (LB=NB-NLOCK+1); NACT+NLOCK<=NB ALWAYS.     ==
!     ==   D,HD,OD,PD: CORRECTION VECTORS AND THEIR H/O IMAGES.        ==
!     ==   W: SCRATCH (RESIDUALS, TRANSFORMS, NEW RITZ VECTORS).       ==
!     == THE EXTENDED BASIS [PB(1:NACT),D(1:NGOOD)] IS NEVER COPIED   ==
!     == INTO ONE ARRAY; SUBH/SUBO ARE ASSEMBLED BLOCKWISE.            ==
!     ==================================================================
      NG=NGL*NDIM
      ALLOCATE(PB(NGL,NDIM,NB),HB(NGL,NDIM,NB),OB(NGL,NDIM,NB))
      ALLOCATE(D(NGL,NDIM,NB),HD(NGL,NDIM,NB),OD(NGL,NDIM,NB))
      ALLOCATE(W(NGL,NDIM,NB))
      ALLOCATE(PRB(NDIM,NB,NPRO),PD(NDIM,NB,NPRO),PWORK(NDIM,NB,NPRO))
      ALLOCATE(EPSACT(NB),RNORMACT(NB))
      ALLOCATE(SUBH(2*NB,2*NB),SUBO(2*NB,2*NB),SUBVEC(2*NB,2*NB))
      ALLOCATE(SUBEPS(2*NB))
      ALLOCATE(RNORMMAT(NB,NB),SLOCK(NB,NB),SACT(NB,NB))
      ALLOCATE(GMAT(NB,NB),GVEC(NB,NB),TMAT(NB,NB),CMAT(NB,NB))
      ALLOCATE(GEIG(NB),DNORM0(NB),DSCALE(NB))
!
!     == SEED EPS WITH A REAL RAYLEIGH-RITZ ESTIMATE FROM PSI ALONE BEFORE ==
!     == THE FIRST RESIDUAL IS EVER COMPUTED. ON THE VERY FIRST CALL, EPS  ==
!     == ARRIVES AS THE PLACEHOLDER 1.D100 (SEEDED BY WAVES$KAESTNERCG1    ==
!     == FOR THE CG PATH). USING THAT DIRECTLY IN RESID=HPSI-EPS*OPSI      ==
!     == PRODUCES A RESIDUAL, AND HENCE A PRECONDITIONED CORRECTION        ==
!     == VECTOR, ~1.D100 IN MAGNITUDE -- WHICH MAKES SUBH/SUBO SPAN ~200   ==
!     == ORDERS OF MAGNITUDE, CATASTROPHICALLY ILL-CONDITIONING THE        ==
!     == GENERALIZED EIGENPROBLEM.                                        ==
      CALL CG_SUBSPACEROTATE(NGL,NDIM,NB,NB,NPRO,R0,PSI,PROJ,EPS)

      NLOCK=0
      NACT=NB
      DO IB=1,NB
        IACT(IB)=IB
      END DO

      DO ISWEEP=1,NSWEEPX
        IF(NACT.EQ.0) THEN
          TCONV=.TRUE.
          EXIT
        END IF
        LB=NB-NLOCK+1
!
!       == GATHER THE CURRENT ACTIVE SET (POSSIBLY SCATTERED ORIGINAL     ==
!       == SLOTS) INTO CONTIGUOUS WORK COLUMNS 1:NACT.                    ==
        DO K=1,NACT
          PB(:,:,K)=PSI(:,:,IACT(K))
          PRB(:,K,:)=PROJ(:,IACT(K),:)
          EPSACT(K)=EPS(IACT(K))
        END DO
!
!       == APPLY H AND O TO THE ACTIVE SET ONLY -- THIS (AND THE          ==
!       == CORRECTION-VECTOR STEP BELOW) IS WHERE LOCKING SHRINKS THE     ==
!       == PER-SWEEP COST AS BANDS CONVERGE.                              ==
        CALL WAVES_HPSI(MAP,GSET,ISPIN,NGL,NDIM,NDIMD,NACT,NPRO,LMNXX,NAT &
       &                ,NRL,PB(:,:,1:NACT),V(1,ISPIN),R0 &
       &                ,PRB(:,1:NACT,:),DH,HB(:,:,1:NACT))
        OB(:,:,1:NACT)=PB(:,:,1:NACT)
        CALL WAVES_OPSI(NACT,NACT,NPRO,NAT,NGL,R0,PRB(:,1:NACT,:) &
     &                  ,OB(:,:,1:NACT))
!
!       == RESIDUALS (IN W) AND THEIR NORMS ================================
        DO K=1,NACT
          W(:,:,K)=HB(:,:,K)-CMPLX(EPSACT(K),0.D0,KIND=8)*OB(:,:,K)
          CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,1,W(:,:,K),1,W(:,:,K) &
     &                                ,CSCAL)
          CALL MPE$COMBINE('K','+',CSCAL)
          RNORMACT(K)=SQRT(MAX(REAL(CSCAL(1,1),KIND=8),0.D0))
        END DO
!
!       == LOCK EVERY ACTIVE BAND THAT JUST DROPPED BELOW CONV: FREEZE IT  ==
!       == (ITS PSI/EPS/PROJ ARE ALREADY CORRECT IN THE MAIN ARRAYS),      ==
!       == KEEP ITS H/O IMAGES (THEY CAN NEVER CHANGE AGAIN), AND DROP IT  ==
!       == FROM THE ACTIVE SET. THE SURVIVING BANDS' PRECONDITIONED        ==
!       == RESIDUALS GO TO D(1:NSURV) IN THE SAME PASS.                    ==
        NACTOLD=NACT
        IACTOLD(1:NACTOLD)=IACT(1:NACTOLD)
        NSURV=0
        NNEW=0
        DO K=1,NACTOLD
!         == EFFECTIVE TOLERANCE FOR THIS BAND, SCALED BY ITS OCCUPATION  ==
!         == WEIGHT VIA A SMOOTH LINEAR RAMP -- SEE THE OCCUPATION-       ==
!         == WEIGHTED LOCKING PARAGRAPH IN THE HEADER COMMENT.            ==
          FEFF=FWEIGHTFLOOR+F(IACTOLD(K))*(1.D0-FWEIGHTFLOOR)
          EFFCONV=CONV/FEFF
          TLOCKNOW(K)=(RNORMACT(K).LT.EFFCONV)
          IF(TLOCKNOW(K)) THEN
            NNEW=NNEW+1
          ELSE
            NSURV=NSURV+1
!           == PRECONDITION (TETER/KRESSE) INTO D, COMPACTED ===============
            DO IDIMP=1,NDIM
              CALL CG_PRECONDITION_FULL(NGL,G2,PB(:,IDIMP,K),W(:,IDIMP,K) &
     &                                 ,D(:,IDIMP,NSURV))
            ENDDO
          END IF
        END DO
!       == STAGE THE NEW LOCKS' H/O IMAGES (W IS FREE NOW; D HAS NNEW     ==
!       == FREE COLUMNS BEHIND THE NSURV CORRECTIONS) BEFORE COMPACTION   ==
!       == MAY OVERWRITE THEM.                                            ==
        J=0
        DO K=1,NACTOLD
          IF(.NOT.TLOCKNOW(K)) CYCLE
          J=J+1
          W(:,:,J)=HB(:,:,K)
          D(:,:,NSURV+J)=OB(:,:,K)
          LOCKIDX(NLOCK+J)=IACTOLD(K)
        END DO
!       == COMPACT THE SURVIVORS TO THE FRONT (IN PLACE, NEVER OVERWRITES ==
!       == A SURVIVOR THAT HAS NOT BEEN MOVED YET)                        ==
        IS=0
        DO K=1,NACTOLD
          IF(TLOCKNOW(K)) CYCLE
          IS=IS+1
          IACT(IS)=IACTOLD(K)
          IF(IS.EQ.K) CYCLE
          PB(:,:,IS)=PB(:,:,K)
          HB(:,:,IS)=HB(:,:,K)
          OB(:,:,IS)=OB(:,:,K)
          PRB(:,IS,:)=PRB(:,K,:)
        END DO
!       == PLACE THE NEW LOCKS BEHIND THE OLD ONES: LOCK NUMBER L LIVES IN ==
!       == COLUMN NB-L+1. PSI AND PROJ COME FROM THE FROZEN MAIN ARRAYS.   ==
        DO J=1,NNEW
          IC=NB-(NLOCK+J)+1
          HB(:,:,IC)=W(:,:,J)
          OB(:,:,IC)=D(:,:,NSURV+J)
          PB(:,:,IC)=PSI(:,:,LOCKIDX(NLOCK+J))
          PRB(:,IC,:)=PROJ(:,LOCKIDX(NLOCK+J),:)
        END DO
        NLOCK=NLOCK+NNEW
        LB=NB-NLOCK+1
        NACT=NSURV
        IF(NACT.EQ.0) THEN
          TCONV=.TRUE.
          EXIT
        END IF
!
!       == H AND O ON THE CORRECTION VECTORS ===============================
        CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NACT,NPRO &
     &                         ,D(:,:,1:NACT),PD(:,1:NACT,:))
        CALL WAVES_HPSI(MAP,GSET,ISPIN,NGL,NDIM,NDIMD,NACT,NPRO,LMNXX,NAT &
       &                ,NRL,D(:,:,1:NACT),V(1,ISPIN),R0 &
       &                ,PD(:,1:NACT,:),DH,HD(:,:,1:NACT))
        OD(:,:,1:NACT)=D(:,:,1:NACT)
        CALL WAVES_OPSI(NACT,NACT,NPRO,NAT,NGL,R0,PD(:,1:NACT,:) &
     &                  ,OD(:,:,1:NACT))
!       == NORMS BEFORE ANY PROJECTION, TO DETECT CANCELLATION BELOW ======
        DO K=1,NACT
          CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,1,D(:,:,K),1 &
     &              ,OD(:,:,K),CSCAL)
          CALL MPE$COMBINE('K','+',CSCAL)
          DNORM0(K)=MAX(REAL(CSCAL(1,1),KIND=8),0.D0)
        END DO
!
!       ================================================================
!       == ROBUST SUBSPACE (2026-09-23): O-ORTHOGONALIZE THE CORRECTION ==
!       == VECTORS AGAINST EVERY CURRENT BAND -- LOCKED *AND* ACTIVE --  ==
!       == TWICE ("TWICE IS ENOUGH" GRAM-SCHMIDT), THEN AMONG            ==
!       == THEMSELVES BY CANONICAL ORTHOGONALIZATION. THE EXTENDED BASIS ==
!       == [PSI_ACTIVE,D] IS THEN O-ORTHONORMAL BY CONSTRUCTION, SO THE  ==
!       == RAYLEIGH-RITZ PROBLEM NEEDS NO REGULARIZATION AND ITS RESULT  ==
!       == IS O-ORTHONORMAL. BEFORE, DELTA WAS ONLY ORTHOGONALIZED       ==
!       == AGAINST LOCKED BANDS; THE NEARLY SINGULAR OVERLAP THAT LEFT   ==
!       == WAS PATCHED WITH A TIKHONOV SHIFT (WHICH DISTORTS THE         ==
!       == EIGENPROBLEM: ORBITALS NO LONGER O-ORTHONORMAL, ENERGIES      ==
!       == BELOW THE MINIMUM, SPLIT DEGENERACIES) AND AN ABSOLUTE 0.05   ==
!       == RESIDUAL-NORM DEFLATION (WHICH STOPPED ALL REFINEMENT BELOW   ==
!       == THAT RESIDUAL AND TRAPPED COLD STARTS IN EXCITED STATES).     ==
!       ================================================================
        DO IPASS=1,2
          IF(NLOCK.GT.0) THEN
            CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NLOCK,PB(:,:,LB:NB) &
       &              ,NACT,OD(:,:,1:NACT),SLOCK(1:NLOCK,1:NACT))
            CALL MPE$COMBINE('K','+',SLOCK(1:NLOCK,1:NACT))
            CALL DAVIDSON_SUBTRACT(NG,NLOCK,NACT,SLOCK(1:NLOCK,1:NACT) &
       &              ,PB(:,:,LB:NB),HB(:,:,LB:NB),OB(:,:,LB:NB) &
       &              ,D(:,:,1:NACT),HD(:,:,1:NACT),OD(:,:,1:NACT))
            DO K=1,NACT
              DO IC=1,NLOCK
                PD(:,K,:)=PD(:,K,:)-PRB(:,LB+IC-1,:)*SLOCK(IC,K)
              END DO
            END DO
          END IF
          CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NACT,PB(:,:,1:NACT) &
     &              ,NACT,OD(:,:,1:NACT),SACT(1:NACT,1:NACT))
          CALL MPE$COMBINE('K','+',SACT(1:NACT,1:NACT))
          CALL DAVIDSON_SUBTRACT(NG,NACT,NACT,SACT(1:NACT,1:NACT) &
       &            ,PB(:,:,1:NACT),HB(:,:,1:NACT),OB(:,:,1:NACT) &
       &            ,D(:,:,1:NACT),HD(:,:,1:NACT),OD(:,:,1:NACT))
          DO K=1,NACT
            DO IC=1,NACT
              PD(:,K,:)=PD(:,K,:)-PRB(:,IC,:)*SACT(IC,K)
            END DO
          END DO
        END DO
!
!       == NORMALIZE; DROP DIRECTIONS THAT CANCELLED ALMOST COMPLETELY   ==
!       == (WHAT IS LEFT OF THEM IS ROUNDING NOISE, NOT A DIRECTION)     ==
        CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NACT,D(:,:,1:NACT) &
     &            ,NACT,OD(:,:,1:NACT),RNORMMAT(1:NACT,1:NACT))
        CALL MPE$COMBINE('K','+',RNORMMAT(1:NACT,1:NACT))
        NGOOD=0
        DO IC=1,NACT
          SVARN=REAL(RNORMMAT(IC,IC),KIND=8)
          IF(SVARN.LE.DCANCEL*DNORM0(IC).OR.SVARN.LE.1.D-30) CYCLE
          NGOOD=NGOOD+1
          GOODIDX(NGOOD)=IC
          DSCALE(NGOOD)=1.D0/SQRT(SVARN)
        END DO
!       == CANONICAL ORTHOGONALIZATION OF THE NORMALIZED DIRECTIONS:     ==
!       == G=D^H O D (UNIT DIAGONAL) = U E U^H; KEEP E>ECANON; D<-D U E^-1/2
        NKEEP=0
        IF(NGOOD.GT.0) THEN
          DO K=1,NGOOD
            DO IC=1,NGOOD
              GMAT(IC,K)=RNORMMAT(GOODIDX(IC),GOODIDX(K))*DSCALE(IC)*DSCALE(K)
            END DO
          END DO
          GMAT(1:NGOOD,1:NGOOD)=0.5D0*(GMAT(1:NGOOD,1:NGOOD) &
     &                   +CONJG(TRANSPOSE(GMAT(1:NGOOD,1:NGOOD))))
          IF(TREALSUB) GMAT(1:NGOOD,1:NGOOD) &
     &        =CMPLX(REAL(GMAT(1:NGOOD,1:NGOOD),KIND=8),0.D0,KIND=8)
          CALL LIB$DIAGC8(NGOOD,GMAT(1:NGOOD,1:NGOOD),GEIG(1:NGOOD) &
     &                   ,GVEC(1:NGOOD,1:NGOOD))
!         == TRANSFORMATION IN TERMS OF ALL NACT COLUMNS (ZERO ROWS FOR   ==
!         == THE DROPPED DIRECTIONS), SO THAT IT IS ONE MATRIX PRODUCT    ==
          CMAT(1:NACT,1:NACT)=(0.D0,0.D0)
          DO K=1,NGOOD
            IF(GEIG(K).LE.ECANON) CYCLE
            NKEEP=NKEEP+1
            DO IC=1,NGOOD
              CMAT(GOODIDX(IC),NKEEP)=GVEC(IC,K)*DSCALE(IC)/SQRT(GEIG(K))
            END DO
          END DO
        END IF
        NGOOD=NKEEP
        IF(NGOOD.GT.0) THEN
          TMAT(1:NACT,1:NGOOD)=CMAT(1:NACT,1:NGOOD)
          CALL DAVIDSON_TRANSFORM(NG,NACT,NGOOD,TMAT(1:NACT,1:NGOOD) &
       &                          ,D(:,:,1:NACT),W(:,:,1:NGOOD))
          CALL DAVIDSON_TRANSFORM(NG,NACT,NGOOD,TMAT(1:NACT,1:NGOOD) &
       &                          ,HD(:,:,1:NACT),W(:,:,1:NGOOD))
          CALL DAVIDSON_TRANSFORM(NG,NACT,NGOOD,TMAT(1:NACT,1:NGOOD) &
       &                          ,OD(:,:,1:NACT),W(:,:,1:NGOOD))
          DO K=1,NGOOD
            PWORK(:,K,:)=(0.D0,0.D0)
            DO IC=1,NACT
              PWORK(:,K,:)=PWORK(:,K,:)+PD(:,IC,:)*TMAT(IC,K)
            END DO
          END DO
          PD(:,1:NGOOD,:)=PWORK(:,1:NGOOD,:)
        END IF
!
!       == RAYLEIGH-RITZ IN THE BASIS [PB(1:NACT),D(1:NGOOD)], ASSEMBLED ==
!       == BLOCKWISE                                                     ==
        NTOT=NACT+NGOOD
        CALL DAVIDSON_SUBMATRIX(NGL,NDIM,NACT,NGOOD,PB(:,:,1:NACT) &
     &          ,D(:,:,1:MAX(NGOOD,1)),HB(:,:,1:NACT),HD(:,:,1:MAX(NGOOD,1)) &
     &          ,SUBH(1:NTOT,1:NTOT))
        CALL DAVIDSON_SUBMATRIX(NGL,NDIM,NACT,NGOOD,PB(:,:,1:NACT) &
     &          ,D(:,:,1:MAX(NGOOD,1)),OB(:,:,1:NACT),OD(:,:,1:MAX(NGOOD,1)) &
     &          ,SUBO(1:NTOT,1:NTOT))

        SUBH(1:NTOT,1:NTOT)=0.5D0*(SUBH(1:NTOT,1:NTOT) &
     &                            +CONJG(TRANSPOSE(SUBH(1:NTOT,1:NTOT))))
        SUBO(1:NTOT,1:NTOT)=0.5D0*(SUBO(1:NTOT,1:NTOT) &
     &                            +CONJG(TRANSPOSE(SUBO(1:NTOT,1:NTOT))))
        IF(TREALSUB) THEN
          SUBH(1:NTOT,1:NTOT)=CMPLX(REAL(SUBH(1:NTOT,1:NTOT),KIND=8),0.D0,KIND=8)
          SUBO(1:NTOT,1:NTOT)=CMPLX(REAL(SUBO(1:NTOT,1:NTOT),KIND=8),0.D0,KIND=8)
        END IF
!       == OPTIONAL TIKHONOV REGULARIZATION (OFF BY DEFAULT) ==============
        REGVAR=0.D0
        DO IB=1,NTOT
          REGVAR=REGVAR+REAL(SUBO(IB,IB),KIND=8)
        END DO
        REGVAR=REGVAR/REAL(NTOT,KIND=8)*SUBOREGFAC
        IF(REGVAR.GT.0.D0) THEN
          DO IB=1,NTOT
            SUBO(IB,IB)=SUBO(IB,IB)+CMPLX(REGVAR,0.D0,KIND=8)
          END DO
        END IF

        CALL LIB$GENERALEIGENVALUEC8(NTOT,SUBH(1:NTOT,1:NTOT) &
     &            ,SUBO(1:NTOT,1:NTOT),SUBEPS(1:NTOT),SUBVEC(1:NTOT,1:NTOT))

        IF(TDAVCONDDIAG) THEN
!         == SUBO'S OWN EIGENVALUES (CONDITION NUMBER OF THE TRIAL BASIS'   ==
!         == OVERLAP MATRIX). SUBO WAS OVERWRITTEN BY THE SOLVER, SO IT IS  ==
!         == REBUILT HERE (DIAGNOSTIC ONLY).                                ==
          CALL DAVIDSON_SUBMATRIX(NGL,NDIM,NACT,NGOOD,PB(:,:,1:NACT) &
     &          ,D(:,:,1:MAX(NGOOD,1)),OB(:,:,1:NACT),OD(:,:,1:MAX(NGOOD,1)) &
     &          ,SUBO(1:NTOT,1:NTOT))
          ALLOCATE(SOIDENT(NTOT,NTOT));ALLOCATE(SOVEC(NTOT,NTOT))
          ALLOCATE(SOEIG(NTOT))
          SOIDENT=(0.D0,0.D0)
          DO IB=1,NTOT
            SOIDENT(IB,IB)=(1.D0,0.D0)
          END DO
          CALL LIB$GENERALEIGENVALUEC8(NTOT,SUBO(1:NTOT,1:NTOT),SOIDENT &
     &                                 ,SOEIG,SOVEC)
          PRINT*,'VESPAW_DAV_COND_DIAG CALL=',DAVCONDDIAGCALL &
     &          ,' SWEEP=',ISWEEP,' NTOT=',NTOT &
     &          ,' SUBEPS_MIN=',MINVAL(SUBEPS(1:NTOT)) &
     &          ,' SUBEPS_MAX=',MAXVAL(SUBEPS(1:NTOT)) &
     &          ,' SUBO_COND=',MAXVAL(SOEIG)/MAX(MINVAL(SOEIG),1.D-300)
          DEALLOCATE(SOIDENT,SOVEC,SOEIG)
        END IF
!
!       == RAYLEIGH-RITZ CONTRACTION BACK TO NACT: THE LOWEST NACT        ==
!       == EIGENPAIRS BECOME THE NEW ACTIVE BANDS, SCATTERED BACK INTO    ==
!       == THEIR ORIGINAL BAND SLOTS (IACT) OF THE MAIN ARRAYS.           ==
        TMAT(1:NACT,1:NACT)=SUBVEC(1:NACT,1:NACT)
        CALL LIB$MATMULC8(NG,NACT,NACT,PB(:,:,1:NACT),TMAT(1:NACT,1:NACT) &
     &                   ,W(:,:,1:NACT))
        IF(NGOOD.GT.0) THEN
          CMAT(1:NGOOD,1:NACT)=SUBVEC(NACT+1:NTOT,1:NACT)
          CALL LIB$ADDPRODUCTC8(.FALSE.,NG,NGOOD,NACT,D(:,:,1:NGOOD) &
     &                         ,CMAT(1:NGOOD,1:NACT),W(:,:,1:NACT))
        END IF
        DO K=1,NACT
          PWORK(:,K,:)=(0.D0,0.D0)
          DO IC=1,NACT
            PWORK(:,K,:)=PWORK(:,K,:)+PRB(:,IC,:)*SUBVEC(IC,K)
          END DO
          DO IC=1,NGOOD
            PWORK(:,K,:)=PWORK(:,K,:)+PD(:,IC,:)*SUBVEC(NACT+IC,K)
          END DO
        END DO
        DO K=1,NACT
          PSI(:,:,IACT(K))=W(:,:,K)
          PROJ(:,IACT(K),:)=PWORK(:,K,:)
          EPS(IACT(K))=SUBEPS(K)
        END DO
      END DO

      DEALLOCATE(PB,HB,OB,D,HD,OD,W,PRB,PD,PWORK)
      DEALLOCATE(EPSACT,RNORMACT)
      DEALLOCATE(SUBH,SUBO,SUBVEC,SUBEPS)
      DEALLOCATE(RNORMMAT,SLOCK,SACT,GMAT,GVEC,TMAT,CMAT,GEIG,DNORM0,DSCALE)
      RETURN
      END SUBROUTINE DAVIDSON_BLOCK_SWEEP
!
!     ...1.........2.........3.........4.........5.........6.........7.........8
      SUBROUTINE DAVIDSON_SUBTRACT(NG,NB1,NB2,S,P,HP,OP,D,HD,OD)
!     ******************************************************************
!     ** D <- D - P*S, AND THE SAME FOR THE H AND O IMAGES             **
!     ** (P: NB1 VECTORS, D: NB2 VECTORS, S: NB1 X NB2)                **
!     ******************************************************************
      IMPLICIT NONE
      INTEGER(4),INTENT(IN)    :: NG,NB1,NB2
      COMPLEX(8),INTENT(IN)    :: S(NB1,NB2)
      COMPLEX(8),INTENT(IN)    :: P(NG,NB1),HP(NG,NB1),OP(NG,NB1)
      COMPLEX(8),INTENT(INOUT) :: D(NG,NB2),HD(NG,NB2),OD(NG,NB2)
      COMPLEX(8),ALLOCATABLE   :: MS(:,:)
!     ******************************************************************
      IF(NB1.LT.1.OR.NB2.LT.1) RETURN
      ALLOCATE(MS(NB1,NB2))
      MS(:,:)=-S(:,:)
      CALL LIB$ADDPRODUCTC8(.FALSE.,NG,NB1,NB2,P,MS,D)
      CALL LIB$ADDPRODUCTC8(.FALSE.,NG,NB1,NB2,HP,MS,HD)
      CALL LIB$ADDPRODUCTC8(.FALSE.,NG,NB1,NB2,OP,MS,OD)
      DEALLOCATE(MS)
      RETURN
      END SUBROUTINE DAVIDSON_SUBTRACT
!
!     ...1.........2.........3.........4.........5.........6.........7.........8
      SUBROUTINE DAVIDSON_TRANSFORM(NG,NB1,NB2,T,X,WORK)
!     ******************************************************************
!     ** X(:,1:NB2) <- X(:,1:NB1)*T, USING WORK AS SCRATCH (NB2<=NB1)  **
!     ******************************************************************
      IMPLICIT NONE
      INTEGER(4),INTENT(IN)    :: NG,NB1,NB2
      COMPLEX(8),INTENT(IN)    :: T(NB1,NB2)
      COMPLEX(8),INTENT(INOUT) :: X(NG,NB1)
      COMPLEX(8),INTENT(OUT)   :: WORK(NG,NB2)
!     ******************************************************************
      CALL LIB$MATMULC8(NG,NB1,NB2,X,T,WORK)
      X(:,1:NB2)=WORK(:,:)
      RETURN
      END SUBROUTINE DAVIDSON_TRANSFORM
!
!     ...1.........2.........3.........4.........5.........6.........7.........8
      SUBROUTINE DAVIDSON_SUBMATRIX(NGL,NDIM,NA,ND,PA,PD,XA,XD,SUB)
!     ******************************************************************
!     ** SUB=<[PA,PD]|[XA,XD]> ASSEMBLED FROM FOUR BLOCKS, WHERE X IS  **
!     ** H|PSI> OR O|PSI> OF THE EXTENDED BASIS [PA(1:NA),PD(1:ND)]    **
!     ******************************************************************
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN)  :: NGL,NDIM,NA,ND
      COMPLEX(8),INTENT(IN)  :: PA(NGL,NDIM,NA),XA(NGL,NDIM,NA)
      COMPLEX(8),INTENT(IN)  :: PD(NGL,NDIM,*),XD(NGL,NDIM,*)
      COMPLEX(8),INTENT(OUT) :: SUB(NA+ND,NA+ND)
      COMPLEX(8),ALLOCATABLE :: BLK(:,:)
!     ******************************************************************
      ALLOCATE(BLK(NA+ND,NA+ND))
      CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NA,PA,NA,XA,BLK(1:NA,1:NA))
      SUB(1:NA,1:NA)=BLK(1:NA,1:NA)
      IF(ND.GT.0) THEN
        CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NA,PA,ND,XD(:,:,1:ND) &
     &                              ,BLK(1:NA,1:ND))
        SUB(1:NA,NA+1:NA+ND)=BLK(1:NA,1:ND)
        CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,ND,PD(:,:,1:ND),NA,XA &
     &                              ,BLK(1:ND,1:NA))
        SUB(NA+1:NA+ND,1:NA)=BLK(1:ND,1:NA)
        CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,ND,PD(:,:,1:ND),ND &
     &                              ,XD(:,:,1:ND),BLK(1:ND,1:ND))
        SUB(NA+1:NA+ND,NA+1:NA+ND)=BLK(1:ND,1:ND)
      END IF
      CALL MPE$COMBINE('K','+',SUB)
      DEALLOCATE(BLK)
      RETURN
      END SUBROUTINE DAVIDSON_SUBMATRIX
!
!     ..................................................................
      SUBROUTINE RMM$STATE_BY_BLOCK(NRL_,NDIMD_,V_,CONV,NAT_,LMNXX_,DH_)
!     ******************************************************************
!     ** INTERFACE SUBROUTINE FOR THE RMM-DIIS DIAGONALIZER. MIRRORS     **
!     ** DAVIDSON$STATE_BY_BLOCK'S SETUP/LOOP/SUPER-WAVE-FUNCTION        **
!     ** UNPACK-REPACK STRUCTURE EXACTLY; ONLY THE INNER DIAGONALIZER    **
!     ** DIFFERS (RMM_DIIS_BLOCK_SWEEP INSTEAD OF DAVIDSON_BLOCK_SWEEP). **
!     ******************************************************************
      USE CG_INTERFACE_MODULE
      USE WAVES_MODULE
      IMPLICIT NONE
      INTEGER(4)   , INTENT(IN)   :: NRL_
      INTEGER(4)   , INTENT(IN)   :: NDIMD_
      REAL(8)      , INTENT(IN)   :: V_(NRL_,NDIMD_)
      REAL(8)      , INTENT(INOUT)   :: CONV
      INTEGER(4)   , INTENT(IN)   :: NAT_
      INTEGER(4)   , INTENT(IN)   :: LMNXX_
      COMPLEX(8)   , INTENT(IN)   :: DH_(LMNXX_,LMNXX_,NDIMD_,NAT_)
      LOGICAL(4)                  :: TCONV
      INTEGER(4)                  :: NGL,NB,NBH,NPRO
      INTEGER(4)                  :: NRMMX
      REAL(8)     ,ALLOCATABLE    :: G2(:) ! (NGL)
      REAL(8)     ,ALLOCATABLE    :: R0(:,:)
      COMPLEX(8)  ,ALLOCATABLE    :: PSIU(:,:,:)  ! (NGL,NDIM,NB) UNPACKED
      COMPLEX(8)  ,ALLOCATABLE    :: PROJU(:,:,:) ! (NDIM,NB,NPRO) UNPACKED
      LOGICAL(4)                  :: TDEBUG  ! !CONTROL!GENERIC VERBOSITY='DEBUG'
!     ******************************************************************
      CALL VERBOSITY$GETL4('DEBUG',TDEBUG)
      IF(NDIM.NE.1) THEN
         CALL ERROR$I4VAL('NDIMD',NDIMD)
         CALL ERROR$MSG('NON-COLLINEAR RMM-DIIS NOT IMPLEMENTED')
         CALL ERROR$STOP('RMM$STATE_BY_BLOCK')
      END IF
      NAT=NAT_
      LMNXX=LMNXX_
      ALLOCATE(DH(LMNXX,LMNXX,NDIMD,NAT))
      DH=DH_
      NPRO=MAP%NPRO
      NRL=NRL_
      ALLOCATE(V(NRL,NDIMD_))
      V=V_
      NRMMX=RMMNRMMX  ! SET VIA !PSIDYN NRMMX=... (DEFAULT 4), SEE paw_ioroutines.f90
      DO IKPT=1,NKPTL   ! LOCAL K-POINTS (MPI K-PARALLELIZATION)
         DO ISPIN=1,NSPIN
            CALL WAVES_SELECTWV(IKPT,ISPIN)
            CALL PLANEWAVE$SELECT(GSET%ID)
            NGL=GSET%NGL
            NBH=THIS%NBH
            NB=THIS%NB
            IF(ALLOCATED(G2)) DEALLOCATE(G2)
            ALLOCATE(G2(NGL))
            CALL PLANEWAVE$GETR8A('G2',NGL,G2)

            ALLOCATE(R0(3,NAT))
            CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,R0)
!           == SUPER-WAVE-FUNCTION SUPPORT: SEE CG$STATE_BY_STATE FOR THE   ==
!           == FULL RATIONALE -- UNPACK ONCE, RUN ON GENUINE SINGLE-BAND   ==
!           == ARRAYS, REPACK BEFORE RETURNING.                            ==
            ALLOCATE(PSIU(NGL,NDIM,NB))
            ALLOCATE(PROJU(NDIM,NB,NPRO))
            TREALSUB=(NB.NE.NBH)
            IF(NB.EQ.NBH) THEN
               PSIU=THIS%PSI0
            ELSE
               CALL CG_UNPACKSUPER(NGL,NDIM,NB,NBH,THIS%PSI0,PSIU)
            END IF
            CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NB,MAP%NPRO &
                ,PSIU,PROJU)

            CALL TIMING$CLOCKON('RMM-SWEEP')
            CALL RMM_DIIS_BLOCK_SWEEP(NGL,NB,NDIM,NPRO,CONV,NRMMX,G2,R0 &
                ,THIS%EIGVAL,PSIU,PROJU,TCONV)
            CALL TIMING$CLOCKOFF('RMM-SWEEP')

            IF(NB.EQ.NBH) THEN
               THIS%PSI0=PSIU
            ELSE
               CALL CG_PACKSUPER(NGL,NDIM,NB,NBH,PSIU,THIS%PSI0)
            END IF
            CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NBH,MAP%NPRO &
                ,THIS%PSI0,THIS%PROJ)
            DEALLOCATE(R0)
            DEALLOCATE(PSIU)
            DEALLOCATE(PROJU)
         END DO
      END DO
      DEALLOCATE(DH)
      DEALLOCATE(V)
      IF(TDEBUG) THEN
        PRINT*,'RMM-DIIS FINISHED !!'
        PRINT*,'RMM-DIIS EPS:',THIS%EIGVAL*27.211386245988D0
      END IF
      IF(.NOT.TCONV) THEN
!        == NOT FATAL: SEE THE SAME REASONING IN CG$STATE_BY_STATE/         ==
!        == DAVIDSON$STATE_BY_BLOCK -- THE MIXER'S OWN TCONV GOVERNS THE    ==
!        == OUTER-LOOP CONVERGENCE.                                        ==
        IF(TDEBUG) PRINT*, &
     &    'RMM-DIIS BLOCK NOT CONVERGED -- CONTINUING TO NEXT OUTER ITERATION'
      END IF
      END SUBROUTINE RMM$STATE_BY_BLOCK
!
!     ..................................................................
      SUBROUTINE RMM_DIIS_BLOCK_SWEEP(NGL,NB,NDIM,NPRO,CONV,NRMMX,G2,R0 &
     &                                ,EPS,PSI,PROJ,TCONV)
!     ******************************************************************
!     ** RMM-DIIS (RESIDUAL MINIMIZATION METHOD -- DIRECT INVERSION IN   **
!     ** THE ITERATIVE SUBSPACE) DIAGONALIZER (KRESSE & FURTHMUELLER,    **
!     ** COMP. MATER. SCI. 6, 15 (1996)). EACH BAND IS REFINED           **
!     ** INDEPENDENTLY VIA DIIS EXTRAPOLATION OVER ITS OWN HISTORY OF    **
!     ** TRIAL VECTORS/RESIDUALS (SAME CLOSED-FORM COEFFICIENT SOLVE     **
!     ** ALREADY USED BY THE PULAY DENSITY MIXER IN PAW_MIXER.F90:       **
!     ** C=AINV*1/(1^T*AINV*1), SEE RMM_DIIS_COEFF BELOW) -- BUT THE      **
!     ** EXPENSIVE H/O OPERATOR APPLICATIONS ARE BATCHED ACROSS ALL       **
!     ** STILL-ACTIVE BANDS AT EVERY DIIS ITERATION (WAVES_HPSI/         **
!     ** WAVES_OPSI CALLED ONCE PER ITERATION, NOT ONCE PER BAND), THE    **
!     ** SAME DISCIPLINE DAVIDSON_BLOCK_SWEEP USES -- THE PER-BAND DIIS   **
!     ** COEFFICIENT SOLVE ITSELF IS A TINY (<=NRMMX+1)-SIZED LINEAR      **
!     ** SYSTEM AND IS NOT WHERE THE COST LIVES. AFTER ALL BANDS FINISH   **
!     ** THEIR (INDEPENDENT, GENERALLY NON-ORTHOGONAL) REFINEMENT, A      **
!     ** SINGLE CG_SUBSPACEROTATE CALL (ALREADY VALIDATED, REUSED         **
!     ** DIRECTLY) RAYLEIGH-RITZES THEM BACK INTO A PROPER ORTHONORMAL,   **
!     ** ENERGY-ORDERED SET.                                              **
!     ******************************************************************
      USE CG_INTERFACE_MODULE, ONLY: NAT,LMNXX,DH,NRL,V,ISPIN
      USE WAVES_MODULE, ONLY: MAP,GSET,NDIMD
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN)    :: NGL
      INTEGER(4),INTENT(IN)    :: NB
      INTEGER(4),INTENT(IN)    :: NDIM
      INTEGER(4),INTENT(IN)    :: NPRO
      REAL(8)   ,INTENT(IN)    :: CONV
      INTEGER(4),INTENT(IN)    :: NRMMX
      REAL(8)   ,INTENT(IN)    :: G2(NGL)
      REAL(8)   ,INTENT(IN)    :: R0(3,NAT)
      REAL(8)   ,INTENT(INOUT) :: EPS(NB)
      COMPLEX(8),INTENT(INOUT) :: PSI(NGL,NDIM,NB)
      COMPLEX(8),INTENT(INOUT) :: PROJ(NDIM,NB,NPRO)
      LOGICAL(4),INTENT(OUT)   :: TCONV
      INTEGER(4),PARAMETER     :: NSIMX=32  ! BANDS PER BLOCK
      INTEGER(4)               :: NHISTX,NSIM,NBL,IB0,L
      INTEGER(4)               :: ITER,IH,K
      INTEGER(4) ,ALLOCATABLE  :: NHIST(:)
      LOGICAL(4) ,ALLOCATABLE  :: TACTIVE(:)
      COMPLEX(8),ALLOCATABLE   :: XHIST(:,:,:,:)   ! (NGL,NDIM,NSIM,0:NHISTX-1)
      COMPLEX(8),ALLOCATABLE   :: RHIST(:,:,:,:)
      COMPLEX(8),ALLOCATABLE   :: XCUR(:,:,:),RCUR(:,:,:)
      COMPLEX(8),ALLOCATABLE   :: XDIIS(:,:,:),RDIIS(:,:,:)
      COMPLEX(8),ALLOCATABLE   :: PHI(:,:,:)
      COMPLEX(8),ALLOCATABLE   :: PROJCUR(:,:,:)
      COMPLEX(8),ALLOCATABLE   :: HNEW(:,:,:),ONEW(:,:,:)
      REAL(8)    ,ALLOCATABLE  :: RNORM(:)
      COMPLEX(8)               :: CSCAL(1,1)
      INTEGER(4)               :: NACT
      INTEGER(4) ,ALLOCATABLE  :: IACT(:)
!     ******************************************************************
      TCONV=.FALSE.
      IF(NB.LT.1) RETURN
      NHISTX=NRMMX+1
!
!     ==================================================================
!     == THE BANDS ARE REFINED INDEPENDENTLY UNTIL THE FINAL RAYLEIGH-==
!     == RITZ STEP, SO THEY ARE PROCESSED IN BLOCKS OF NSIM BANDS,    ==
!     == EACH BLOCK RUNNING ITS FULL DIIS LOOP (AS VASP'S NSIM). THE   ==
!     == DIIS HISTORY THEN ONLY COVERS ONE BLOCK: MEMORY ~19*NSIM      ==
!     == WAVE FUNCTIONS INSTEAD OF ~19*NB (2026-09-27; SI216 NEEDED    ==
!     == 16.5 GB BEFORE). H/O ARE STILL APPLIED IN BATCHES.           ==
!     ==================================================================
      NSIM=MIN(NB,NSIMX)
      ALLOCATE(NHIST(NSIM)); ALLOCATE(TACTIVE(NSIM))
      ALLOCATE(XHIST(NGL,NDIM,NSIM,0:NHISTX-1))
      ALLOCATE(RHIST(NGL,NDIM,NSIM,0:NHISTX-1))
      ALLOCATE(XCUR(NGL,NDIM,NSIM)); ALLOCATE(RCUR(NGL,NDIM,NSIM))
      ALLOCATE(XDIIS(NGL,NDIM,NSIM)); ALLOCATE(RDIIS(NGL,NDIM,NSIM))
      ALLOCATE(PHI(NGL,NDIM,NSIM))
      ALLOCATE(PROJCUR(NDIM,NSIM,NPRO))
      ALLOCATE(HNEW(NGL,NDIM,NSIM)); ALLOCATE(ONEW(NGL,NDIM,NSIM))
      ALLOCATE(RNORM(NSIM))
      ALLOCATE(IACT(NSIM))

!     == SEED EPS WITH A REAL RAYLEIGH-RITZ ESTIMATE (SAME PLACEHOLDER-    ==
!     == SEEDING FIX AS DAVIDSON_BLOCK_SWEEP -- SEE ITS HEADER COMMENT:    ==
!     == THIS%EIGVAL CAN ARRIVE AS THE 1.D100 PLACEHOLDER ON THE VERY      ==
!     == FIRST CALL, WHICH WOULD OTHERWISE POISON THE FIRST RESIDUAL.      ==
      CALL CG_SUBSPACEROTATE(NGL,NDIM,NB,NB,NPRO,R0,PSI,PROJ,EPS)

      TCONV=.TRUE.
      DO IB0=1,NB,NSIM
        NBL=MIN(NSIM,NB-IB0+1)
!       == HISTORY ENTRY 0 = THE CURRENT (JUST ROTATED) TRIAL VECTORS.     ==
        XHIST(:,:,1:NBL,0)=PSI(:,:,IB0:IB0+NBL-1)
        PROJCUR(:,1:NBL,:)=PROJ(:,IB0:IB0+NBL-1,:)
        CALL WAVES_HPSI(MAP,GSET,ISPIN,NGL,NDIM,NDIMD,NBL,NPRO,LMNXX,NAT &
     &                  ,NRL,XHIST(:,:,1:NBL,0),V(1,ISPIN),R0 &
     &                  ,PROJCUR(:,1:NBL,:),DH,HNEW(:,:,1:NBL))
        ONEW(:,:,1:NBL)=XHIST(:,:,1:NBL,0)
        CALL WAVES_OPSI(NBL,NBL,NPRO,NAT,NGL,R0,PROJCUR(:,1:NBL,:) &
     &                  ,ONEW(:,:,1:NBL))
        DO L=1,NBL
          RHIST(:,:,L,0)=HNEW(:,:,L)-CMPLX(EPS(IB0+L-1),0.D0,KIND=8)*ONEW(:,:,L)
          CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,1,RHIST(:,:,L,0),1 &
     &                                ,RHIST(:,:,L,0),CSCAL)
          CALL MPE$COMBINE('K','+',CSCAL)
          RNORM(L)=SQRT(MAX(REAL(CSCAL(1,1),KIND=8),0.D0))
        END DO
        NHIST(1:NBL)=1  ! ONE ENTRY (INDEX 0) STORED SO FAR, FOR EVERY BAND
        TACTIVE(1:NBL)=(RNORM(1:NBL).GE.CONV)

        DO ITER=1,NRMMX
          NACT=0
          DO L=1,NBL
            IF(TACTIVE(L)) THEN
              NACT=NACT+1
              IACT(NACT)=L
            END IF
          END DO
          IF(NACT.EQ.0) EXIT

!         == PER-BAND DIIS EXTRAPOLATION OVER THIS BAND'S OWN HISTORY SO  ==
!         == FAR (TINY, NOT A HOT SPOT -- SEE HEADER COMMENT).            ==
          DO K=1,NACT
            L=IACT(K)
            CALL RMM_DIIS_COEFF(NGL,NDIM,NHIST(L),XHIST(:,:,L,0:NHIST(L)-1) &
     &                          ,RHIST(:,:,L,0:NHIST(L)-1) &
     &                          ,XDIIS(:,:,K),RDIIS(:,:,K))
          END DO
!         == PRECONDITION THE EXTRAPOLATED RESIDUAL AND STEP DOWNHILL.    ==
!         == CG_PRECONDITION_FULL RETURNS K*R (POSITIVE-DEFINITE K); THE  ==
!         == STEEPEST-DESCENT STEP ON THE RAYLEIGH QUOTIENT IS X-K*R. A   ==
!         == "+" HERE WAS AN ASCENT STEP (BAND ENERGIES DIVERGED UPWARD   ==
!         == ON THE H2 TEST CASE).                                        ==
          DO K=1,NACT
            CALL CG_PRECONDITION_FULL(NGL,G2,XDIIS(:,1,K),RDIIS(:,1,K) &
     &                                ,PHI(:,1,K))
          END DO
          XCUR(:,:,1:NACT)=XDIIS(:,:,1:NACT)-PHI(:,:,1:NACT)

!         == BATCHED H/O APPLICATION OVER THE BLOCK'S ACTIVE BANDS        ==
          CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NACT,NPRO &
     &                           ,XCUR(:,:,1:NACT),PROJCUR(:,1:NACT,:))
          CALL WAVES_HPSI(MAP,GSET,ISPIN,NGL,NDIM,NDIMD,NACT,NPRO,LMNXX,NAT &
     &                    ,NRL,XCUR(:,:,1:NACT),V(1,ISPIN),R0 &
     &                    ,PROJCUR(:,1:NACT,:),DH,HNEW(:,:,1:NACT))
          ONEW(:,:,1:NACT)=XCUR(:,:,1:NACT)
          CALL WAVES_OPSI(NACT,NACT,NPRO,NAT,NGL,R0,PROJCUR(:,1:NACT,:) &
     &                    ,ONEW(:,:,1:NACT))
!
!         == APPEND TO HISTORY (WINDOWED: DROP THE OLDEST ENTRY IF THE    ==
!         == CAP IS REACHED) AND UPDATE TACTIVE/RNORM FOR EACH BAND JUST  ==
!         == REFINED. PSI/PROJ ARE UPDATED HERE TOO, SO A BAND THAT LOCKS ==
!         == PARTWAY THROUGH KEEPS ITS LATEST (CONVERGED) VALUE.          ==
          DO K=1,NACT
            L=IACT(K)
            RCUR(:,:,K)=HNEW(:,:,K)-CMPLX(EPS(IB0+L-1),0.D0,KIND=8)*ONEW(:,:,K)
            CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,1,RCUR(:,:,K),1 &
     &                                  ,RCUR(:,:,K),CSCAL)
            CALL MPE$COMBINE('K','+',CSCAL)
            RNORM(L)=SQRT(MAX(REAL(CSCAL(1,1),KIND=8),0.D0))
            IF(NHIST(L).GE.NHISTX) THEN
              DO IH=0,NHISTX-2
                XHIST(:,:,L,IH)=XHIST(:,:,L,IH+1)
                RHIST(:,:,L,IH)=RHIST(:,:,L,IH+1)
              END DO
              XHIST(:,:,L,NHISTX-1)=XCUR(:,:,K)
              RHIST(:,:,L,NHISTX-1)=RCUR(:,:,K)
            ELSE
              XHIST(:,:,L,NHIST(L))=XCUR(:,:,K)
              RHIST(:,:,L,NHIST(L))=RCUR(:,:,K)
              NHIST(L)=NHIST(L)+1
            END IF
            PSI(:,:,IB0+L-1)=XCUR(:,:,K)
            PROJ(:,IB0+L-1,:)=PROJCUR(:,K,:)
            IF(RNORM(L).LT.CONV) TACTIVE(L)=.FALSE.
          END DO
        END DO
        IF(ANY(TACTIVE(1:NBL))) TCONV=.FALSE.
      END DO

!     == FINAL RAYLEIGH-RITZ: THE NB INDEPENDENTLY-REFINED BANDS ARE      ==
!     == GENERALLY NOT MUTUALLY ORTHONORMAL -- ROTATE THEM BACK INTO A    ==
!     == PROPER ORTHONORMAL, ENERGY-ORDERED SET (REUSES THE SAME,         ==
!     == ALREADY-VALIDATED ROUTINE DAVIDSON USES FOR ITS OWN CONTRACTION).==
      CALL CG_SUBSPACEROTATE(NGL,NDIM,NB,NB,NPRO,R0,PSI,PROJ,EPS)

      DEALLOCATE(NHIST,TACTIVE)
      DEALLOCATE(XHIST,RHIST)
      DEALLOCATE(XCUR,RCUR,XDIIS,RDIIS,PHI)
      DEALLOCATE(PROJCUR)
      DEALLOCATE(HNEW,ONEW)
      DEALLOCATE(RNORM,IACT)
      RETURN
      END SUBROUTINE RMM_DIIS_BLOCK_SWEEP
