      SUBROUTINE CG_SUBSPACEROTATE(NGL,NDIM,NB,NBH,NPRO,R0,PSI,PROJ,EIGVAL)
!     ******************************************************************
!     ** RAYLEIGH-RITZ SUBSPACE DIAGONALIZATION OF THE CURRENT NB TRIAL **
!     ** VECTORS: BUILD THE NBxNB SUBSPACE HAMILTONIAN AND OVERLAP,     **
!     ** SOLVE THE GENERALIZED EIGENPROBLEM, AND ROTATE ALL BANDS (AND  **
!     ** THEIR PROJECTIONS) INTO THAT JOINT EIGENBASIS. THIS IS THE     **
!     ** STEP VASP'S BLOCKED-DAVIDSON/RMM-DIIS SCHEME RUNS EVERY        **
!     ** ITERATION TO STAY ROBUST FOR (NEAR-)DEGENERATE BANDS; CP-PAW'S **
!     ** SEQUENTIAL SINGLE-BAND CG HAS NO EQUIVALENT OF ITS OWN.        **
!     **                                                                **
!     ** PSI/PROJ/EIGVAL ARE PASSED IN EXPLICITLY (RATHER THAN READ     **
!     ** FROM THIS% DIRECTLY) SO THE SAME ROUTINE SERVES BOTH THE       **
!     ** NORMAL CASE (NB=NBH, CALLED DIRECTLY ON THIS%PSI0/THIS%PROJ)   **
!     ** AND THE SUPER-WAVE-FUNCTION CASE (NB>NBH), WHERE THE CALLER    **
!     ** FIRST UNPACKS INTO NB GENUINE SINGLE-BAND ARRAYS AND PASSES    **
!     ** THOSE INSTEAD -- SEE CG$STATE_BY_STATE.                        **
!     ******************************************************************
      USE CG_INTERFACE_MODULE, ONLY: NAT,LMNXX,DH,NRL,V,ISPIN,TREALSUB
      USE WAVES_MODULE, ONLY: MAP,GSET,NDIMD
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NGL
      INTEGER(4),INTENT(IN) :: NDIM
      INTEGER(4),INTENT(IN) :: NB
      INTEGER(4),INTENT(IN) :: NBH
      INTEGER(4),INTENT(IN) :: NPRO
      REAL(8)   ,INTENT(IN) :: R0(3,NAT)
      COMPLEX(8),INTENT(INOUT) :: PSI(NGL,NDIM,NB)
      COMPLEX(8),INTENT(INOUT) :: PROJ(NDIM,NB,NPRO)
      REAL(8)   ,INTENT(INOUT) :: EIGVAL(NB)
      COMPLEX(8),ALLOCATABLE :: HPSI(:,:,:)
      COMPLEX(8),ALLOCATABLE :: OPSI(:,:,:)
      COMPLEX(8),ALLOCATABLE :: SUBH(:,:)
      COMPLEX(8),ALLOCATABLE :: SUBO(:,:)
      COMPLEX(8),ALLOCATABLE :: SUBVEC(:,:)
      COMPLEX(8),ALLOCATABLE :: PSIROT(:,:,:)
      COMPLEX(8),ALLOCATABLE :: PROJROT(:,:,:)
      REAL(8)   ,ALLOCATABLE :: SUBEPS(:)
      INTEGER(4)              :: IB1,IB2
!     == SCAN0R DAV+ANDERSON INSTABILITY DIAGNOSTIC (2026-09-10): OPT-IN,   ==
!     == FOLLOW-UP TO VESPAW_DAV_COND_DIAG IN DAVIDSON_BLOCK_SWEEP -- THAT  ==
!     == DIAGNOSTIC ONLY COVERS THE EXPANDED (PSISURV+DELTA) TRIAL         ==
!     == SUBSPACE INSIDE THE ISWEEP LOOP; IT MISSES THIS ROUTINE'S OWN     ==
!     == PLAIN NB-BAND RAYLEIGH-RITZ ROTATION, WHICH DAVIDSON_BLOCK_SWEEP  ==
!     == CALLS UNCONDITIONALLY *BEFORE* ITS ISWEEP LOOP EVER STARTS -- I.E.==
!     == BEFORE ANY CORRECTION-DIRECTION VECTORS EXIST. IF THE BLOWUP'S    ==
!     == BAD EIGENVALUE IS ALREADY PRESENT HERE, IT IMPLICATES DH'S        ==
!     == APPLICATION TO THE PLAIN OLD WAVEFUNCTIONS DIRECTLY, INDEPENDENT  ==
!     == OF ANY DAVIDSON SUBSPACE-EXPANSION MACHINERY.                     ==
      LOGICAL(4),SAVE          :: TDAVCONDDIAGCHECKED=.FALSE.
      LOGICAL(4),SAVE          :: TDAVCONDDIAG=.FALSE.
      INTEGER(4),SAVE          :: CGSRCALL=0
      CHARACTER(16)            :: CENVDAVCONDDIAG
!     == PSISURV RAYLEIGH-QUOTIENT DIAGNOSTIC, PUSHED ONE LEVEL EARLIER        ==
!     == (2026-09-10, SAME DAY FOLLOW-UP): THE DAVIDSON_BLOCK_SWEEP-SIDE       ==
!     == VESPAW_DAV_PSISURV_RQ MEASURES THE RAW SUBH DIAGONAL AT ISWEEP=1 OF   ==
!     == THAT ROUTINE'S OWN LOOP -- BUT THAT'S *AFTER* THIS ROUTINE HAS        ==
!     == ALREADY ROTATED PSI/PROJ ONCE (DAVIDSON_BLOCK_SWEEP CALLS             ==
!     == CG_SUBSPACEROTATE UNCONDITIONALLY BEFORE ITS OWN ISWEEP LOOP EVER     ==
!     == STARTS). THIS IS THE GENUINELY EARLIEST POINT: SUBH/SUBO HERE ARE     ==
!     == BUILT DIRECTLY FROM THE INCOMING PSI/PROJ, UNTOUCHED BY ANY ROTATION  ==
!     == THIS OUTER ITERATION. SAME ENV VAR AS THE DAVIDSON_BLOCK_SWEEP-SIDE   ==
!     == VERSION SO BOTH PRINT TOGETHER. SEE THE DEV NOTES.               ==
      LOGICAL(4),SAVE          :: TPSRQCHECKED=.FALSE.
      LOGICAL(4),SAVE          :: TPSRQ=.FALSE.
      CHARACTER(16)            :: CENVPSRQ
      INTEGER(4)               :: KWORST
      REAL(8)                  :: RQEV,RQWORST,IMWORST,MAXABSIM
      INTEGER(4)               :: IPRO8A,IPRO8B,IATDIAG
      REAL(8)                  :: NORM8IN,NORM8OUT
!     ******************************************************************
      IF(.NOT.TDAVCONDDIAGCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_DAV_COND_DIAG',CENVDAVCONDDIAG)
        TDAVCONDDIAG=(LEN_TRIM(CENVDAVCONDDIAG).GT.0)
        TDAVCONDDIAGCHECKED=.TRUE.
      END IF
      IF(TDAVCONDDIAG) CGSRCALL=CGSRCALL+1
      IF(.NOT.TPSRQCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_DAV_PSISURV_RQ',CENVPSRQ)
        TPSRQ=(LEN_TRIM(CENVPSRQ).GT.0)
        TPSRQCHECKED=.TRUE.
      END IF
      IF(NB.LE.1) RETURN ! NOTHING TO ROTATE
      IF(TPSRQ.AND.NAT.GE.8) THEN
!       == ATOM-8 INCOMING PROJ, AS RECEIVED -- BEFORE THIS ROUTINE (OR ANY  ==
!       == PRIOR CALL THIS OUTER ITERATION) TOUCHES ANYTHING. TRACKS         ==
!       == <P|PSI> FOR ATOM 8 SPECIFICALLY ACROSS EVERY CALL (BOTH THE       ==
!       == BASELINE ITERATION-1 CALLS AND THE FIRST ITERATION-2 CALLS) TO    ==
!       == PIN DOWN WHETHER IT'S ALREADY LARGE THE MOMENT THIS ROUTINE SEES  ==
!       == IT, MATCHING THE MAX|PROJ| SPIKE WAVES$DENMAT FINDS LATER (SAME   ==
!       == ATOM). SEE THE DEV NOTES.                                    ==
        IPRO8A=1
        DO IATDIAG=1,7
          IPRO8A=IPRO8A+MAP%LMNX(MAP%ISP(IATDIAG))
        ENDDO
        IPRO8B=IPRO8A+MAP%LMNX(MAP%ISP(8))-1
        NORM8IN=MAXVAL(ABS(PROJ(:,:,IPRO8A:IPRO8B)))
        PRINT*,'VESPAW_DAV_PSISURV_RQ_PROJIN CALL=',CGSRCALL &
     &        ,' MAX|PROJ(IAT=8,INCOMING)|=',NORM8IN
      END IF
      ALLOCATE(HPSI(NGL,NDIM,NBH))
      ALLOCATE(OPSI(NGL,NDIM,NBH))
      CALL WAVES_HPSI(MAP,GSET,ISPIN,NGL,NDIM,NDIMD,NBH,NPRO,LMNXX,NAT &
     &                ,NRL,PSI,V(1,ISPIN),R0,PROJ,DH,HPSI)
      OPSI=PSI
      CALL WAVES_OPSI(NB,NBH,NPRO,NAT,NGL,R0,PROJ,OPSI)

      ALLOCATE(SUBH(NB,NB))
      ALLOCATE(SUBO(NB,NB))
!     == SUMS OVER PLANE WAVES USE CID='K' (THE TASKS SHARING THIS K-POINT; ==
!     == '~', THE WORLD GROUP, MIXED DIFFERENT K-POINTS UNDER K-POINT       ==
!     == PARALLELIZATION). BEFORE THAT, 'NONE' AS ORIGINALLY WRITTEN --      ==
!     == 'NONE' IS NEVER REGISTERED VIA MPE$NEW ANYWHERE IN THE CODEBASE,    ==
!     == SO MPE$SELECT('NONE') HARD-STOPS ('UNKNOWN ID') THE FIRST TIME ANY  ==
!     == OPTIMIZER (CG/DAV/RMM) RUNS UNDER REAL NTASKS>1 MPI (PPAW_FAST.X);  ==
!     == FOUND WHILE VALIDATING THE RMM-DELAY/MIXER WORK UNDER ACTUAL MPI    ==
!     == FOR THE FIRST TIME THIS PROJECT HAS DONE SO (PRIOR TESTING WAS      ==
!     == SERIAL-ONLY, PAW_FAST.X). THIS BUG PREDATES THIS SESSION.           ==
      CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,PSI,NB,HPSI,SUBH)
      CALL MPE$COMBINE('K','+',SUBH)
      CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,PSI,NB,OPSI,SUBO)
      CALL MPE$COMBINE('K','+',SUBO)
      DEALLOCATE(HPSI)
      DEALLOCATE(OPSI)

      IF(TPSRQ) THEN
!       == RAW, PRE-SYMMETRIZATION DIAGONAL -- THIS IS THE EARLIEST POINT     ==
!       == IN THE WHOLE CALL CHAIN WHERE <PSI_K_OLD|H_NEW|PSI_K_OLD> CAN BE    ==
!       == FORMED: NO ROTATION (THIS ROUTINE'S OWN ROTATION HAPPENS BELOW,    ==
!       == AFTER THIS PRINT), NO CORRECTION DIRECTIONS, JUST THE INCOMING,    ==
!       == UNTOUCHED PSI/PROJ FROM THE END OF THE PREVIOUS OUTER ITERATION.   ==
        KWORST=1
        RQWORST=REAL(SUBH(1,1),KIND=8)/MAX(REAL(SUBO(1,1),KIND=8),1.D-14)
        MAXABSIM=0.D0
        DO IB1=1,NB
          RQEV=REAL(SUBH(IB1,IB1),KIND=8)/MAX(REAL(SUBO(IB1,IB1),KIND=8),1.D-14)
          IF(RQEV.LT.RQWORST) THEN
            RQWORST=RQEV
            KWORST=IB1
          END IF
          MAXABSIM=MAX(MAXABSIM,ABS(AIMAG(SUBH(IB1,IB1))))
        END DO
        IMWORST=AIMAG(SUBH(KWORST,KWORST))
        PRINT*,'VESPAW_DAV_PSISURV_RQ_PREROTATE CALL=',CGSRCALL &
     &        ,' NB=',NB &
     &        ,' K_WORST=',KWORST &
     &        ,' RQ_WORST_EV=',RQWORST*27.211386245988D0 &
     &        ,' IMAG_SUBH_AT_WORST=',IMWORST &
     &        ,' MAXABS_IMAG_SUBH_DIAG=',MAXABSIM
      END IF

!     == ENFORCE EXACT HERMITICITY: LIB$GENERALEIGENVALUEC8 HARD-STOPS ON ==
!     == ANY ROUNDOFF ASYMMETRY, SINCE SUBH/SUBO ARE BUILT FROM TWO       ==
!     == INDEPENDENTLY-EVALUATED OPERATOR APPLICATIONS RATHER THAN A      ==
!     == SELF-OVERLAP.                                                    ==
      SUBH=0.5D0*(SUBH+CONJG(TRANSPOSE(SUBH)))
      SUBO=0.5D0*(SUBO+CONJG(TRANSPOSE(SUBO)))
      IF(TREALSUB) THEN
        SUBH=CMPLX(REAL(SUBH,KIND=8),0.D0,KIND=8)
        SUBO=CMPLX(REAL(SUBO,KIND=8),0.D0,KIND=8)
      END IF

      ALLOCATE(SUBVEC(NB,NB))
      ALLOCATE(SUBEPS(NB))
      CALL LIB$GENERALEIGENVALUEC8(NB,SUBH,SUBO,SUBEPS,SUBVEC)
      IF(TDAVCONDDIAG) THEN
        PRINT*,'VESPAW_DAV_COND_DIAG SUBSPACEROTATE CALL=',CGSRCALL &
     &        ,' NB=',NB &
     &        ,' SUBEPS_MIN_EV=',MINVAL(SUBEPS)*27.211386245988D0 &
     &        ,' SUBEPS_MAX_EV=',MAXVAL(SUBEPS)*27.211386245988D0
      END IF
      DEALLOCATE(SUBH)
      DEALLOCATE(SUBO)

      ALLOCATE(PSIROT(NGL,NDIM,NB))
      PSIROT=(0.D0,0.D0)
      DO IB2=1,NB
        DO IB1=1,NB
          PSIROT(:,:,IB2)=PSIROT(:,:,IB2)+PSI(:,:,IB1)*SUBVEC(IB1,IB2)
        END DO
      END DO
      PSI=PSIROT
      DEALLOCATE(PSIROT)

      ALLOCATE(PROJROT(NDIM,NB,NPRO))
      PROJROT=(0.D0,0.D0)
      DO IB2=1,NB
        DO IB1=1,NB
          PROJROT(:,IB2,:)=PROJROT(:,IB2,:)+PROJ(:,IB1,:)*SUBVEC(IB1,IB2)
        END DO
      END DO
      PROJ=PROJROT
      DEALLOCATE(PROJROT)

      IF(TPSRQ.AND.NAT.GE.8) THEN
!       == ATOM-8 OUTGOING PROJ, RIGHT AFTER THIS ROUTINE'S OWN PURE          ==
!       == PSISURV-ONLY ROTATION -- NO DELTA/CORRECTION DIRECTIONS INVOLVED   ==
!       == AT ALL AT THIS POINT (2026-09-11, FOLLOW-UP TO THE AMPLIFICATION-  ==
!       == CAP FIX: CAPPING DELTA'S NORMALIZATION DID NOT CHANGE THE          ==
!       == CONTRACTED SWEEP-1 ATOM-8 SPIKE AT ALL, SO CHECK WHETHER IT'S      ==
!       == ALREADY FULLY PRESENT HERE, PURELY FROM MIXING THE 58 PSISURV      ==
!       == VECTORS AMONG THEMSELVES). SEE THE DEV NOTES.                 ==
        IPRO8A=1
        DO IATDIAG=1,7
          IPRO8A=IPRO8A+MAP%LMNX(MAP%ISP(IATDIAG))
        ENDDO
        IPRO8B=IPRO8A+MAP%LMNX(MAP%ISP(8))-1
        NORM8OUT=MAXVAL(ABS(PROJ(:,:,IPRO8A:IPRO8B)))
        PRINT*,'VESPAW_DAV_PSISURV_RQ_PROJOUT CALL=',CGSRCALL &
     &        ,' MAX|PROJ(IAT=8,POST-ROTATION)|=',NORM8OUT
      END IF

      EIGVAL=SUBEPS
      DEALLOCATE(SUBVEC)
      DEALLOCATE(SUBEPS)
      RETURN
      END SUBROUTINE CG_SUBSPACEROTATE
!
!     ..................................................................
      SUBROUTINE DAVIDSON$STATE_BY_BLOCK(NRL_,NDIMD_,V_,CONV,NAT_,LMNXX_,DH_)
!     ******************************************************************
!     ** INTERFACE SUBROUTINE FOR THE BLOCKED-DAVIDSON DIAGONALIZER.    **
!     ** MIRRORS CG$STATE_BY_STATE'S SETUP/LOOP/SUPER-WAVE-FUNCTION     **
!     ** UNPACK-REPACK STRUCTURE EXACTLY; ONLY THE INNER DIAGONALIZER   **
!     ** DIFFERS (DAVIDSON_BLOCK_SWEEP INSTEAD OF CG_STATE_BY_STATE).   **
!     ******************************************************************
      USE CG_INTERFACE_MODULE
      USE WAVES_MODULE
      IMPLICIT NONE
      INTEGER(4)   , INTENT(IN)   :: NRL_
      INTEGER(4)   , INTENT(IN)   :: NDIMD_
      REAL(8)      , INTENT(IN)   :: V_(NRL_,NDIMD_)
      REAL(8)      , INTENT(INOUT)   :: CONV
      INTEGER(4)   , INTENT(IN)   :: NAT_
      INTEGER(4)   , INTENT(IN)   :: LMNXX_
      COMPLEX(8)   , INTENT(IN)   :: DH_(LMNXX_,LMNXX_,NDIMD_,NAT_)
      LOGICAL(4)                  :: TCONV
      INTEGER(4)                  :: NGL,NB,NBH,NPRO
      INTEGER(4)                  :: NSWEEPX
      REAL(8)     ,ALLOCATABLE    :: G2(:) ! (NGL)
      REAL(8)     ,ALLOCATABLE    :: R0(:,:)
      COMPLEX(8)  ,ALLOCATABLE    :: PSIU(:,:,:)  ! (NGL,NDIM,NB) UNPACKED
      COMPLEX(8)  ,ALLOCATABLE    :: PROJU(:,:,:) ! (NDIM,NB,NPRO) UNPACKED
      REAL(8)     ,ALLOCATABLE    :: FWEIGHT(:)   ! (NB) OCCUPATION WEIGHT, SEE BELOW
      LOGICAL(4)                  :: TDEBUG  ! !CONTROL!GENERIC VERBOSITY='DEBUG'
!     == EDFT "SHADOW MODE" (ENSEMBLE-DFT PROTOTYPE, SEE THE DEV NOTES): ==
!     == COMPUTES THE AUXILIARY-HAMILTONIAN MACHINERY FROM REAL WAVEFUNCTION ==
!     == DATA EVERY OUTER ITERATION AND PRINTS A CONVERGENCE DIAGNOSTIC, BUT ==
!     == NEVER FEEDS BACK INTO PSI/EIGVAL/ANYTHING ELSE -- PURELY A         ==
!     == VALIDATION/OBSERVATION HOOK, ZERO EFFECT ON THE REAL RUN. OFF BY   ==
!     == DEFAULT; ENABLED BY SETTING THE ENVIRONMENT VARIABLE               ==
!     == VESPAW_EDFT_SHADOW (ANY NONEMPTY VALUE) BEFORE LAUNCHING VESPAW.   ==
      LOGICAL(4)  ,SAVE           :: TEDFTSHADOWCHECKED=.FALSE.
      LOGICAL(4)  ,SAVE           :: TEDFTSHADOW=.FALSE.
      CHARACTER(16)               :: CENVVAL
!     == ATOM-8 PROJ-AT-WRITE-BACK DIAGNOSTIC (2026-09-10, SAME DAY FOLLOW-  ==
!     == UP): CHECKS WHETHER THE MAX|PROJ(IAT=8)| SPIKE THE VESPAW_DAV_      ==
!     == PSISURV_RQ_PROJIN DIAGNOSTIC SEES AT THE START OF THE *NEXT*        ==
!     == K-POINT-1 DAVIDSON CALL IS ALREADY PRESENT RIGHT HERE, THE MOMENT   ==
!     == THIS%PROJ IS (RE)WRITTEN AFTER DAVIDSON_BLOCK_SWEEP RETURNS AND     ==
!     == THIS%PSI0 IS PACKED/REFRESHED VIA WAVES_PROJECTIONS -- I.E.         ==
!     == BEFORE WAVES$DENMAT, MIXING, OR ANYTHING ELSE BETWEEN OUTER         ==
!     == ITERATIONS COULD POSSIBLY TOUCH IT. SAME ENV VAR AS THE OTHER       ==
!     == VESPAW_DAV_PSISURV_RQ PRINTS SO THEY CORRELATE DIRECTLY.            ==
      LOGICAL(4)  ,SAVE           :: TPROJWBCHECKED=.FALSE.
      LOGICAL(4)  ,SAVE           :: TPROJWB=.FALSE.
      CHARACTER(16)               :: CENVPROJWB
      INTEGER(4)                  :: IPRO8AWB,IPRO8BWB,IATWB
      REAL(8)                     :: NORM8WB
!     == LIVE EDFT OCCUPATION FEED (SEE VESPAW_WAVES1.F90, WAVES$ETOT, FOR    ==
!     == WHERE HAUX'S EIGENVALUES ACTUALLY GET SUBSTITUTED INTO DYNOCC'S      ==
!     == OCCUPATION DETERMINATION): THAT SUBSTITUTION NEEDS HAUX TO ALREADY   ==
!     == BE MAINTAINED (SEEDED + STEPPED) HERE, EXACTLY AS SHADOW MODE ALREADY==
!     == DOES -- SO VESPAW_EDFT_LIVE_OCC ALONE (WITHOUT ALSO SETTING          ==
!     == VESPAW_EDFT_SHADOW) MUST STILL KEEP HAUX RUNNING. TEDFTHAUXACTIVE    ==
!     == (=SHADOW.OR.LIVE_OCC) IS THE GATE FOR "MAINTAIN HAUX AT ALL"; THE    ==
!     == PER-BLOCK DIAGNOSTIC PRINT REMAINS GATED ON TEDFTSHADOW ALONE, SO    ==
!     == ENABLING LIVE-OCC BY ITSELF STAYS QUIET UNLESS SHADOW IS ALSO ASKED  ==
!     == FOR.                                                                 ==
      LOGICAL(4)  ,SAVE           :: TEDFTLIVEOCCCHECKED=.FALSE.
      LOGICAL(4)  ,SAVE           :: TEDFTLIVEOCC=.FALSE.
      CHARACTER(16)               :: CENVVALEDFTOCC
      LOGICAL(4)                  :: TEDFTHAUXACTIVE
      COMPLEX(8)  ,ALLOCATABLE    :: HPHYS(:,:)
      COMPLEX(8)  ,ALLOCATABLE    :: EDFTRESIDUAL(:,:)
      REAL(8)     ,ALLOCATABLE    :: HAUXEIG(:)
      REAL(8)                     :: EDFTMAXDIFF
      INTEGER(4)                  :: IB_EDFT
!     == SHADOW MODE, MVP-WEIGHTED STEP: A GLOBAL CHEMICAL POTENTIAL/TEMP,   ==
!     == SHARED ACROSS ALL (IKPT,ISPIN) BLOCKS FOR THIS OUTER ITERATION, IS  ==
!     == NEEDED TO EVALUATE EDFT$HAUXSTEP_MVP'S FERMI-DIRAC WEIGHT (SEE ITS  ==
!     == OWN HEADER COMMENT). COMPUTED ONCE HERE (BEFORE THE PER-BLOCK LOOP) ==
!     == FROM THE CURRENT (PREVIOUS-ITERATION) HAUX STATE ACROSS ALL BLOCKS  ==
!     == -- A ONE-ITERATION-LAGGED BUT GLOBALLY CONSISTENT ESTIMATE, ONLY    ==
!     == AVAILABLE ONCE EVERY BLOCK HAS BEEN VISITED AT LEAST ONCE (TRACKED  ==
!     == BY TEDFTHAUXREADY, SET AFTER THE FIRST FULL PASS).                  ==
      LOGICAL(4)  ,SAVE           :: TEDFTHAUXREADY=.FALSE.
      REAL(8)     ,SAVE           :: EDFTCHMPOT=0.D0
      REAL(8)     ,SAVE           :: EDFTTEMP=1.D0
      REAL(8)                     :: EDFTTOTCHA
      INTEGER(4)                  :: EDFTISPINDEG
      REAL(8)     ,ALLOCATABLE    :: EDFTWKPT(:)
      REAL(8)     ,ALLOCATABLE,SAVE :: EDFTF(:,:,:)
      REAL(8)                     :: EDFTEMERMN
!     == FERMI-WINDOW-RESTRICTED VERSION OF THE SAME DIAGNOSTIC: THE PLAIN    ==
!     == MAX-OVER-ALL-BANDS VALUE ABOVE IS DOMINATED BY DEEP/HIGH BANDS THAT ==
!     == THE MVP WEIGHTING DELIBERATELY STOPS DRIVING (WEIGHT~0 THERE) --    ==
!     == RESTRICTING TO BANDS WHERE F*(1-F) (THE SAME QUANTITY THE FERMI-    ==
!     == DIRAC-DERIVATIVE WEIGHT IS PROPORTIONAL TO) EXCEEDS A SMALL         ==
!     == THRESHOLD ISOLATES THE PARTIALLY-OCCUPIED, NEAR-FERMI-LEVEL BANDS   ==
!     == THIS WHOLE EXERCISE IS MEANT TO TRACK BETTER. USES EDFTF (SAVED     ==
!     == ACROSS THE PER-BLOCK LOOP, SEE ABOVE) SO IT NEEDS NO EXTRA DYNOCC   ==
!     == CALLS PER BLOCK.                                                    ==
      REAL(8)                     :: EDFTMAXDIFF_FERMI
      INTEGER(4)                  :: NFERMIACT_EDFT
!     == WORST FERMI-WINDOW RESIDUAL SEEN THIS ITERATION, ACROSS ALL BLOCKS  ==
!     == THAT HAVE ANY FERMI-ACTIVE BAND -- REPORTED TO EDFT_MODULE (SEE     ==
!     == EDFT$SETHAUXRESMAX) FOR THE LIVE-OCCUPATION STOPPING GATE IN        ==
!     == VESPAW_WAVES1.F90. INITIALIZED TO A LARGE SENTINEL SO AN ITERATION  ==
!     == WITH NO FERMI-ACTIVE BLOCKS AT ALL (E.G. THE VERY FIRST ONE) NEVER  ==
!     == LOOKS FALSELY "CONVERGED" TO THAT GATE.                             ==
      REAL(8)                     :: EDFTITERRESMAX
      REAL(8)     ,PARAMETER      :: FERMIACT_THRESH=1.D-4  ! F(1-F) THRESHOLD
!     == FORCE-UNIFORM-STEP OVERRIDE: DIAGNOSTIC-ONLY LEVER FOR A/B TESTING  ==
!     == THE MVP-WEIGHTED STEP AGAINST THE OLD UNIFORM STEP UNDER THE *SAME* ==
!     == FERMI-WINDOW DIAGNOSTIC ABOVE, WITHOUT RECOMPILING. HAS NO EFFECT   ==
!     == UNLESS VESPAW_EDFT_SHADOW IS ALSO SET (SHADOW MODE IS STILL A       ==
!     == NO-OP EITHER WAY). OFF BY DEFAULT.                                  ==
      LOGICAL(4)  ,SAVE           :: TEDFTFORCEUNICHECKED=.FALSE.
      LOGICAL(4)  ,SAVE           :: TEDFTFORCEUNIFORM=.FALSE.
      CHARACTER(16)               :: CENVVAL3
!     == RAW-MVP OVERRIDE: DIAGNOSTIC-ONLY LEVER, FOR COMPARISON, TO FALL     ==
!     == BACK TO THE OLD (FOUND-REGRESSED, SEE THE DEV NOTES) RAW-WEIGHT  ==
!     == EDFT$HAUXSTEP_MVP INSTEAD OF THE PER-BAND-ADAPTIVE                  ==
!     == EDFT$HAUXSTEP_ADAPTIVE, WHICH IS THE DEFAULT (TEMP>0) STEP NOW.     ==
      LOGICAL(4)  ,SAVE           :: TEDFTMVPRAWCHECKED=.FALSE.
      LOGICAL(4)  ,SAVE           :: TEDFTMVPRAWWEIGHT=.FALSE.
      CHARACTER(16)               :: CENVVAL4
!     == "LIVE LOCKING": REAL, ALREADY-TRUSTED DYNOCC OCCUPATIONS (NOT THE   ==
!     == EDFT/HAUX SELF-CONSISTENCY MACHINERY) FED INTO FWEIGHT BELOW, SO    ==
!     == DAVIDSON_BLOCK_SWEEP'S OCCUPATION-WEIGHTED LOCKING TOLERANCE (STEP  ==
!     == 3, NOW WITH THE SMOOTH RAMP -- SEE THAT ROUTINE'S HEADER COMMENT)   ==
!     == ACTUALLY AFFECTS CONVERGENCE. OFF BY DEFAULT; ENABLED BY SETTING    ==
!     == VESPAW_EDFT_LIVE_LOCKING (ANY NONEMPTY VALUE). *DOES* AFFECT        ==
!     == CONVERGENCE WHEN ENABLED (UNLIKE SHADOW MODE ABOVE). 'OCC' RETURNS  ==
!     == FMAX*WKPT(IKPT)*(BARE FRACTION) (SEE DYNOCC_WGHT) -- MUST DIVIDE BY==
!     == WKPT(IKPT) TOO, NOT JUST FMAX (SEE THE DEV NOTES FOR WHY THIS  ==
!     == MATTERS -- GETTING IT WRONG WAS THE BUG BEHIND THE FIRST ATTEMPT). ==
      LOGICAL(4)  ,SAVE           :: TEDFTLIVELOCKCHECKED=.FALSE.
      LOGICAL(4)  ,SAVE           :: TEDFTLIVELOCK=.FALSE.
      CHARACTER(16)               :: CENVVAL2
      INTEGER(4)                  :: NBDYNOCC
      REAL(8)                     :: FMAXVAL
      REAL(8)     ,ALLOCATABLE    :: OCCALL(:,:,:) ! (NB,NKPT,NSPIN)
      REAL(8)     ,ALLOCATABLE    :: WKPTARR(:)    ! (NKPT)
!     ******************************************************************
      IF(.NOT.TEDFTSHADOWCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_SHADOW',CENVVAL)
        TEDFTSHADOW=(LEN_TRIM(CENVVAL).GT.0)
        TEDFTSHADOWCHECKED=.TRUE.
        IF(TEDFTSHADOW) THEN
          PRINT*,'VESPAW_EDFT_SHADOW SET -- EDFT SHADOW-MODE DIAGNOSTICS ENABLED' &
     &          ,' (DOES NOT AFFECT THE REAL RUN)'
        END IF
      END IF
      IF(.NOT.TPROJWBCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_DAV_PSISURV_RQ',CENVPROJWB)
        TPROJWB=(LEN_TRIM(CENVPROJWB).GT.0)
        TPROJWBCHECKED=.TRUE.
      END IF
      IF(.NOT.TEDFTLIVEOCCCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_LIVE_OCC',CENVVALEDFTOCC)
        TEDFTLIVEOCC=(LEN_TRIM(CENVVALEDFTOCC).GT.0)
        TEDFTLIVEOCCCHECKED=.TRUE.
      END IF
      TEDFTHAUXACTIVE=TEDFTSHADOW.OR.TEDFTLIVEOCC
      IF(.NOT.TEDFTLIVELOCKCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_LIVE_LOCKING',CENVVAL2)
        TEDFTLIVELOCK=(LEN_TRIM(CENVVAL2).GT.0)
        TEDFTLIVELOCKCHECKED=.TRUE.
        IF(TEDFTLIVELOCK) THEN
          PRINT*,'VESPAW_EDFT_LIVE_LOCKING SET -- REAL OCCUPATION-WEIGHTED' &
     &          ,' LOCKING ACTIVE (AFFECTS CONVERGENCE)'
        END IF
      END IF
      IF(.NOT.TEDFTFORCEUNICHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_FORCE_UNIFORM_STEP',CENVVAL3)
        TEDFTFORCEUNIFORM=(LEN_TRIM(CENVVAL3).GT.0)
        TEDFTFORCEUNICHECKED=.TRUE.
        IF(TEDFTFORCEUNIFORM) THEN
          PRINT*,'VESPAW_EDFT_FORCE_UNIFORM_STEP SET -- SHADOW MODE WILL USE' &
     &          ,' THE OLD UNIFORM-WEIGHT STEP EVEN WHEN MVP WOULD APPLY' &
     &          ,' (A/B DIAGNOSTIC LEVER, STILL A NO-OP ON THE REAL RUN)'
        END IF
      END IF
      IF(.NOT.TEDFTMVPRAWCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_MVP_RAW_WEIGHT',CENVVAL4)
        TEDFTMVPRAWWEIGHT=(LEN_TRIM(CENVVAL4).GT.0)
        TEDFTMVPRAWCHECKED=.TRUE.
        IF(TEDFTMVPRAWWEIGHT) THEN
          PRINT*,'VESPAW_EDFT_MVP_RAW_WEIGHT SET -- SHADOW MODE WILL USE THE' &
     &          ,' OLD RAW-WEIGHT EDFT$HAUXSTEP_MVP INSTEAD OF THE' &
     &          ,' PER-BAND-ADAPTIVE STEP (A/B DIAGNOSTIC LEVER, STILL A' &
     &          ,' NO-OP ON THE REAL RUN)'
        END IF
      END IF
      CALL VERBOSITY$GETL4('DEBUG',TDEBUG)
!     == NONCOLLINEAR SPINORS (NDIM=2) ARE HANDLED BY THE GENERIC NDIM    ==
!     == ARRAYS BELOW; THERE ARE NO SUPER WAVE FUNCTIONS IN THAT CASE     ==
      NAT=NAT_
      LMNXX=LMNXX_
      ALLOCATE(DH(LMNXX,LMNXX,NDIMD,NAT))
      DH=DH_
      NPRO=MAP%NPRO
      NRL=NRL_
      ALLOCATE(V(NRL,NDIMD_))
      V=V_
      NSWEEPX=8
      IF(TEDFTLIVELOCK) THEN
        CALL DYNOCC$GETI4('NB',NBDYNOCC)
        CALL DYNOCC$GETR8('FMAX',FMAXVAL)
        ALLOCATE(OCCALL(NBDYNOCC,NKPT,NSPIN))
        CALL DYNOCC$GETR8A('OCC',NBDYNOCC*NKPT*NSPIN,OCCALL)
        ALLOCATE(WKPTARR(NKPT))
        CALL DYNOCC$GETR8A('WKPT',NKPT,WKPTARR)
      END IF
!     == SHADOW MODE, MVP-WEIGHTED STEP: COMPUTE A GLOBAL CHEMICAL POTENTIAL ==
!     == /TEMPERATURE FROM HAUX'S STATE AS IT STANDS AT THE START OF THIS    ==
!     == OUTER ITERATION (BEFORE ANY BLOCK BELOW HAS BEEN TOUCHED), SO EVERY ==
!     == BLOCK'S EDFT$HAUXSTEP_MVP CALL THIS ITERATION SHARES ONE CONSISTENT==
!     == (EIGVAL,CHMPOT) PAIR -- EXACTLY WHAT EDFT$OCCUPATIONS ALREADY DOES ==
!     == FOR THE (VALIDATED) DIAGNOSTIC OCCUPATION CALCULATION.             ==
      IF(TEDFTHAUXACTIVE.AND.TEDFTHAUXREADY) THEN
        CALL DYNOCC$GETI4('NB',NBDYNOCC)
!       == NOTE: DYNOCC$GETR8('TOTCHA',...) RETURNS THE *EXCESS* CHARGE      ==
!       == (TOTCHA-SUMOFZ, ~0 FOR A NEUTRAL CELL), NOT THE ELECTRON COUNT --==
!       == THE TRUE COUNT (WHAT EDFT$OCCUPATIONS/DYNOCC_MERMIN NEED) IS     ==
!       == UNDER THE ID 'NEL'. GETTING THIS WRONG SILENTLY FERMI-FILLS FOR  ==
!       == ~0 ELECTRONS (CHMPOT FAR BELOW EVERY BAND, F~0 EVERYWHERE).       ==
        CALL DYNOCC$GETR8('NEL',EDFTTOTCHA)
        CALL DYNOCC$GETR8('FMAX',FMAXVAL)
        EDFTISPINDEG=NINT(FMAXVAL)
        CALL DYNOCC$GETR8('TEMP',EDFTTEMP)
        ALLOCATE(EDFTWKPT(NKPT))
        CALL DYNOCC$GETR8A('WKPT',NKPT,EDFTWKPT)
        IF(ALLOCATED(EDFTF)) DEALLOCATE(EDFTF)
        ALLOCATE(EDFTF(NBDYNOCC,NKPT,NSPIN))
        CALL EDFT$OCCUPATIONS(NBDYNOCC,NKPT,NSPIN,EDFTTOTCHA,EDFTISPINDEG &
     &                        ,EDFTTEMP,EDFTWKPT,EDFTF,EDFTCHMPOT,EDFTEMERMN)
        DEALLOCATE(EDFTWKPT)
      END IF
      EDFTITERRESMAX=1.D+20
      DO IKPT=1,NKPTL   ! LOCAL K-POINTS (MPI K-PARALLELIZATION)
         DO ISPIN=1,NSPIN
            CALL WAVES_SELECTWV(IKPT,ISPIN)
            CALL PLANEWAVE$SELECT(GSET%ID)
            NGL=GSET%NGL
            NBH=THIS%NBH
            NB=THIS%NB
            IF(TEDFTLIVELOCK.AND.NB.NE.NBDYNOCC) THEN
              CALL ERROR$MSG('NB FROM WAVES_MODULE INCONSISTENT WITH DYNOCC NB')
              CALL ERROR$MSG('(VESPAW_EDFT_LIVE_LOCKING ASSUMES A UNIFORM, GLOBAL NB)')
              CALL ERROR$I4VAL('NB',NB)
              CALL ERROR$I4VAL('NBDYNOCC',NBDYNOCC)
              CALL ERROR$STOP('DAVIDSON$STATE_BY_BLOCK')
            END IF
            IF(ALLOCATED(G2)) DEALLOCATE(G2)
            ALLOCATE(G2(NGL))
            CALL PLANEWAVE$GETR8A('G2',NGL,G2)

            ALLOCATE(R0(3,NAT))
            CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,R0)
!           == SUPER-WAVE-FUNCTION SUPPORT: SEE CG$STATE_BY_STATE FOR THE   ==
!           == FULL RATIONALE -- UNPACK ONCE, RUN ON GENUINE SINGLE-BAND   ==
!           == ARRAYS, REPACK BEFORE RETURNING.                            ==
            ALLOCATE(PSIU(NGL,NDIM,NB))
            ALLOCATE(PROJU(NDIM,NB,NPRO))
            TREALSUB=(NB.NE.NBH)
            IF(NB.EQ.NBH) THEN
               PSIU=THIS%PSI0
            ELSE
               CALL CG_UNPACKSUPER(NGL,NDIM,NB,NBH,THIS%PSI0,PSIU)
            END IF
            CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NB,MAP%NPRO &
                ,PSIU,PROJU)

!           == OCCUPATION WEIGHT FOR DAVIDSON_BLOCK_SWEEP'S PER-BAND       ==
!           == LOCKING TOLERANCE (SEE THAT ROUTINE'S HEADER COMMENT).      ==
!           == DEFAULT (VESPAW_EDFT_LIVE_LOCKING UNSET): HARDCODED TO 1.0  ==
!           == (FULL WEIGHT, EVERY BAND) -- AN EXACT NO-OP, THE SMOOTH     ==
!           == RAMP BELOW REDUCES TO EFFCONV=CONV/1=CONV, BIT FOR BIT      ==
!           == IDENTICAL TO THE UNWEIGHTED CRITERION THIS REPLACES.        ==
!           == WITH VESPAW_EDFT_LIVE_LOCKING SET: REAL, ALREADY-TRUSTED    ==
!           == DYNOCC OCCUPATIONS (OCCALL, FETCHED ABOVE), NORMALIZED BY   ==
!           == FMAX *AND* WKPT(IKPT) TO [0,1] -- THIS ACTUALLY AFFECTS     ==
!           == CONVERGENCE.                                                ==
            ALLOCATE(FWEIGHT(NB))
            IF(TEDFTLIVELOCK) THEN
              FWEIGHT(:)=OCCALL(:,IKPT,ISPIN) &
     &                  /MAX(FMAXVAL*WKPTARR(IKPT),1.D-10)
            ELSE
              FWEIGHT(:)=1.D0
            END IF

            CALL TIMING$CLOCKON('DAV-SWEEP')
            CALL DAVIDSON_BLOCK_SWEEP(NGL,NB,NDIM,NPRO,CONV,NSWEEPX,G2,R0 &
                ,THIS%EIGVAL,PSIU,PROJU,FWEIGHT,TCONV)
            CALL TIMING$CLOCKOFF('DAV-SWEEP')
            DEALLOCATE(FWEIGHT)

!           == EDFT SHADOW MODE: OBSERVE-ONLY, SEE THE DECLARATION-BLOCK   ==
!           == COMMENT ABOVE. USES THE JUST-CONVERGED, O-ORTHONORMAL      ==
!           == PSIU/PROJU (RAYLEIGH-RITZ GUARANTEES PSI^H*O*PSI=I AT THE  ==
!           == END OF EVERY DAVIDSON_BLOCK_SWEEP CALL, SEE ITS OWN HEADER ==
!           == COMMENT) TO BUILD HPHYS AND EVOLVE HAUX, THEN COMPARES     ==
!           == HAUX'S OWN EIGENVALUES AGAINST THE REAL EIGVAL AS A         ==
!           == CONVERGENCE DIAGNOSTIC. NOTHING HERE IS READ BACK INTO      ==
!           == PSIU/PROJU/THIS%EIGVAL/ANYTHING ELSE. (RUNS WHENEVER HAUX IS ==
!           == BEING MAINTAINED AT ALL -- TEDFTHAUXACTIVE, SEE THE          ==
!           == DECLARATION-BLOCK COMMENT -- NOT JUST UNDER SHADOW MODE      ==
!           == PROPER, SINCE THE LIVE-OCC FEED IN VESPAW_WAVES1.F90 ALSO    ==
!           == DEPENDS ON HAUX BEING KEPT UP TO DATE HERE. ONLY THE PRINT   ==
!           == BELOW IS STILL SHADOW-MODE-ONLY.)                            ==
            IF(TEDFTHAUXACTIVE) THEN
              ALLOCATE(HPHYS(NB,NB))
              ALLOCATE(EDFTRESIDUAL(NB,NB))
              ALLOCATE(HAUXEIG(NB))
              CALL EDFT_BUILDHPHYS(NGL,NDIM,NB,NPRO,PSIU,PROJU,HPHYS)
              CALL EDFT$INIBLOCK(IKPT,ISPIN,NB,NKPT,NSPIN,THIS%EIGVAL)
              CALL EDFT$HAUXFORCE(IKPT,ISPIN,HPHYS,EDFTRESIDUAL)
!             == MVP-WEIGHTED STEP ONCE A GLOBAL (CHMPOT,TEMP) IS AVAILABLE  ==
!             == (I.E. NOT THE VERY FIRST OUTER ITERATION) AND TEMP>0 (NOT   ==
!             == THE UNSMEARED, T=0 CASE, WHERE THE FERMI-DIRAC WEIGHT'S     ==
!             == 1/TEMP FACTOR IS UNDEFINED) -- OTHERWISE FALL BACK TO THE   ==
!             == ORIGINAL UNIFORM-WEIGHT STEP.                                ==
              IF(TEDFTHAUXREADY.AND.EDFTTEMP.GT.0.D0.AND..NOT.TEDFTFORCEUNIFORM) THEN
                IF(TEDFTMVPRAWWEIGHT) THEN
                  CALL EDFT$HAUXSTEP_MVP(0.3D0,IKPT,ISPIN,EDFTCHMPOT,EDFTTEMP &
     &                                  ,EDFTRESIDUAL)
                ELSE
                  CALL EDFT$HAUXSTEP_ADAPTIVE(0.3D0,IKPT,ISPIN,EDFTCHMPOT &
     &                                       ,EDFTTEMP,EDFTRESIDUAL)
                END IF
              ELSE
                CALL EDFT$HAUXSTEP(0.3D0,IKPT,ISPIN,EDFTRESIDUAL)
              END IF
              CALL EDFT$HAUXEIG(IKPT,ISPIN,NB,HAUXEIG)
              EDFTMAXDIFF=0.D0
              DO IB_EDFT=1,NB
                EDFTMAXDIFF=MAX(EDFTMAXDIFF,ABS(HAUXEIG(IB_EDFT)-THIS%EIGVAL(IB_EDFT)))
              ENDDO
!             == FERMI-WINDOW-RESTRICTED VERSION, SEE DECLARATION-BLOCK       ==
!             == COMMENT. ONLY MEANINGFUL ONCE EDFTF (THIS ITERATION'S       ==
!             == DIAGNOSTIC OCCUPATIONS) IS AVAILABLE -- I.E. NOT THE VERY   ==
!             == FIRST OUTER ITERATION.                                       ==
              EDFTMAXDIFF_FERMI=0.D0
              NFERMIACT_EDFT=0
              IF(ALLOCATED(EDFTF)) THEN
                DO IB_EDFT=1,NB
                  IF(EDFTF(IB_EDFT,IKPT,ISPIN)*(1.D0-EDFTF(IB_EDFT,IKPT,ISPIN)) &
     &               .GT.FERMIACT_THRESH) THEN
                    NFERMIACT_EDFT=NFERMIACT_EDFT+1
                    EDFTMAXDIFF_FERMI=MAX(EDFTMAXDIFF_FERMI &
     &                                   ,ABS(HAUXEIG(IB_EDFT)-THIS%EIGVAL(IB_EDFT)))
                  END IF
                ENDDO
              END IF
              IF(NFERMIACT_EDFT.GT.0) THEN
                IF(EDFTITERRESMAX.GT.1.D+19) EDFTITERRESMAX=0.D0
                EDFTITERRESMAX=MAX(EDFTITERRESMAX,EDFTMAXDIFF_FERMI)
              END IF
              IF(TEDFTSHADOW) THEN
                PRINT*,'EDFT SHADOW: IKPT=',IKPT,' ISPIN=',ISPIN &
     &                ,' MAX|HAUXEIG-EIGVAL|(ALL)=',EDFTMAXDIFF &
     &                ,' (FERMI-WINDOW N=',NFERMIACT_EDFT,')=',EDFTMAXDIFF_FERMI
              END IF
              DEALLOCATE(HPHYS)
              DEALLOCATE(EDFTRESIDUAL)
              DEALLOCATE(HAUXEIG)
            END IF

            IF(NB.EQ.NBH) THEN
               THIS%PSI0=PSIU
            ELSE
               CALL CG_PACKSUPER(NGL,NDIM,NB,NBH,PSIU,THIS%PSI0)
            END IF
            CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NBH,MAP%NPRO &
                ,THIS%PSI0,THIS%PROJ)
            IF(TPROJWB.AND.NAT.GE.8) THEN
              IPRO8AWB=1
              DO IATWB=1,7
                IPRO8AWB=IPRO8AWB+MAP%LMNX(MAP%ISP(IATWB))
              ENDDO
              IPRO8BWB=IPRO8AWB+MAP%LMNX(MAP%ISP(8))-1
              NORM8WB=MAXVAL(ABS(THIS%PROJ(:,:,IPRO8AWB:IPRO8BWB)))
              PRINT*,'VESPAW_DAV_PSISURV_RQ_PROJWRITEBACK IKPT=',IKPT &
     &              ,' ISPIN=',ISPIN,' NB=',NB,' NBH=',NBH &
     &              ,' MAX|PROJ(IAT=8,JUST-WRITTEN)|=',NORM8WB
            END IF
            DEALLOCATE(R0)
            DEALLOCATE(PSIU)
            DEALLOCATE(PROJU)
         END DO
      END DO
      IF(TEDFTLIVELOCK) THEN
        DEALLOCATE(OCCALL)
        DEALLOCATE(WKPTARR)
      END IF
      IF(TEDFTHAUXACTIVE) THEN
        TEDFTHAUXREADY=.TRUE.
        CALL EDFT$SETHAUXRESMAX(EDFTITERRESMAX)
      END IF
      DEALLOCATE(DH)
      DEALLOCATE(V)
      IF(TDEBUG) THEN
        PRINT*,'DAVIDSON FINISHED !!'
        PRINT*,'DAVIDSON EPS:',THIS%EIGVAL*27.211386245988D0
      END IF
      IF(.NOT.TCONV) THEN
!        == NOT FATAL: SEE THE SAME REASONING IN CG$STATE_BY_STATE -- THE  ==
!        == MIXER'S OWN TCONV GOVERNS OUTER-LOOP CONVERGENCE.              ==
        IF(TDEBUG) PRINT*, &
     &    'DAVIDSON BLOCK NOT CONVERGED -- CONTINUING TO NEXT OUTER ITERATION'
      END IF
      END SUBROUTINE DAVIDSON$STATE_BY_BLOCK
