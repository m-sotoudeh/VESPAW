      SUBROUTINE EDFT$STATE_BY_BLOCK(NRL_,NDIMD_,V_,CONV,NAT_,LMNXX_,DH_)
!     ******************************************************************
!     ** REAL, LIVE JOINT ORBITAL+OCCUPATION OPTIMIZER (OPTIMIZER='EDFT'),**
!     ** IMPLEMENTING THE ACTUAL MARZARI-VANDERBILT-PAYNE SCHEME (PRL 79, **
!     ** 1337 (1997)) THIS PROJECT'S EDFT PROTOTYPE HAS BEEN BUILDING     **
!     ** TOWARD ALL ALONG -- SEE THE DEV NOTES FOR THE FULL HISTORY   **
!     ** (SHADOW MODE, THEN A LIVE OCCUPATION FEED BOLTED ONTO THE        **
!     ** UNCHANGED DAVIDSON OPTIMIZER, NOW THIS: A GENUINE JOINT UPDATE). **
!     **                                                                 **
!     ** KEY THEORETICAL POINT THIS ROUTINE RESTS ON: WHEN TRIAL ORBITALS **
!     ** CARRY UNEQUAL OCCUPATION WEIGHT, ROTATING BETWEEN TWO OF THEM     **
!     ** CHANGES THE TOTAL ENERGY -- UNLIKE THE INSULATOR CASE, WHERE ANY  **
!     ** ORTHONORMAL BASIS OF THE OCCUPIED SUBSPACE IS EQUIVALENT. MVP'S   **
!     ** RESOLUTION: THE ORBITAL GRADIENT ITSELF NEEDS NO OCCUPATION       **
!     ** WEIGHTING AT ALL -- IT STAYS THE SAME UNITARY-INVARIANT PROJECTED **
!     ** RESIDUAL H|PSI_I>-SUM_J|PSI_J><PSI_J|H|PSI_I> ANY ORDINARY         **
!     ** OPTIMIZER ALREADY COMPUTES (EXACTLY WHAT DAVIDSON_BLOCK_SWEEP'S    **
!     ** OWN POST-RAYLEIGH-RITZ RESIDUAL H|PSI_I>-EPS_I*O|PSI_I> ALREADY IS **
!     ** -- CALLED BELOW UNCHANGED, WITH F(:)=1 UNIFORMLY, ITS DOCUMENTED   **
!     ** NO-OP CASE). ALL THE OCCUPATION-DEPENDENT PHYSICS INSTEAD LIVES   **
!     ** IN THE AUXILIARY HAMILTONIAN HAUX: ITS EIGENVECTORS DEFINE THE    **
!     ** "NATURAL ORBITALS" THE TRIAL SUBSPACE MUST BE ROTATED INTO (A     **
!     ** UNITARY ROTATION, SAFE -- PRESERVES O-ORTHONORMALITY EXACTLY,     **
!     ** SAME PRINCIPLE AS CG_SUBSPACEROTATE'S OWN ROTATION-BY-EIGENVECTORS **
!     ** A FEW SUBROUTINES ABOVE), AND ITS FERMI-FILLED EIGENVALUES ARE    **
!     ** THE OCCUPATIONS THAT ACTUALLY DETERMINE THE DENSITY (FED TO       **
!     ** DYNOCC VIA THE SAME LIVE-OCCUPATION SUBSTITUTION IN               **
!     ** VESPAW_WAVES1.F90'S WAVES$ETOT ALREADY BUILT FOR VESPAW_EDFT_     **
!     ** LIVE_OCC, NOW ALSO UNCONDITIONAL FOR OPTIMIZERTYPE='EDFT').       **
!     **                                                                 **
!     ** PER-BLOCK ALGORITHM EACH OUTER ITERATION:                        **
!     **  A) ORBITAL STEP: DAVIDSON_BLOCK_SWEEP, UNMODIFIED, F(:)=1.       **
!     **  B) SEED/EVOLVE HAUX TOWARD THE JUST-UPDATED SUBSPACE HAMILTONIAN **
!     **     (EDFT_BUILDHPHYS/EDFT$HAUXFORCE/EDFT$HAUXSTEP_ADAPTIVE, ALL    **
!     **     UNCHANGED FROM THE SHADOW-MODE MACHINERY). VESPAW_EDFT_MVP_    **
!     **     EXACT (OFF BY DEFAULT) SWITCHES THIS STEP TO EDFT$HAUXSTEP_    **
!     **     MVPEXACT -- THE VERIFIED TRUE dF/dHAUX, SEE THE DEV NOTES **
!     **     -- INSTEAD OF THE HEURISTIC ADAPTIVE STEP, FOR A/B TESTING    **
!     **     WHETHER A CORRECT GRADIENT IS ALSO A STABLE FIXED-LAMBDA_HAUX **
!     **     STEP ON A REAL SYSTEM. VESPAW_EDFT_ANDERSON (OFF BY DEFAULT,   **
!     **     TAKES PRIORITY OVER VESPAW_EDFT_MVP_EXACT/LAMBDA_HAUX IF SET)  **
!     **     REPLACES THE STEP ENTIRELY WITH EDFT$HAUXSTEP_ANDERSON --      **
!     **     SELF-TUNING DAMPING VIA RESTARTED-DIIS ANDERSON MIXING, NO     **
!     **     LAMBDA_HAUX INVOLVED AT ALL -- SEE THAT ROUTINE'S OWN HEADER   **
!     **     COMMENT AND THE DEV NOTES FOR WHY (NO SINGLE LAMBDA_HAUX   **
!     **     VALUE WORKED ACROSS BOTH TEST SYSTEMS FOR MVPEXACT).           **
!     **  C) DIAGONALIZE HAUX (EDFT$HAUXEIGVEC) AND ROTATE THE TRIAL       **
!     **     ORBITALS INTO ITS EIGENBASIS.                                 **
!     **  D) WRITE BACK, IDENTICAL TAIL TO DAVIDSON$STATE_BY_BLOCK.        **
!     **                                                                 **
!     ** OPEN RISKS, NOT SILENTLY RESOLVED (SEE THE DEV NOTES):        **
!     **  - THIS IS THE FIRST TIME HAUX FEEDS BACK INTO PSI ITSELF (EVERY   **
!     **    EARLIER VALIDATION HAD HAUX PASSIVELY OBSERVING AN             **
!     **    INDEPENDENTLY-CONVERGING DAV TRAJECTORY) -- A GENUINELY NEW,    **
!     **    PREVIOUSLY-UNTESTED TWO-WAY COUPLING.                          **
!     **  - THE REAL MVP BENEFIT IS EXPECTED PRE-SELF-CONSISTENCY, NOT AT   **
!     **    CONVERGENCE (WHERE HPHYS BECOMES NEARLY DIAGONAL REGARDLESS OF  **
!     **    OCCUPATION STRUCTURE AND THE ROTATION APPROACHES THE IDENTITY). **
!     **  - F(:)=1 UNIFORMLY IN THE ORBITAL STEP MEANS NO LOCKING-TOLERANCE **
!     **    COMPUTE SAVINGS ON NEAR-EMPTY BANDS IN THIS FIRST VERSION.      **
!     **  - INHERITS THE SAME (PRE-EXISTING, WHOLE-CODEBASE) K-POINT-       **
!     **    PARALLEL-MPI LIMITATION AS CG/DAV/RMM: LOOPS THE GLOBAL NKPT,   **
!     **    NOT ADDRESSED HERE.                                             **
!     ******************************************************************
      USE CG_INTERFACE_MODULE
      USE WAVES_MODULE
      IMPLICIT NONE
      INTEGER(4)                :: NTASKSEDFT,THISTASKEDFT
      INTEGER(4)   , INTENT(IN)      :: NRL_
      INTEGER(4)   , INTENT(IN)      :: NDIMD_
      REAL(8)      , INTENT(IN)      :: V_(NRL_,NDIMD_)
      REAL(8)      , INTENT(INOUT)   :: CONV
      INTEGER(4)   , INTENT(IN)      :: NAT_
      INTEGER(4)   , INTENT(IN)      :: LMNXX_
      COMPLEX(8)   , INTENT(IN)      :: DH_(LMNXX_,LMNXX_,NDIMD_,NAT_)
      LOGICAL(4)                     :: TCONV
      INTEGER(4)                     :: NGL,NB,NBH,NPRO
      INTEGER(4)                     :: NSWEEPX
      REAL(8)     ,ALLOCATABLE       :: G2(:)
      REAL(8)     ,ALLOCATABLE       :: R0(:,:)
      COMPLEX(8)  ,ALLOCATABLE       :: PSIU(:,:,:)
      COMPLEX(8)  ,ALLOCATABLE       :: PROJU(:,:,:)
      REAL(8)     ,ALLOCATABLE       :: FWEIGHT(:)
      LOGICAL(4)                     :: TDEBUG
!     == HAUX DAMPING STEP -- CARRIED OVER UNCHANGED FROM THE EARLIER, PASSIVE ==
!     == SHADOW/LIVE-OCC VALIDATION, WHERE HAUX NEVER FED BACK INTO PSI. NOW  ==
!     == THAT PSI IS ROTATED BY HAUX'S OWN EIGENVECTORS EVERY ITERATION (STEP ==
!     == C BELOW), THE (PSI,HAUX) SYSTEM IS A GENUINE TWO-WAY COUPLED         ==
!     == RECURSION -- NOT GUARANTEED STABLE AT THE SAME DAMPING THAT WAS FINE ==
!     == FOR THE DECOUPLED CASE. RUNTIME-CONFIGURABLE (VESPAW_EDFT_LAMBDA_    ==
!     == HAUX) SO THIS CAN BE SWEPT WITHOUT RECOMPILING WHILE DIAGNOSING THE  ==
!     == RUN-TO-RUN ITERATION-COUNT SCATTER FOUND ON THE AL METAL TEST (SEE   ==
!     == THE DEV NOTES).                                                 ==
      LOGICAL(4)  ,SAVE              :: TLAMBDAHAUXCHECKED=.FALSE.
      REAL(8)     ,SAVE              :: LAMBDA_HAUX=0.3D0
      CHARACTER(32)                  :: CENVVALLAMBDA
      LOGICAL(4)  ,SAVE              :: TEDFTHAUXREADY=.FALSE.
      REAL(8)                        :: EDFTTEMP
      REAL(8)     ,SAVE              :: EDFTCHMPOT=0.D0
      REAL(8)                        :: EDFTTOTCHA
      INTEGER(4)                     :: EDFTISPINDEG
      REAL(8)                        :: FMAXVAL
      INTEGER(4)                     :: NBDYNOCC
      REAL(8)     ,ALLOCATABLE       :: EDFTWKPT(:)
      REAL(8)     ,ALLOCATABLE,SAVE  :: EDFTF(:,:,:)
      REAL(8)                        :: EDFTEMERMN
      COMPLEX(8)  ,ALLOCATABLE       :: HPHYS(:,:)
      COMPLEX(8)  ,ALLOCATABLE       :: EDFTRESIDUAL(:,:)
      REAL(8)     ,ALLOCATABLE       :: EIGVALNAT(:)
      COMPLEX(8)  ,ALLOCATABLE       :: UNAT(:,:)
      COMPLEX(8)  ,ALLOCATABLE       :: PSINAT(:,:,:)
      INTEGER(4)                     :: IB1,IB2
!     == MVP-EXACT OVERRIDE: DIAGNOSTIC-ONLY LEVER, OFF BY DEFAULT, TO SWITCH  ==
!     == THE HAUX STEP FROM THE DEFAULT EDFT$HAUXSTEP_ADAPTIVE (A HEURISTIC,   ==
!     == GATE-WEIGHTED RESIDUAL) TO EDFT$HAUXSTEP_MVPEXACT (THE VERIFIED TRUE  ==
!     == dF/dHAUX -- SEE THE DEV NOTES AND TESTS/UNITTESTS/                ==
!     == EDFT_GRADIENT_CHECK FOR THE DERIVATION AND VALIDATION). A CORRECT     ==
!     == GRADIENT IS NOT AUTOMATICALLY A STABLE FIXED-LAMBDA_HAUX STEP, SO     ==
!     == THIS IS DELIBERATELY OPT-IN, NOT THE DEFAULT, UNTIL ITS OWN STABILITY ==
!     == IS CHARACTERIZED THE SAME WAY LAMBDA_HAUX=0.1 WAS FOR THE ADAPTIVE    ==
!     == STEP.                                                                ==
      LOGICAL(4)  ,SAVE              :: TEDFTMVPEXACTCHECKED=.FALSE.
      LOGICAL(4)  ,SAVE              :: TEDFTMVPEXACT=.FALSE.
      CHARACTER(16)                  :: CENVVALMVPEXACT
!     == ANDERSON-MIXING OVERRIDE: DIAGNOSTIC-ONLY LEVER, OFF BY DEFAULT, TO   ==
!     == REPLACE THE HAUX STEP ENTIRELY WITH EDFT$HAUXSTEP_ANDERSON --        ==
!     == SELF-TUNING DAMPING (NO LAMBDA_HAUX INVOLVED AT ALL), SAME           ==
!     == RESTARTED-DIIS ANDERSON RECIPE ALREADY VALIDATED FOR DENSITY MIXING  ==
!     == (SEE VESPAW_MIXER.F90 AND EDFT$HAUXSTEP_ANDERSON'S OWN HEADER        ==
!     == COMMENT). TAKES PRIORITY OVER TEDFTMVPEXACT/LAMBDA_HAUX IF BOTH ARE  ==
