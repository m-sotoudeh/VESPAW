!     == ORBITAL, SO IT CONVERGES ONTO WHICHEVER EIGENVECTOR IS *NEAREST* THAT ==
!     == BAD EPS GUESS, NOT THE TRUE GROUND STATE -- AND ONCE THE RESULTING    ==
!     == (WRONG) STATE'S RESIDUAL DROPS BELOW CONV IT LOCKS AND NEVER GETS     ==
!     == REVISITED, SINCE EACH OUTER-ITERATION CALL RE-SEEDS EPS FROM THAT     ==
!     == SAME (STILL WRONG) ORBITAL. CONFIRMED DIRECTLY: TESTS/SI_EDFT/        ==
!     == RMM_DIAG SHOWED 5 OF 8 BAND EIGENVALUES (INCLUDING THE LOWEST,        ==
!     == OCCUPIED ONE) FROZEN BIT-FOR-BIT AT UNPHYSICAL +20 TO +51 EV ACROSS   ==
!     == 25 OUTER ITERATIONS FROM A COLD START, VS. A CLEAN, MONOTONIC         ==
!     == CONVERGENCE TO THE CORRECT ENERGY WHEN THE SAME RMM STEP IS INSTEAD   ==
!     == WARM-STARTED FROM A RESTART DAVIDSON HAD ALREADY PARTIALLY CONVERGED  ==
!     == (SANE, NEGATIVE-TO-FEW-EV EIGENVALUES THROUGHOUT). FIX: RUN THE FIRST ==
!     == VESPAW_EDFT_RMM_DELAY OUTER ITERATIONS' STEP A WITH THE GLOBALLY-     ==
!     == CONVERGENT DAVIDSON_BLOCK_SWEEP REGARDLESS OF VESPAW_EDFT_RMM_STEP,   ==
!     == THEN SWITCH TO RMM -- EXACTLY RMMDELAY'S OWN CG-THEN-RMM PATTERN,     ==
!     == JUST WITH DAVIDSON IN PLACE OF CG SINCE THAT'S EDFT'S OWN DEFAULT     ==
!     == STEP A. DEFAULTS TO 10 (NOT 0) WHEN VESPAW_EDFT_RMM_STEP IS SET,      ==
!     == SINCE THE 0-DELAY (IMMEDIATE COLD RMM) CASE IS EXACTLY WHAT WAS JUST  ==
!     == SHOWN BROKEN -- UNLIKE RMMDELAY, WHERE 0 IS A DELIBERATE, STILL-VALID ==
!     == "MATCH EXISTING INPUT FILES" DEFAULT FOR AN OPTIMIZER THAT PREDATES   ==
!     == THIS FINDING. SET VESPAW_EDFT_RMM_DELAY=0 TO FORCE THE OLD (BROKEN)   ==
!     == COLD-START BEHAVIOR BACK, E.G. FOR REGRESSION COMPARISON.             ==
      LOGICAL(4)  ,SAVE              :: TEDFTRMMDELAYCHECKED=.FALSE.
      INTEGER(4)  ,SAVE              :: EDFTRMMDELAY=10
      INTEGER(4)  ,SAVE              :: EDFTRMMDELAYCOUNT=0
      CHARACTER(16)                  :: CENVVALRMMDELAY
      LOGICAL(4)                     :: TUSERMMNOW
      REAL(8)     ,ALLOCATABLE,SAVE  :: EIGVALPREV(:,:,:)   ! (NB,NKPT,NSPIN)
      LOGICAL(4)  ,SAVE              :: THAUXDIAGALLOCATED=.FALSE.
      REAL(8)                        :: DIAGMAXDELTA
      INTEGER(4)                     :: DIAGMAXIKPT,DIAGMAXISPIN,DIAGMAXIB
      REAL(8)                        :: DIAGMAXF,DIAGMAXEIG,DIAGMAXHPHYS
      REAL(8)                        :: DIAGMAXGATE
      INTEGER(4)                     :: IBDIAG
      COMPLEX(8)  ,ALLOCATABLE       :: HPHYSROT(:,:)
      REAL(8)                        :: DIAGSVAR,DIAGEX,DIAGWEIGHT
!     ******************************************************************
      CALL MPE$QUERY('MONOMER',NTASKSEDFT,THISTASKEDFT)
      IF(NTASKSEDFT.GT.1) THEN
        CALL ERROR$MSG('OPTIMIZER EDFT IS NOT YET AVAILABLE FOR MPI RUNS')
        CALL ERROR$MSG('(OCCUPATIONS NEED ALL K-POINTS); USE DAV, RMM OR CG')
        CALL ERROR$STOP('EDFT')
      END IF
      IF(.NOT.TLAMBDAHAUXCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_LAMBDA_HAUX',CENVVALLAMBDA)
        IF(LEN_TRIM(CENVVALLAMBDA).GT.0) THEN
          READ(CENVVALLAMBDA,*) LAMBDA_HAUX
          PRINT*,'VESPAW_EDFT_LAMBDA_HAUX SET -- USING LAMBDA_HAUX=',LAMBDA_HAUX
        END IF
        TLAMBDAHAUXCHECKED=.TRUE.
      END IF
      IF(.NOT.TEDFTMVPEXACTCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_MVP_EXACT',CENVVALMVPEXACT)
        TEDFTMVPEXACT=(LEN_TRIM(CENVVALMVPEXACT).GT.0)
        TEDFTMVPEXACTCHECKED=.TRUE.
        IF(TEDFTMVPEXACT) THEN
          PRINT*,'VESPAW_EDFT_MVP_EXACT SET -- USING EDFT$HAUXSTEP_MVPEXACT' &
     &          ,' (THE VERIFIED TRUE dF/dHAUX) INSTEAD OF EDFT$HAUXSTEP_ADAPTIVE'
        END IF
      END IF
      IF(.NOT.TEDFTANDERSONCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_ANDERSON',CENVVALANDERSON)
        TEDFTANDERSON=(LEN_TRIM(CENVVALANDERSON).GT.0)
        TEDFTANDERSONCHECKED=.TRUE.
        IF(TEDFTANDERSON) THEN
          PRINT*,'VESPAW_EDFT_ANDERSON SET -- USING EDFT$HAUXSTEP_ANDERSON' &
     &          ,' (SELF-TUNING DAMPING, LAMBDA_HAUX/MVP_EXACT IGNORED)'
        END IF
      END IF
      IF(.NOT.TEDFTHAUXDIAGCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_HAUX_DIAG',CENVVALHAUXDIAG)
        TEDFTHAUXDIAG=(LEN_TRIM(CENVVALHAUXDIAG).GT.0)
        TEDFTHAUXDIAGCHECKED=.TRUE.
        IF(TEDFTHAUXDIAG) THEN
          PRINT*,'VESPAW_EDFT_HAUX_DIAG SET -- TRACKING HAUX EIGENVALUE DRIFT' &
     &          ,' PER ITERATION (PURE DIAGNOSTIC, NO EFFECT ON THE RUN)'
        END IF
      END IF
      IF(.NOT.TEDFTRESGATECHECKED) THEN
