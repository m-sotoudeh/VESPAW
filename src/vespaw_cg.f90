!     ..................................................................
      SUBROUTINE EDFT_SUMKGROUPS(X)
!     ** SUMS A SCALAR ACCUMULATED OVER THE LOCAL K-POINTS OVER ALL      **
!     ** K-GROUPS. X IS IDENTICAL ON ALL TASKS OF A K-GROUP, SO ONLY THE **
!     ** FIRST TASK OF EACH K-GROUP CONTRIBUTES TO THE MONOMER SUM.      **
      USE MPE_MODULE
      IMPLICIT NONE
      REAL(8),INTENT(INOUT) :: X
      INTEGER(4)            :: NTASKSK,THISTASKK
!     ******************************************************************
      CALL MPE$QUERY('K',NTASKSK,THISTASKK)
      IF(THISTASKK.NE.1) X=0.D0
      CALL MPE$COMBINE('MONOMER','+',X)
      RETURN
      END
