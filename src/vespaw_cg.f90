MODULE CG_INTERFACE_MODULE
INTEGER (4)    :: IKPT
INTEGER (4)    :: ISPIN
INTEGER(4)     :: NAT
INTEGER(4)     :: LMNXX
COMPLEX(8) ,ALLOCATABLE :: DH(:,:,:,:) ! (LMNXX,LMNXX,NDIMD,NAT)
!INTEGER(4)     :: NPRO
INTEGER(4)               :: NRL
REAL(8) ,ALLOCATABLE :: V(:,:) ! (NRL,NDIMD)
LOGICAL(4)               :: TSAVEMEM=.FALSE.
! SUPER-WAVE-FUNCTION K-POINT (TRIM/GAMMA, NB>NBH): EVERY BAND MUST STAY A
! REAL FUNCTION SO THAT IT CAN BE REPACKED AS A+I*B. THE SUBSPACE MATRICES
! BETWEEN REAL FUNCTIONS ARE REAL; THEIR ROUNDOFF IMAGINARY PARTS ARE REMOVED
! BEFORE EACH DIAGONALIZATION, OTHERWISE EXACTLY DEGENERATE BANDS (E.G. WITH
! SPACE-GROUP SYMMETRIZATION) COME OUT AS COMPLEX MIXTURES AND THE REPACKING
! DESTROYS THEM.
LOGICAL(4)               :: TREALSUB=.FALSE.
!LOGICAL(4)               :: TSAVEMEM=.TRUE.
! AVOID RECALCULATION OF PROJECTIONS
!COMPLEX(8)  ,ALLOCATABLE :: PROJ(:,:)
LOGICAL(4)               :: TNEWPRO=.TRUE.
! AVOID RECALCULATION OF OPSI(OLD)
COMPLEX(8)  ,ALLOCATABLE :: OPSIOLD(:,:) ! (NB,NGL)
END MODULE CG_INTERFACE_MODULE


!
!     ..................................................................
      SUBROUTINE CG$STATE_BY_STATE(NRL_,NDIMD_,V_,CONV,NAT_,LMNXX_,DH_)
!     ******************************************************************
!     ** INTERFACE SUBROUTINE                                         **
!     ******************************************************************
      USE CG_INTERFACE_MODULE
      USE WAVES_MODULE
      IMPLICIT NONE
      INTEGER(4)   , INTENT(IN)   :: NRL_
      INTEGER(4)   , INTENT(IN)   :: NDIMD_
      REAL(8)      , INTENT(IN)   :: V_(NRL_,NDIMD_)
      REAL(8)      , INTENT(INOUT)   :: CONV 
      INTEGER(4)   , INTENT(IN)   :: NAT_
      INTEGER(4)   , INTENT(IN)   :: LMNXX_
      COMPLEX(8)   , INTENT(IN)   :: DH_(LMNXX_,LMNXX_,NDIMD_,NAT_)
      LOGICAL(4)                  :: TCONV
      INTEGER(4)                  :: NGL,NB,NBH,IB,NPRO
      INTEGER(4)                  :: NITERX
      REAL(8)     ,ALLOCATABLE    :: G2(:) ! (NGL)
      REAL(8)     ,ALLOCATABLE    :: R0(:,:)
      COMPLEX(8)  ,ALLOCATABLE    :: PSIU(:,:,:)  ! (NGL,NDIM,NB) UNPACKED
      COMPLEX(8)  ,ALLOCATABLE    :: PROJU(:,:,:) ! (NDIM,NB,NPRO) UNPACKED
      LOGICAL(4)                  :: TDEBUG  ! !CONTROL!GENERIC VERBOSITY='DEBUG'
!     ******************************************************************
      CALL VERBOSITY$GETL4('DEBUG',TDEBUG)
      IF(NDIM.NE.1) THEN
         CALL ERROR$I4VAL('NDIMD',NDIMD)
         CALL ERROR$MSG('NON-COLLINEAR CG NOT IMPLEMENTED')
         CALL ERROR$STOP('CG$STATE_BY_STATE')
      END IF
      NAT=NAT_
      LMNXX=LMNXX_
      ALLOCATE(DH(LMNXX,LMNXX,NDIMD,NAT))
      DH=DH_
      NPRO=MAP%NPRO

      NRL=NRL_
      ALLOCATE(V(NRL,NDIMD_))
      V=V_
IF(TDEBUG) WRITE(*,"('CG-MIXER: POT   :',3F10.7)") V(1:3,1)
      NITERX=30 !400
      DO IKPT=1,NKPTL   ! LOCAL K-POINTS (MPI K-PARALLELIZATION)
         DO ISPIN=1,NSPIN
            CALL WAVES_SELECTWV(IKPT,ISPIN)
            CALL PLANEWAVE$SELECT(GSET%ID) 
            NGL=GSET%NGL
            NBH=THIS%NBH !TAKE CARE OF SUPER WAVE FUNCTIONS!!
            NB=THIS%NB
            !ALLOCATE(THIS%EIGVAL(NB))
            !ALLOCATE(PROJ(NDIM,NPRO))
            IF((.NOT.TSAVEMEM).AND.(NB.GT.1)) THEN
               PRINT*,'SAVEMEM=FALSE, ALLOCATING ',NB*NGL*16.D0/1024.D0,' KB'
               ALLOCATE(OPSIOLD(NB-1,NGL))
            END IF
            !IF(.NOT.ASSOCIATED(THIS%HPSI))ALLOCATE(THIS%HPSI(NGL,NDIM,NBH))
            IF(ALLOCATED(G2)) DEALLOCATE(G2) !NEW GSET?
            ALLOCATE(G2(NGL))
            CALL PLANEWAVE$GETR8A('G2',NGL,G2)
            !G2(:)=1.D0 ! IF THIS LINE IS USED, PRECONDITIONING IS AVOIDED
!!$            ! IF THE FOLLOWING LOOP IS USED, START FROM RANDOM WF
!!$            DO IB=1,NB
!!$               CONV=1.D-8
!!$               CALL WAVES_RANDOMIZE(NGL,1,1,1.D4,G2,THIS%PSI0(:,1,IB))
!!$            END DO

            ALLOCATE(R0(3,NAT))
            CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,R0)
!           == RAYLEIGH-RITZ SUBSPACE ROTATION -- SAME ROLE THIS STEP PLAYS  ==
!           == IN VASP'S BLOCKED-DAVIDSON/RMM-DIIS SCHEME. WITHOUT IT,      ==
!           == (NEAR-)DEGENERATE BANDS CANNOT BE SEPARATED BY THE SEQUENTIAL==
!           == SINGLE-BAND CG BELOW AND ITS LINE SEARCH CAN OSCILLATE       ==
!           == INDEFINITELY INSTEAD OF CONVERGING (OBSERVED ON H2'S         ==
!           == UNOCCUPIED BAND PAIR).                                      ==
!
!           == SUPER-WAVE-FUNCTION (NB>NBH, TRIM/GAMMA K-POINT) SUPPORT:    ==
!           == THIS%PSI0/THIS%PROJ PACK 2 REAL BANDS PER COMPLEX SLOT       ==
!           == (PSI_PACKED=PSI_2J-1+I*PSI_2J), EXPLOITING PSI(-G)=PSI(G)*.  ==
!           == BOTH H AND O ARE REAL-LINEAR OPERATORS FOR A COLLINEAR,      ==
!           == NON-HYBRID SYSTEM, SO THEY COMMUTE WITH THIS PACKING:        ==
!           == H(A+IB)=H(A)+I*H(B). THE PER-BAND CG BELOW NEEDS INDIVIDUAL  ==
!           == RAYLEIGH QUOTIENTS, WHICH THE PACKED <PSI|H|PSI> CANNOT      ==
!           == GIVE (IT RETURNS <A|H|A>+<B|H|B>, THE SUM). SO WE UNPACK     ==
!           == ONCE INTO NB GENUINE SINGLE-BAND ARRAYS (PLANEWAVE$UNSUPER,  ==
!           == USING THE SAME G/-G RECONSTRUCTION THE REST OF THE CODE     ==
!           == USES), RUN THE EXISTING PER-BAND MACHINERY UNCHANGED ON      ==
!           == THOSE (EACH IS THEN JUST AN ORDINARY WAVEFUNCTION AS FAR AS  ==
!           == WAVES_HPSI/WAVES_OPSI/WAVES_PROJECTIONS ARE CONCERNED --     ==
!           == FEEDING ONE UNPACKED BAND WITH NBH_ARG=1 IS THE SAME AS      ==
!           == FEEDING A PACKED SLOT WHOSE PARTNER IS IDENTICALLY ZERO),    ==
!           == THEN REPACK (PACKING IS THE TRIVIAL INVERSE, C=A+I*B, NO     ==
!           == G/-G RECONSTRUCTION NEEDED) BEFORE HANDING BACK TO WAVES$ETOT==
            ALLOCATE(PSIU(NGL,NDIM,NB))
            ALLOCATE(PROJU(NDIM,NB,NPRO))
            TREALSUB=(NB.NE.NBH)
            IF(NB.EQ.NBH) THEN
               PSIU=THIS%PSI0
            ELSE
               CALL CG_UNPACKSUPER(NGL,NDIM,NB,NBH,THIS%PSI0,PSIU)
            END IF
            CALL TIMING$CLOCKON('CG-PRO1')
            CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NB,MAP%NPRO &
                ,PSIU,PROJU)
            CALL TIMING$CLOCKOFF('CG-PRO1')
            CALL CG_SUBSPACEROTATE(NGL,NDIM,NB,NB,NPRO,R0,PSIU,PROJU,THIS%EIGVAL)

            CALL CG_STATE_BY_STATE(NGL,NB,NDIM,NPRO,CONV,NITERX,G2,&
                 THIS%EIGVAL, &
                 PSIU,TCONV)
            CALL TIMING$CLOCKON('CG-PRO2')
            IF(NB.EQ.NBH) THEN
               THIS%PSI0=PSIU
            ELSE
               CALL CG_PACKSUPER(NGL,NDIM,NB,NBH,PSIU,THIS%PSI0)
            END IF
            CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NBH,MAP%NPRO &
                ,THIS%PSI0,THIS%PROJ)
            DEALLOCATE(R0)
            DEALLOCATE(PSIU)
            DEALLOCATE(PROJU)
            CALL TIMING$CLOCKOFF('CG-PRO2')
            IF(.NOT.TSAVEMEM) THEN
               DEALLOCATE(OPSIOLD)
            END IF
         END DO
      END DO
      DEALLOCATE(DH)
      DEALLOCATE(V)
      IF(TDEBUG) THEN
        PRINT*,'CG FINISHED !!'
        PRINT*,'CG EPS:',THIS%EIGVAL*27.211386245988D0
      END IF
      !CALL ERROR$STOP(' BREAK IN CG$STATE_BY_STATE')
      IF(.NOT.TCONV) THEN
!        == NOT FATAL: A BAND MISSING NITERX IS EXPECTED EARLY IN THE   ==
!        == OUTER SCF CYCLE, WHILE CONVPSI IS STILL LOOSE. THE MIXER'S  ==
!        == OWN TCONV (paw_mixer.f90) GOVERNS OUTER-LOOP CONVERGENCE,   ==
!        == NOT WHETHER EVERY INNER PER-BAND SOLVE FINISHED THIS PASS.  ==
        IF(TDEBUG) &
     &    PRINT*,'CG CYCLE NOT CONVERGED -- CONTINUING TO NEXT OUTER ITERATION'
      END IF
      END SUBROUTINE CG$STATE_BY_STATE
!
!     ..................................................................
      SUBROUTINE CG_UNPACKSUPER(NGL,NDIM,NB,NBH,PSIPACKED,PSIU)
!     ******************************************************************
!     ** UNPACKS NBH SUPER-WAVE-FUNCTION SLOTS (EACH HOLDING 2 REAL     **
!     ** BANDS AS PSI_PACKED=PSI_2J-1+I*PSI_2J) INTO NB GENUINE          **
!     ** SINGLE-BAND ARRAYS, USING THE SAME G/-G RECONSTRUCTION AS       **
!     ** PLANEWAVE$UNSUPER (WHICH THIS ROUTINE CALLS DIRECTLY, ONE SLOT  **
!     ** AT A TIME -- NDIM=1 IS ENFORCED ELSEWHERE IN THIS FILE). IF NB  **
!     ** IS ODD, THE LAST SLOT HOLDS ONLY ONE REAL BAND (PACKED WITH AN  **
!     ** IMPLICIT ZERO PARTNER); ITS SECOND UNSUPER COMPONENT COMES BACK **
!     ** AS ZERO AND IS SIMPLY NOT COPIED.                               **
!     ******************************************************************
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NGL
      INTEGER(4),INTENT(IN) :: NDIM
      INTEGER(4),INTENT(IN) :: NB
      INTEGER(4),INTENT(IN) :: NBH
      COMPLEX(8),INTENT(IN) :: PSIPACKED(NGL,NDIM,NBH)
      COMPLEX(8),INTENT(OUT):: PSIU(NGL,NDIM,NB)
      COMPLEX(8)             :: PAIR(NGL,2)
      INTEGER(4)             :: J
!     ******************************************************************
      DO J=1,NBH
        CALL PLANEWAVE$UNSUPER(NGL,PSIPACKED(:,1,J),PAIR)
        PSIU(:,1,2*J-1)=PAIR(:,1)
        IF(2*J.LE.NB) PSIU(:,1,2*J)=PAIR(:,2)
      END DO
      RETURN
      END SUBROUTINE CG_UNPACKSUPER
!
!     ..................................................................
      SUBROUTINE CG_PACKSUPER(NGL,NDIM,NB,NBH,PSIU,PSIPACKED)
!     ******************************************************************
!     ** INVERSE OF CG_UNPACKSUPER. PACKING IS THE TRIVIAL DIRECTION    **
!     ** (NO G/-G RECONSTRUCTION NEEDED): SOLVING PLANEWAVE$UNSUPER'S    **
!     ** OWN DEFINING FORMULA FOR ITS INPUT GIVES PSI_PACKED=A+I*B      **
!     ** DIRECTLY. IF NB IS ODD, THE LAST SLOT'S PARTNER IS ZERO.        **
!     ******************************************************************
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NGL
      INTEGER(4),INTENT(IN) :: NDIM
      INTEGER(4),INTENT(IN) :: NB
      INTEGER(4),INTENT(IN) :: NBH
      COMPLEX(8),INTENT(IN) :: PSIU(NGL,NDIM,NB)
      COMPLEX(8),INTENT(OUT):: PSIPACKED(NGL,NDIM,NBH)
      INTEGER(4)             :: J
!     ******************************************************************
      DO J=1,NBH
        IF(2*J.LE.NB) THEN
          PSIPACKED(:,1,J)=PSIU(:,1,2*J-1)+(0.D0,1.D0)*PSIU(:,1,2*J)
        ELSE
          PSIPACKED(:,1,J)=PSIU(:,1,2*J-1)
        END IF
      END DO
      RETURN
      END SUBROUTINE CG_PACKSUPER
