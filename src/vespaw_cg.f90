        TEDFTRESGATE=(LEN_TRIM(CENVVALRESGATE).GT.0)
        TEDFTRESGATECHECKED=.TRUE.
        IF(TEDFTRESGATE) THEN
          PRINT*,'VESPAW_EDFT_RESGATE SET -- USING EDFT$HAUXSTEP_RESGATE' &
     &          ,' (ADAPTIVE + RESIDUAL-SIZE GATE FIX)'
        END IF
      END IF
      IF(.NOT.TEDFTRMMSTEPCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_RMM_STEP',CENVVALRMMSTEP)
        TEDFTRMMSTEP=(LEN_TRIM(CENVVALRMMSTEP).GT.0)
        TEDFTRMMSTEPCHECKED=.TRUE.
        IF(TEDFTRMMSTEP) THEN
          PRINT*,'VESPAW_EDFT_RMM_STEP SET -- STEP A USES RMM_DIIS_BLOCK_SWEEP' &
     &          ,' INSTEAD OF DAVIDSON_BLOCK_SWEEP'
        END IF
      END IF
      IF(.NOT.TEDFTRMMDELAYCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFT_RMM_DELAY',CENVVALRMMDELAY)
        IF(LEN_TRIM(CENVVALRMMDELAY).GT.0) THEN
          READ(CENVVALRMMDELAY,*) EDFTRMMDELAY
        END IF
        TEDFTRMMDELAYCHECKED=.TRUE.
        IF(TEDFTRMMSTEP) THEN
          PRINT*,'EDFT RMM STEP A WARM-UP: FIRST ',EDFTRMMDELAY &
     &          ,' OUTER ITERATION(S) USE DAVIDSON_BLOCK_SWEEP' &
     &          ,' (SEE TEDFTRMMDELAY HEADER COMMENT -- COLD-START RMM' &
     &          ,' CONVERGES TO A WRONG ANSWER WITHOUT THIS)'
        END IF
      END IF
      CALL VERBOSITY$GETL4('DEBUG',TDEBUG)
      IF(NDIM.NE.1) THEN
         CALL ERROR$I4VAL('NDIMD',NDIMD)
         CALL ERROR$MSG('NON-COLLINEAR EDFT NOT IMPLEMENTED')
         CALL ERROR$STOP('EDFT$STATE_BY_BLOCK')
      END IF
      CALL DYNOCC$GETR8('TEMP',EDFTTEMP)
      IF(EDFTTEMP.LE.0.D0) THEN
        CALL ERROR$MSG('OPTIMIZER=EDFT REQUIRES !CONTROL!MERMIN WITH T[K]>0')
        CALL ERROR$MSG('(THE MERMIN FREE ENERGY THIS SCHEME MINIMIZES HAS NO')
        CALL ERROR$MSG(' MEANING WITHOUT FINITE-TEMPERATURE SMEARING)')
        CALL ERROR$STOP('EDFT$STATE_BY_BLOCK')
      END IF
      NAT=NAT_
      LMNXX=LMNXX_
      ALLOCATE(DH(LMNXX,LMNXX,NDIMD,NAT))
      DH=DH_
      NPRO=MAP%NPRO
      NRL=NRL_
      ALLOCATE(V(NRL,NDIMD_))
      V=V_
      NSWEEPX=8
!     == GLOBAL (CHMPOT,TEMP), ONE PER OUTER ITERATION, FROM HAUX'S STATE AS ==
!     == IT STANDS AT THE START OF THIS ITERATION (I.E. THE END OF THE       ==
!     == PREVIOUS ONE) -- SAME PATTERN ALREADY VALIDATED IN                  ==
!     == DAVIDSON$STATE_BY_BLOCK'S SHADOW-MODE MVP-WEIGHTED STEP.            ==
      IF(TEDFTHAUXREADY) THEN
        CALL DYNOCC$GETI4('NB',NBDYNOCC)
        CALL DYNOCC$GETR8('NEL',EDFTTOTCHA)
        CALL DYNOCC$GETR8('FMAX',FMAXVAL)
        EDFTISPINDEG=NINT(FMAXVAL)
        ALLOCATE(EDFTWKPT(NKPT))
        CALL DYNOCC$GETR8A('WKPT',NKPT,EDFTWKPT)
        IF(ALLOCATED(EDFTF)) DEALLOCATE(EDFTF)
        ALLOCATE(EDFTF(NBDYNOCC,NKPT,NSPIN))
        CALL EDFT$OCCUPATIONS(NBDYNOCC,NKPT,NSPIN,EDFTTOTCHA,EDFTISPINDEG &
     &                        ,EDFTTEMP,EDFTWKPT,EDFTF,EDFTCHMPOT,EDFTEMERMN)
        DEALLOCATE(EDFTWKPT)
      END IF
!     == HAUX EIGENVALUE-DRIFT DIAGNOSTIC RESET (VESPAW_EDFT_HAUX_DIAG): SEE   ==
!     == THE PER-BLOCK ACCUMULATION SITE (STEP C, BELOW) AND THE SUMMARY      ==
!     == PRINT AFTER THE PER-BLOCK LOOP FOR THE FULL RATIONALE. PURE          ==
!     == DIAGNOSTIC -- NO EFFECT ON THE ACTUAL RUN EITHER WAY. EIGVALPREV     ==
!     == ITSELF IS ALLOCATED LAZILY INSIDE THE PER-BLOCK LOOP (STEP C) ONCE   ==
!     == NB IS ACTUALLY KNOWN -- NOT HERE, SINCE NB IS SET PER-BLOCK          ==
!     == (THIS%NB), NOT YET AVAILABLE BEFORE THE LOOP STARTS.                 ==
      IF(TEDFTHAUXDIAG) DIAGMAXDELTA=-1.D0
!     == RMM STEP A WARM-UP GATE: ONE INCREMENT PER OUTER ITERATION (THIS      ==
!     == CALL), NOT PER (IKPT,ISPIN) BLOCK -- SEE TEDFTRMMDELAY HEADER         ==
!     == COMMENT ABOVE FOR WHY COLD RMM NEEDS THIS.                            ==
      EDFTRMMDELAYCOUNT=EDFTRMMDELAYCOUNT+1
      TUSERMMNOW=TEDFTRMMSTEP.AND.(EDFTRMMDELAYCOUNT.GT.EDFTRMMDELAY)
      DO IKPT=1,NKPT
         DO ISPIN=1,NSPIN
            CALL WAVES_SELECTWV(IKPT,ISPIN)
            CALL PLANEWAVE$SELECT(GSET%ID)
            NGL=GSET%NGL
            NBH=THIS%NBH
            NB=THIS%NB
            IF(ALLOCATED(G2)) DEALLOCATE(G2)
            ALLOCATE(G2(NGL))
            CALL PLANEWAVE$GETR8A('G2',NGL,G2)

            ALLOCATE(R0(3,NAT))
            CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,R0)
            ALLOCATE(PSIU(NGL,NDIM,NB))
            ALLOCATE(PROJU(NDIM,NB,NPRO))
            TREALSUB=(NB.NE.NBH)
            IF(NB.EQ.NBH) THEN
               PSIU=THIS%PSI0
            ELSE
               CALL CG_UNPACKSUPER(NGL,NDIM,NB,NBH,THIS%PSI0,PSIU)
            END IF
            CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NB,MAP%NPRO &
                ,PSIU,PROJU)

!           == STEP A: ORBITAL UPDATE, UNMODIFIED, UNIFORM WEIGHT -- SEE     ==
!           == THIS SUBROUTINE'S OWN HEADER COMMENT FOR WHY NO OCCUPATION    ==
!           == WEIGHTING BELONGS HERE. VESPAW_EDFT_RMM_STEP (OFF BY DEFAULT) ==
!           == SWAPS THE INNER DIAGONALIZER TO RMM_DIIS_BLOCK_SWEEP -- SAME  ==
!           == O-ORTHONORMAL, ENERGY-ORDERED POSTCONDITION, NO FWEIGHT       ==
!           == ARGUMENT (RMM HAS NO OCCUPATION-WEIGHTED LOCKING TOLERANCE TO ==
!           == BEGIN WITH, SO THE UNIFORM-WEIGHT NO-OP IS MOOT FOR IT).      ==
            CALL TIMING$CLOCKON('EDFT-SWEEP')
            IF(TUSERMMNOW) THEN
              NRMMX=RMMNRMMX
              CALL RMM_DIIS_BLOCK_SWEEP(NGL,NB,NDIM,NPRO,CONV,NRMMX,G2,R0 &
                  ,THIS%EIGVAL,PSIU,PROJU,TCONV)
            ELSE
              ALLOCATE(FWEIGHT(NB))
              FWEIGHT(:)=1.D0
              CALL DAVIDSON_BLOCK_SWEEP(NGL,NB,NDIM,NPRO,CONV,NSWEEPX,G2,R0 &
                  ,THIS%EIGVAL,PSIU,PROJU,FWEIGHT,TCONV)
              DEALLOCATE(FWEIGHT)
            END IF
            CALL TIMING$CLOCKOFF('EDFT-SWEEP')

!           == STEP B: SEED/EVOLVE HAUX TOWARD THE JUST-UPDATED SUBSPACE     ==
!           == HAMILTONIAN. PSIU/PROJU ARE O-ORTHONORMAL HERE (RAYLEIGH-RITZ ==
!           == GUARANTEE AT THE END OF EVERY DAVIDSON_BLOCK_SWEEP CALL).     ==
            ALLOCATE(HPHYS(NB,NB))
            ALLOCATE(EDFTRESIDUAL(NB,NB))
            CALL EDFT_BUILDHPHYS(NGL,NDIM,NB,NPRO,PSIU,PROJU,HPHYS)
            CALL EDFT$INIBLOCK(IKPT,ISPIN,NB,NKPT,NSPIN,THIS%EIGVAL)
            CALL EDFT$HAUXFORCE(IKPT,ISPIN,HPHYS,EDFTRESIDUAL)
            IF(TEDFTANDERSON) THEN
!             == NO TEDFTHAUXREADY GATE NEEDED: EDFT$HAUXSTEP_ANDERSON HAS   ==
!             == ITS OWN PER-BLOCK FIRST-CALL BOOTSTRAP (SEEDS ITS HISTORY   ==
!             == AND RETURNS WITHOUT STEPPING), SO IT IS SAFE TO CALL EVEN   ==
!             == ON THE VERY FIRST-EVER VISIT TO THIS BLOCK.                 ==
              CALL EDFT$HAUXSTEP_ANDERSON(IKPT,ISPIN,EDFTRESIDUAL)
            ELSE IF(TEDFTHAUXREADY) THEN
              IF(TEDFTRESGATE) THEN
                CALL EDFT$HAUXSTEP_RESGATE(LAMBDA_HAUX,IKPT,ISPIN,EDFTCHMPOT &
     &                                    ,EDFTTEMP,EDFTRESIDUAL)
              ELSE IF(TEDFTMVPEXACT) THEN
                CALL EDFT$HAUXSTEP_MVPEXACT(LAMBDA_HAUX,IKPT,ISPIN,EDFTCHMPOT &
     &                                     ,EDFTTEMP,EDFTRESIDUAL)
              ELSE
                CALL EDFT$HAUXSTEP_ADAPTIVE(LAMBDA_HAUX,IKPT,ISPIN,EDFTCHMPOT &
     &                                     ,EDFTTEMP,EDFTRESIDUAL)
              END IF
            ELSE
              CALL EDFT$HAUXSTEP(LAMBDA_HAUX,IKPT,ISPIN,EDFTRESIDUAL)
            END IF
            DEALLOCATE(EDFTRESIDUAL)
!           == HPHYS ITSELF IS DEALLOCATED FURTHER BELOW, AFTER STEP C'S      ==
!           == HAUX-VS-HPHYS DIAGNOSTIC (VESPAW_EDFT_HAUX_DIAG) HAS A CHANCE  ==
!           == TO PROJECT IT INTO THE JUST-UPDATED NATURAL-ORBITAL BASIS.     ==

!           == STEP C: DIAGONALIZE HAUX -> NATURAL ORBITALS, ROTATE THE      ==
!           == TRIAL ORBITALS INTO THAT EIGENBASIS -- SAME EXPLICIT-LOOP     ==
!           == ACCUMULATION PATTERN AS CG_SUBSPACEROTATE'S OWN ROTATION-BY-  ==
!           == EIGENVECTORS (A FEW SUBROUTINES ABOVE), JUST ROTATING BY      ==
!           == HAUX'S EIGENVECTORS INSTEAD OF THE PHYSICAL SUBSPACE          ==
!           == HAMILTONIAN'S OWN. A UNITARY ROTATION OF AN O-ORTHONORMAL     ==
!           == SET STAYS O-ORTHONORMAL -- NO RE-ORTHOGONALIZATION NEEDED.    ==
            ALLOCATE(EIGVALNAT(NB))
            ALLOCATE(UNAT(NB,NB))
            CALL EDFT$HAUXEIGVEC(IKPT,ISPIN,NB,EIGVALNAT,UNAT)
!           == HAUX EIGENVALUE-DRIFT DIAGNOSTIC (VESPAW_EDFT_HAUX_DIAG): HOW   ==
!           == MUCH DID HAUX'S OWN SPECTRUM CHANGE FOR THIS BLOCK SINCE THE    ==
!           == PREVIOUS OUTER ITERATION -- DIRECT INSTRUMENTATION OF HAUX      ==
!           == ITSELF (SEE THE DEV NOTES FOR WHY: ENERGY/DENSITY-SIDE      ==
!           == SYMPTOMS ALONE COULDN'T LOCATE THE SI SLOWDOWN). TRACKS THE     ==
!           == (K-POINT,SPIN,BAND) WITH THE LARGEST |DELTA EIGENVALUE| ACROSS  ==
!           == THE WHOLE OUTER ITERATION, PLUS ITS OCCUPATION AND EIGENVALUE,  ==
!           == SUMMARIZED IN ONE PRINT LINE AFTER THE PER-BLOCK LOOP BELOW.    ==
!           == PURE DIAGNOSTIC -- EIGVALPREV IS READ-THEN-UPDATED BUT NEVER    ==
!           == FEEDS BACK INTO HAUX/PSI/THE ACTUAL RUN.                       ==
            IF(TEDFTHAUXDIAG) THEN
              IF(.NOT.THAUXDIAGALLOCATED) THEN
                ALLOCATE(EIGVALPREV(NB,NKPT,NSPIN))
                EIGVALPREV=0.D0
                THAUXDIAGALLOCATED=.TRUE.
              END IF
!             == PROJECT HPHYS (THIS ITERATION'S ACTUAL BUILD TARGET, STILL   ==
!             == IN SCOPE -- SEE ITS DEALLOCATION MOVED BELOW) INTO THE       ==
!             == JUST-UPDATED NATURAL-ORBITAL BASIS: HPHYSROT(IB,IB) IS WHAT  ==
!             == THIS ITERATION'S STEP WAS ACTUALLY AIMING HAUX(IB,IB)        ==
!             == TOWARD. COMPARING IT AGAINST EIGVALNAT(IB) DIRECTLY ANSWERS  ==
!             == WHETHER HAUX IS CHASING A GENUINELY MOVING TARGET (HPHYS     ==
!             == ITSELF STILL DRIFTING) OR DIVERGING AWAY FROM AN ALREADY-    ==
!             == STATIONARY ONE.                                              ==
              ALLOCATE(HPHYSROT(NB,NB))
              HPHYSROT=MATMUL(TRANSPOSE(CONJG(UNAT)),MATMUL(HPHYS,UNAT))
              DO IBDIAG=1,NB
                IF(ABS(EIGVALNAT(IBDIAG)-EIGVALPREV(IBDIAG,IKPT,ISPIN)).GT.DIAGMAXDELTA) THEN
                  DIAGMAXDELTA=ABS(EIGVALNAT(IBDIAG)-EIGVALPREV(IBDIAG,IKPT,ISPIN))
                  DIAGMAXIKPT=IKPT
                  DIAGMAXISPIN=ISPIN
                  DIAGMAXIB=IBDIAG
                  DIAGMAXEIG=EIGVALNAT(IBDIAG)
                  DIAGMAXHPHYS=REAL(HPHYSROT(IBDIAG,IBDIAG),KIND=8)
                  IF(ALLOCATED(EDFTF)) THEN
                    DIAGMAXF=EDFTF(IBDIAG,IKPT,ISPIN)
                  ELSE
                    DIAGMAXF=-1.D0
                  END IF
!                 == RECOMPUTE EDFT$HAUXSTEP_ADAPTIVE'S OWN GATE FORMULA        ==
!                 == INDEPENDENTLY, USING THE SAME EIGENVALUE IT WOULD HAVE     ==
!                 == USED INTERNALLY (EIGVALPREV, HAUX'S STATE ENTERING THIS    ==
!                 == ITERATION'S STEP -- UNCHANGED SINCE HAUX ISN'T TOUCHED     ==
!                 == BETWEEN THE END OF THE PREVIOUS ITERATION'S STEP C AND     ==
!                 == THIS ITERATION'S STEP B). WREF=1.D-6 MATCHES THE           ==
!                 == PRODUCTION DEFAULT (NOT RE-CHECKING                        ==
!                 == VESPAW_EDFT_ADAPTIVE_WREF HERE -- NONE OF THE TEST RUNS    ==
!                 == THIS DIAGNOSTIC WAS BUILT FOR OVERRIDE IT).                ==
                  DIAGSVAR=(EIGVALPREV(IBDIAG,IKPT,ISPIN)-EDFTCHMPOT)/EDFTTEMP
                  IF(ABS(DIAGSVAR).GT.50.D0) THEN
                    DIAGWEIGHT=0.D0
                  ELSE
                    DIAGEX=EXP(DIAGSVAR)
                    DIAGWEIGHT=4.D0*DIAGEX/((1.D0+DIAGEX)**2)
                  END IF
                  DIAGMAXGATE=MIN(1.D0,DIAGWEIGHT/1.D-6)
                END IF
                EIGVALPREV(IBDIAG,IKPT,ISPIN)=EIGVALNAT(IBDIAG)
              ENDDO
              DEALLOCATE(HPHYSROT)
            END IF
            DEALLOCATE(HPHYS)
            ALLOCATE(PSINAT(NGL,NDIM,NB))
            PSINAT=(0.D0,0.D0)
            DO IB2=1,NB
              DO IB1=1,NB
                PSINAT(:,:,IB2)=PSINAT(:,:,IB2)+PSIU(:,:,IB1)*UNAT(IB1,IB2)
              END DO
            END DO
            THIS%EIGVAL(:)=EIGVALNAT(:)
            DEALLOCATE(EIGVALNAT)
            DEALLOCATE(UNAT)

!           == STEP D: WRITE BACK, IDENTICAL TAIL TO DAVIDSON$STATE_BY_BLOCK ==
            IF(NB.EQ.NBH) THEN
               THIS%PSI0=PSINAT
            ELSE
               CALL CG_PACKSUPER(NGL,NDIM,NB,NBH,PSINAT,THIS%PSI0)
            END IF
            DEALLOCATE(PSINAT)
            CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NBH,MAP%NPRO &
                ,THIS%PSI0,THIS%PROJ)
            DEALLOCATE(R0)
            DEALLOCATE(PSIU)
            DEALLOCATE(PROJU)
         END DO
      END DO
      IF(TEDFTHAUXDIAG.AND.DIAGMAXDELTA.GE.0.D0) THEN
        PRINT*,'EDFT HAUX-DIAG: MAXDELTAEIG=',DIAGMAXDELTA,' AT IKPT=',DIAGMAXIKPT &
     &        ,' ISPIN=',DIAGMAXISPIN,' IB=',DIAGMAXIB,' F=',DIAGMAXF &
     &        ,' EIG=',DIAGMAXEIG,' HPHYSTARGET=',DIAGMAXHPHYS &
     &        ,' RES=',DIAGMAXHPHYS-DIAGMAXEIG,' GATE=',DIAGMAXGATE
      END IF
      TEDFTHAUXREADY=.TRUE.
      DEALLOCATE(DH)
      DEALLOCATE(V)
      IF(TDEBUG) THEN
        PRINT*,'EDFT FINISHED !!'
        PRINT*,'EDFT EPS:',THIS%EIGVAL*27.211386245988D0
      END IF
      IF(.NOT.TCONV) THEN
        IF(TDEBUG) PRINT*, &
     &    'EDFT BLOCK NOT CONVERGED -- CONTINUING TO NEXT OUTER ITERATION'
      END IF
      END SUBROUTINE EDFT$STATE_BY_BLOCK
