MODULE EDFTVAR_MODULE
!     ** STATE OF EDFT$VARSTEP (OPTIMIZER='EDFT' WITH MIXER='VARIATIONAL'): **
!     ** THE BEST (LOWEST-FREE-ENERGY) POINT (PSI,HAUX) FOUND SO FAR AND    **
!     ** THE SEARCH DIRECTION FROM IT, PER (K-POINT,SPIN) BLOCK.            **
TYPE EDFTVARBLOCK_TYPE
  COMPLEX(8),ALLOCATABLE :: PSIB(:,:,:)  ! (NGL,NDIM,NB) BEST ORBITALS (NATURAL BASIS)
  COMPLEX(8),ALLOCATABLE :: DPSI(:,:,:)  ! (NGL,NDIM,NB) ORBITAL SEARCH DIRECTION
  COMPLEX(8),ALLOCATABLE :: HAUXB(:,:)   ! (NB,NB) BEST HAUX (IN THE PSIB BASIS)
  COMPLEX(8),ALLOCATABLE :: DHAUX(:,:)   ! (NB,NB) HAUX SEARCH DIRECTION
  COMPLEX(8),ALLOCATABLE :: GRAD(:,:,:)  ! (NGL,NDIM,NB) PROJECTED RESIDUAL AT PSIB
  COMPLEX(8),ALLOCATABLE :: PGRAD(:,:,:) ! (NGL,NDIM,NB) ITS PRECONDITIONED VERSION
END TYPE EDFTVARBLOCK_TYPE
TYPE(EDFTVARBLOCK_TYPE),ALLOCATABLE,SAVE :: BLK(:,:) ! (NKPT,NSPIN)
LOGICAL(4),SAVE :: TVARFIRST=.TRUE.
REAL(8)   ,SAVE :: ABEST=HUGE(1.D0)  ! FREE ENERGY AT THE BEST POINT
REAL(8)   ,SAVE :: G0=0.D0           ! ORBITAL PART OF DA/DS AT S=0 ALONG THE DIRECTION
REAL(8)   ,SAVE :: STEP=0.D0         ! STEP LENGTH OF THE TRIAL POINT BEING EVALUATED
REAL(8)   ,SAVE :: STEPNEXT=0.5D0    ! INITIAL STEP LENGTH ALONG THE NEXT NEW DIRECTION
REAL(8)   ,SAVE :: ETOL=1.D-7        ! ACCEPTANCE SLACK [H]
REAL(8)   ,SAVE :: GNORM=0.D0        ! OCCUPATION-WEIGHTED ORBITAL GRADIENT NORM**2
INTEGER(4),SAVE :: NEVAL=0,NREJ=0,NACCTOT=0,NREJTOT=0
LOGICAL(4),SAVE :: TCLEAN=.FALSE.
LOGICAL(4),SAVE :: TCGRESET=.TRUE.    ! NEXT DIRECTION IS PLAIN STEEPEST DESCENT
INTEGER(4),SAVE :: NSMALLDE=0         ! #(CONSECUTIVE CLEAN ACCEPTS GAINING < EDIFF)
LOGICAL(4),SAVE :: TLASTNEWDIR=.FALSE. ! LAST CALL ACCEPTED A POINT AND BUILT A DIRECTION
REAL(8)   ,SAVE :: CGDENOLD=0.D0      ! SUM OCC*<G|PG> AT THE PREVIOUS BEST POINT
INTEGER(4),PARAMETER :: NREJMAX=6
END MODULE EDFTVAR_MODULE
!
!     ..................................................................
      SUBROUTINE EDFT$VARSTEP(NRL_,NDIMD_,V_,NAT_,LMNXX_,DH_,ENERGY,EDIFF &
     &                       ,CONVTOL,TCONV)
!     ******************************************************************
!     ** VARIATIONAL ENSEMBLE DFT (OPTIMIZER='EDFT', MIXER='VARIATIONAL'):**
!     ** DIRECT MINIMIZATION OF THE MERMIN FREE ENERGY                    **
!     **    A[PSI,HAUX] = E_KS[RHO(PSI,F)] - T*S[F],  F=FERMI(EIG HAUX),   **
!     ** JOINTLY OVER THE ORBITALS PSI AND THE AUXILIARY HAMILTONIAN HAUX **
!     ** (MARZARI, VANDERBILT, PAYNE, PRL 79, 1337 (1997)). PSI IS ALWAYS **
!     ** STORED IN HAUX'S EIGENBASIS (NATURAL ORBITALS), HAUX THEN BEING  **
!     ** DIAGONAL; ITS EIGENVALUES FEED DYNOCC, WHICH FERMI-FILLS THEM AT **
!     ** FIXED ELECTRON NUMBER (THIS FIXES THE GAUGE: A UNIFORM SHIFT OF  **
!     ** HAUX CHANGES NOTHING). THERE IS NO DIAGONALIZATION AT A FROZEN   **
!     ** POTENTIAL AND NO DENSITY OR POTENTIAL MIXING: V_,DH_ ARE THE     **
!     ** EXACT KOHN-SHAM HAMILTONIAN OF THE CURRENT STATE, AND ENERGY IS  **
!     ** A AT THAT STATE.                                                 **
!     **                                                                 **
!     ** SEARCH DIRECTION FROM THE BEST POINT:                            **
!     **   ORBITALS: D_I=-P*R_I, R_I=(1-O|PSI><PSI|)H|PSI_I>, P = TETER    **
!     **             PRECONDITIONER, THEN PROJECTED OUT OF THE SUBSPACE.  **
!     **             DA/DPSI_I*=F_I*R_I, SO DA/DS=-2*SUM F_I<R_I|P|R_I>   **
!     **             <= 0: A DESCENT DIRECTION.                           **
!     **   HAUX:     D=HPHYS-HAUX, HPHYS=<PSI|H|PSI>. IN HAUX'S EIGENBASIS**
!     **             DA/DHAUX_IJ=W_IJ*(HAUX-HPHYS)_IJ WITH W_IJ=(F_I-F_J)/ **
!     **             (E_I-E_J)<=0 (PLUS THE FIXED-N PROJECTION ON THE     **
!     **             DIAGONAL), SO THIS IS A DESCENT DIRECTION TOO, AND   **
!     **             A FULL STEP MEANS "HAUX:=HPHYS".                     **
!     ** TRIAL POINT: PSI=ORTHO(PSIB+S*DPSI), HAUX=HAUXB+MIN(S,1)*DHAUX.  **
!     ** A TRIAL IS ACCEPTED ONLY IF A DOES NOT RISE (BY MORE THAN ETOL); **
!     ** OTHERWISE S IS REDUCED FROM THE SAME BEST POINT, USING THE       **
!     ** QUADRATIC MODEL A0+G0*S+Q*S**2 FROM A(0), THE ORBITAL SLOPE G0   **
!     ** AND A(S) WHEN IT IS CONVEX, HALVING OTHERWISE. THE SAME MODEL    **
!     ** SETS THE INITIAL LENGTH ALONG THE NEXT DIRECTION. AFTER NREJMAX  **
!     ** CONSECUTIVE REJECTIONS THE BEST POINT ITSELF IS RE-EVALUATED.    **
!     ** G0 OMITS THE HAUX PART OF THE SLOPE (IT VANISHES FOR INTEGER     **
!     ** OCCUPATIONS), SO THE MODEL ONLY STEERS THE STEP LENGTH; THE      **
!     ** ACCEPTANCE TEST ALONE GUARANTEES THAT A NEVER RISES.             **
!     ******************************************************************
      USE CG_INTERFACE_MODULE
      USE WAVES_MODULE
      USE EDFTVAR_MODULE
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4)                :: NTASKSEDFT,THISTASKEDFT
      INTEGER(4)   , INTENT(IN)   :: NRL_
      INTEGER(4)   , INTENT(IN)   :: NDIMD_
      REAL(8)      , INTENT(IN)   :: V_(NRL_,NDIMD_)
      INTEGER(4)   , INTENT(IN)   :: NAT_
      INTEGER(4)   , INTENT(IN)   :: LMNXX_
      COMPLEX(8)   , INTENT(IN)   :: DH_(LMNXX_,LMNXX_,NDIMD_,NAT_)
      REAL(8)      , INTENT(IN)   :: ENERGY  ! A AT THE CURRENT (PSI,HAUX)
      REAL(8)      , INTENT(IN)   :: EDIFF   ! ACCEPTED-ENERGY CHANGE FOR TCONV
      REAL(8)      , INTENT(IN)   :: CONVTOL ! GNORM BELOW WHICH TCONV
      LOGICAL(4)   , INTENT(OUT)  :: TCONV
      INTEGER(4)                  :: NGL,NB,NBH,NPRO,NBX
      REAL(8)     ,ALLOCATABLE    :: G2(:)
      REAL(8)     ,ALLOCATABLE    :: R0(:,:)
      REAL(8)     ,ALLOCATABLE    :: OCC(:,:,:)
      COMPLEX(8)  ,ALLOCATABLE    :: PSIU(:,:,:),PSINEW(:,:,:),PROJU(:,:,:)
      COMPLEX(8)  ,ALLOCATABLE    :: HPSI(:,:,:),OPSI(:,:,:),RES(:,:,:)
      COMPLEX(8)  ,ALLOCATABLE    :: HTBCPSI(:,:,:) ! WORK ARRAY
      COMPLEX(8)  ,ALLOCATABLE    :: HPHYS(:,:),CMAT(:,:),SMAT(:,:),UMAT(:,:)
      REAL(8)     ,ALLOCATABLE    :: EVAL(:)
      REAL(8)                     :: AOLD,QUADA,SSTAR,G0LOC,GNORMLOC,SHAUX
      INTEGER(4)                  :: IB,JB,NFILO
      CHARACTER(10)               :: CSTAT
      CHARACTER(32)               :: CENV
      LOGICAL(4)                  :: TACCEPT,TNEWDIR
      LOGICAL(4)                  :: TCONVE ! ENERGY PART OF THE CONVERGENCE TEST
      REAL(8)                     :: CGNUM,CGDEN,CGBETA
      INTEGER(4)                  :: ITRY
      INTEGER(4)                  :: NTASKS,THISTASK
!     ******************************************************************
!     == MPI: THE K-POINTS ARE DISTRIBUTED OVER K-GROUPS (LOOPS RUN OVER ==
!     == THE NKPTL LOCAL ONES); WITHIN A K-GROUP THE PLANE WAVES ARE      ==
!     == DISTRIBUTED ('K' SUMS). SCALARS SUMMED OVER K-POINTS ARE SUMMED  ==
!     == OVER THE K-GROUPS WITH EDFT_SUMKGROUPS. THE OCCUPATIONS COME     ==
!     == FROM DYNOCC, WHICH SEES ALL K-POINTS (WAVES_DYNOCCSETR8A).       ==
      CALL MPE$QUERY('~',NTASKS,THISTASK)
      IF(NDIM.NE.1) THEN
        CALL ERROR$MSG('VARIATIONAL EDFT SUPPORTS NDIM=1 ONLY (NO NONCOLLINEAR SPIN)')
        CALL ERROR$STOP('EDFT$VARSTEP')
      END IF
      NAT=NAT_
      LMNXX=LMNXX_
      ALLOCATE(DH(LMNXX,LMNXX,NDIMD,NAT))
      DH=DH_
      NPRO=MAP%NPRO
      NRL=NRL_
      ALLOCATE(V(NRL,NDIMD_))
      V=V_
      TCONV=.FALSE.
      TCONVE=.FALSE.
      NEVAL=NEVAL+1
      CALL DYNOCC$GETI4('NB',NBX)
      ALLOCATE(OCC(NBX,NKPTL,NSPIN))
      CALL WAVES_DYNOCCGETR8A('OCC',NBX*NKPTL*NSPIN,OCC)
!
!     ==================================================================
!     == LINE-SEARCH DECISION                                         ==
!     ==================================================================
      IF(TVARFIRST) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_EDFTVAR_ETOL',CENV)
        IF(LEN_TRIM(CENV).GT.0) READ(CENV,*) ETOL
        ALLOCATE(BLK(NKPTL,NSPIN))
        CSTAT='START'
      ELSE IF(ABEST.EQ.HUGE(1.D0)) THEN
        CSTAT='START'   ! RE-EVALUATION OF THE BEST POINT AFTER A RE-ANCHOR
      ELSE IF(ENERGY.LE.ABEST+ETOL) THEN
        CSTAT='ACCEPT'
      ELSE
        CSTAT='REJECT'
      END IF
      TACCEPT=(CSTAT.NE.'REJECT')
!     == QUADRATIC MODEL ALONG THE DIRECTION JUST TRIED ================
      SSTAR=-1.D0
      IF(CSTAT.EQ.'ACCEPT'.OR.CSTAT.EQ.'REJECT') THEN
        IF(STEP.GT.0.D0) THEN
          QUADA=(ENERGY-ABEST-G0*STEP)/STEP**2
          IF(QUADA.GT.0.D0.AND.G0.LT.0.D0) SSTAR=-G0/(2.D0*QUADA)
        END IF
      END IF
      TNEWDIR=TACCEPT
      IF(TACCEPT) THEN
        AOLD=ABEST
        ABEST=ENERGY
        NREJ=0
        IF(CSTAT.EQ.'ACCEPT') THEN
          NACCTOT=NACCTOT+1
!         == ENERGY CRITERION ONLY AFTER A CLEAN, NOT ARTIFICIALLY SHORT STEP
          IF(TCLEAN.AND.AOLD-ENERGY.LT.EDIFF) THEN
            NSMALLDE=NSMALLDE+1
          ELSE
            NSMALLDE=0
          END IF
          TCONVE=(NSMALLDE.GE.2)
          IF(SSTAR.GT.0.D0) THEN
            STEPNEXT=MIN(MAX(SSTAR,0.5D0*STEP),4.D0*STEP)
          ELSE
            STEPNEXT=2.D0*STEP
          END IF
        END IF
        TCLEAN=.TRUE.
        STEP=STEPNEXT
      ELSE
        NREJ=NREJ+1
        NREJTOT=NREJTOT+1
        TCLEAN=.FALSE.
        IF(NREJ.GT.NREJMAX) THEN
!         == RE-ANCHOR: RE-EVALUATE THE BEST POINT ITSELF (STEP 0) ========
          CSTAT='REANCHOR'
          STEP=0.D0
          ABEST=HUGE(1.D0)
          NREJ=0
          STEPNEXT=0.1D0*STEPNEXT
          TCGRESET=.TRUE.
        ELSE IF(SSTAR.GT.0.D0) THEN
          STEP=MIN(MAX(SSTAR,0.1D0*STEP),0.5D0*STEP)
        ELSE
          STEP=0.5D0*STEP
        END IF
      END IF
!
!     ==================================================================
!     == PASS 1 (NEW BEST POINT ONLY): STORE IT, THE PROJECTED        ==
!     == RESIDUAL G AND ITS PRECONDITIONED VERSION PG, AND THE SUMS    ==
!     == FOR THE POLAK-RIBIERE COEFFICIENT                             ==
!     ==     BETA=SUM F<G|PG-PG_OLD> / SUM F<G_OLD|PG_OLD>             ==
!     == (OLD VECTORS TAKEN AS STORED, I.E. BEFORE THIS STEP'S UPDATE) ==
!     ==================================================================
      IF(TNEWDIR) THEN
        CGNUM=0.D0
        CGDEN=0.D0
        GNORMLOC=0.D0
        DO IKPT=1,NKPTL
          DO ISPIN=1,NSPIN
            CALL WAVES_SELECTWV(IKPT,ISPIN)
            CALL PLANEWAVE$SELECT(GSET%ID)
            NGL=GSET%NGL
            NBH=THIS%NBH
            NB=THIS%NB
            ALLOCATE(R0(3,NAT))
            CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,R0)
            ALLOCATE(G2(NGL))
            CALL PLANEWAVE$GETR8A('G2',NGL,G2)
            ALLOCATE(PSIU(NGL,NDIM,NB))
            ALLOCATE(PROJU(NDIM,NB,NPRO))
            ALLOCATE(HPSI(NGL,NDIM,NB))
            ALLOCATE(OPSI(NGL,NDIM,NB))
            ALLOCATE(RES(NGL,NDIM,NB))
            ALLOCATE(HPHYS(NB,NB))
            ALLOCATE(CMAT(NB,NB))
            ALLOCATE(SMAT(NB,NB))
            ALLOCATE(UMAT(NB,NB))
            ALLOCATE(EVAL(NB))
            TREALSUB=(NB.NE.NBH)
            IF(NB.EQ.NBH) THEN
              PSIU=THIS%PSI0
            ELSE
              CALL CG_UNPACKSUPER(NGL,NDIM,NB,NBH,THIS%PSI0,PSIU)
            END IF
            CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NB,NPRO,PSIU,PROJU)
            CALL WAVES_HPSI(MAP,GSET,ISPIN,NGL,NDIM,NDIMD,NB,NPRO,LMNXX,NAT &
     &                     ,NRL,PSIU,V(1,ISPIN),R0,PROJU,DH,HPSI)
!           == (THE NTBO HYBRID IS INCLUDED BY WAVES_HPSI ITSELF, AS AN    ==
!           == OPERATOR -- SEE LMTO$APPLYHAMILOP.)                         ==
            OPSI=PSIU
            CALL WAVES_OPSI(NB,NB,NPRO,NAT,NGL,R0,PROJU,OPSI)
            CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,PSIU,NB,HPSI,HPHYS)
            CALL MPE$COMBINE('K','+',HPHYS)
            HPHYS=0.5D0*(HPHYS+CONJG(TRANSPOSE(HPHYS)))
!           == PROJECTED RESIDUAL G_I=H|PSI_I>-SUM_J O|PSI_J>HPHYS_JI ====
            RES=HPSI
            DO IB=1,NB
              DO JB=1,NB
                RES(:,:,IB)=RES(:,:,IB)-OPSI(:,:,JB)*HPHYS(JB,IB)
              ENDDO
            ENDDO
            IF(.NOT.ALLOCATED(BLK(IKPT,ISPIN)%PSIB)) THEN
              ALLOCATE(BLK(IKPT,ISPIN)%PSIB(NGL,NDIM,NB))
              ALLOCATE(BLK(IKPT,ISPIN)%DPSI(NGL,NDIM,NB))
              ALLOCATE(BLK(IKPT,ISPIN)%HAUXB(NB,NB))
              ALLOCATE(BLK(IKPT,ISPIN)%DHAUX(NB,NB))
              ALLOCATE(BLK(IKPT,ISPIN)%GRAD(NGL,NDIM,NB))
              ALLOCATE(BLK(IKPT,ISPIN)%PGRAD(NGL,NDIM,NB))
              BLK(IKPT,ISPIN)%DPSI=(0.D0,0.D0)
              BLK(IKPT,ISPIN)%GRAD=(0.D0,0.D0)
              BLK(IKPT,ISPIN)%PGRAD=(0.D0,0.D0)
            END IF
!           == HAUX: SEEDED WITH HPHYS ON THE VERY FIRST CALL ===========
            IF(TVARFIRST) THEN
              CALL LIB$DIAGC8(NB,HPHYS,EVAL,UMAT)
              CALL EDFT$INIBLOCK(IKPT,ISPIN,NB,NKPT,NSPIN,EVAL)
              CALL EDFT$SETHAUX(IKPT,ISPIN,NB,HPHYS)
            END IF
            CALL EDFT$GETHAUX(IKPT,ISPIN,NB,BLK(IKPT,ISPIN)%HAUXB)
            BLK(IKPT,ISPIN)%PSIB=PSIU
            BLK(IKPT,ISPIN)%DHAUX=HPHYS-BLK(IKPT,ISPIN)%HAUXB
!           == PRECONDITIONED GRADIENT, PROJECTED OUT OF THE SUBSPACE ===
            ALLOCATE(HTBCPSI(NGL,NDIM,NB))       ! WORK: NEW PG
            DO IB=1,NB
              CALL CG_PRECONDITION_FULL(NGL,G2,PSIU(:,1,IB),RES(:,1,IB) &
     &                                 ,HTBCPSI(:,1,IB))
            ENDDO
            CALL CG_PROJECTOUT(HTBCPSI)
!           == POLAK-RIBIERE SUMS WITH THE OLD (STORED) G AND PG ========
            CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,RES,NB &
     &                        ,HTBCPSI-BLK(IKPT,ISPIN)%PGRAD,CMAT)
            CALL MPE$COMBINE('K','+',CMAT)
            CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,BLK(IKPT,ISPIN)%GRAD &
     &                        ,NB,BLK(IKPT,ISPIN)%PGRAD,SMAT)
            CALL MPE$COMBINE('K','+',SMAT)
            DO IB=1,NB
              CGNUM=CGNUM+OCC(IB,IKPT,ISPIN)*REAL(CMAT(IB,IB),KIND=8)
              CGDEN=CGDEN+OCC(IB,IKPT,ISPIN)*REAL(SMAT(IB,IB),KIND=8)
            ENDDO
            CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,RES,NB,RES,SMAT)
            CALL MPE$COMBINE('K','+',SMAT)
            DO IB=1,NB
              GNORMLOC=GNORMLOC+OCC(IB,IKPT,ISPIN)*REAL(SMAT(IB,IB),KIND=8)
            ENDDO
            BLK(IKPT,ISPIN)%GRAD=RES
            BLK(IKPT,ISPIN)%PGRAD=HTBCPSI
            DEALLOCATE(HTBCPSI)
            DEALLOCATE(R0,G2,PSIU,PROJU,HPSI,OPSI,RES,HPHYS,CMAT,SMAT,UMAT,EVAL)
          ENDDO
        ENDDO
        CALL EDFT_SUMKGROUPS(CGNUM)
        CALL EDFT_SUMKGROUPS(CGDEN)
        CALL EDFT_SUMKGROUPS(GNORMLOC)
        GNORM=GNORMLOC
!
!       ================================================================
!       == PASS 1B: CONJUGATE DIRECTION D=-PG+BETA*D_OLD (PR+), THE    ==
!       == OLD DIRECTION TRANSPORTED BY PROJECTING IT OUT OF THE NEW   ==
!       == SUBSPACE; SLOPE G0=2*SUM F*RE<G|D>. RESTART WITH BETA=0 IF   ==
!       == THE CONJUGATE DIRECTION IS NOT DOWNHILL.                    ==
!       ================================================================
        CGBETA=0.D0
        IF(.NOT.TCGRESET.AND.CGDEN.GT.0.D0) CGBETA=MAX(0.D0,CGNUM/CGDEN)
        DO ITRY=1,2
          G0LOC=0.D0
          DO IKPT=1,NKPTL
            DO ISPIN=1,NSPIN
              CALL WAVES_SELECTWV(IKPT,ISPIN)
              CALL PLANEWAVE$SELECT(GSET%ID)
              NGL=GSET%NGL
              NB=THIS%NB
              ALLOCATE(R0(3,NAT))
              CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,R0)
              ALLOCATE(PSIU(NGL,NDIM,NB))
              ALLOCATE(CMAT(NB,NB))
              PSIU=BLK(IKPT,ISPIN)%PSIB
              IF(ITRY.EQ.1) THEN
                BLK(IKPT,ISPIN)%DPSI=-BLK(IKPT,ISPIN)%PGRAD &
     &                              +CGBETA*BLK(IKPT,ISPIN)%DPSI
              ELSE
                BLK(IKPT,ISPIN)%DPSI=-BLK(IKPT,ISPIN)%PGRAD
              END IF
              CALL CG_PROJECTOUT(BLK(IKPT,ISPIN)%DPSI)
              CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,BLK(IKPT,ISPIN)%GRAD &
     &                          ,NB,BLK(IKPT,ISPIN)%DPSI,CMAT)
              CALL MPE$COMBINE('K','+',CMAT)
              DO IB=1,NB
                G0LOC=G0LOC+2.D0*OCC(IB,IKPT,ISPIN)*REAL(CMAT(IB,IB),KIND=8)
              ENDDO
              DEALLOCATE(R0,PSIU,CMAT)
            ENDDO
          ENDDO
          CALL EDFT_SUMKGROUPS(G0LOC)
          IF(G0LOC.LT.0.D0.OR.CGBETA.EQ.0.D0) EXIT
          CGBETA=0.D0      ! NOT DOWNHILL: RESTART AS STEEPEST DESCENT
        ENDDO
        G0=G0LOC
        TCGRESET=.FALSE.
!
!       == CONVERGENCE: TINY GRADIENT, OR A CLEAN STEP THAT GAINED LESS ==
!       == THAN EDIFF WHILE THE SLOPE PREDICTS LESS THAN EDIFF MORE     ==
        IF(CSTAT.EQ.'ACCEPT') THEN
          TCONV=(GNORM.LT.CONVTOL).OR.(TCONVE.AND.ABS(G0)*STEP.LT.EDIFF)
        END IF
!       == CONVERGED: ISSUE THE BEST POINT ITSELF, SO THAT THE FINAL      ==
!       == EVALUATION, THE REPORTED ENERGY AND THE RESTART FILE ALL       ==
!       == BELONG TO THE ACCEPTED MINIMUM RATHER THAN TO ONE MORE TRIAL.  ==
        IF(TCONV) STEP=0.D0
      END IF
!
!     ==================================================================
!     == PASS 2: TRIAL POINT AT STEP FROM THE BEST POINT              ==
!     ==================================================================
      SHAUX=MIN(STEP,1.D0)
      DO IKPT=1,NKPTL
        DO ISPIN=1,NSPIN
          CALL WAVES_SELECTWV(IKPT,ISPIN)
          CALL PLANEWAVE$SELECT(GSET%ID)
          NGL=GSET%NGL
          NBH=THIS%NBH
          NB=THIS%NB
          ALLOCATE(R0(3,NAT))
          CALL ATOMLIST$GETR8A('R(0)',0,3*NAT,R0)
          ALLOCATE(PSIU(NGL,NDIM,NB))
          ALLOCATE(PSINEW(NGL,NDIM,NB))
          ALLOCATE(PROJU(NDIM,NB,NPRO))
          ALLOCATE(OPSI(NGL,NDIM,NB))
          ALLOCATE(HPHYS(NB,NB))
          ALLOCATE(CMAT(NB,NB))
          ALLOCATE(SMAT(NB,NB))
          ALLOCATE(UMAT(NB,NB))
          ALLOCATE(EVAL(NB))
          PSIU=BLK(IKPT,ISPIN)%PSIB+STEP*BLK(IKPT,ISPIN)%DPSI
!         == LOWDIN O-ORTHONORMALIZATION: PSI <- PSI*S**(-1/2) ==========
          CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NB,NPRO,PSIU,PROJU)
          OPSI=PSIU
          CALL WAVES_OPSI(NB,NB,NPRO,NAT,NGL,R0,PROJU,OPSI)
          CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,PSIU,NB,OPSI,SMAT)
          CALL MPE$COMBINE('K','+',SMAT)
          SMAT=0.5D0*(SMAT+CONJG(TRANSPOSE(SMAT)))
          CALL LIB$DIAGC8(NB,SMAT,EVAL,UMAT)
          DO IB=1,NB
            CMAT(:,IB)=UMAT(:,IB)/SQRT(EVAL(IB))
          ENDDO
          SMAT=MATMUL(CMAT,CONJG(TRANSPOSE(UMAT)))   ! S**(-1/2)
!         == HAUX AT THE TRIAL POINT, THEN ROTATE INTO ITS EIGENBASIS ===
          HPHYS=BLK(IKPT,ISPIN)%HAUXB+SHAUX*BLK(IKPT,ISPIN)%DHAUX
          HPHYS=0.5D0*(HPHYS+CONJG(TRANSPOSE(HPHYS)))
          CALL LIB$DIAGC8(NB,HPHYS,EVAL,UMAT)
          CMAT=MATMUL(SMAT,UMAT)          ! S**(-1/2) * U
          PSINEW=(0.D0,0.D0)
          DO IB=1,NB
            DO JB=1,NB
              PSINEW(:,:,IB)=PSINEW(:,:,IB)+PSIU(:,:,JB)*CMAT(JB,IB)
            ENDDO
          ENDDO
          HPHYS=(0.D0,0.D0)
          DO IB=1,NB
            HPHYS(IB,IB)=CMPLX(EVAL(IB),0.D0,KIND=8)
          ENDDO
          CALL EDFT$SETHAUX(IKPT,ISPIN,NB,HPHYS)
          IF(.NOT.ASSOCIATED(THIS%EIGVAL)) ALLOCATE(THIS%EIGVAL(NB))
          THIS%EIGVAL(:)=EVAL(:)
!         == WRITE BACK, SAME TAIL AS DAVIDSON$STATE_BY_BLOCK ============
          IF(NB.EQ.NBH) THEN
            THIS%PSI0=PSINEW
          ELSE
            CALL CG_PACKSUPER(NGL,NDIM,NB,NBH,PSINEW,THIS%PSI0)
          END IF
          CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NBH,MAP%NPRO &
     &                          ,THIS%PSI0,THIS%PROJ)
          DEALLOCATE(R0,PSIU,PSINEW,PROJU,OPSI,HPHYS,CMAT,SMAT,UMAT,EVAL)
        ENDDO
      ENDDO
      TVARFIRST=.FALSE.
      TLASTNEWDIR=TNEWDIR
      CALL MIXER$SETRESIDUAL(GNORM)
!
!     ==================================================================
!     == REPORT                                                       ==
!     ==================================================================
      IF(THISTASK.EQ.1) THEN
        CALL FILEHANDLER$UNIT('PROT',NFILO)
        WRITE(NFILO,FMT='("EDFTVAR ",I5,1X,A8," A=",F20.10," ABEST=",ES18.10' &
     &                //'," GNORM=",ES10.3," G0=",ES10.3," NEXTSTEP=",ES10.3)') &
     &        NEVAL,CSTAT,ENERGY,ABEST,GNORM,G0,STEP
      END IF
      DEALLOCATE(OCC)
      DEALLOCATE(DH)
      DEALLOCATE(V)
      RETURN
      CONTAINS
!       ................................................................
        SUBROUTINE CG_PROJECTOUT(X)
!       ** X <- (1-|PSIU><PSIU|O) X FOR THE CURRENT BLOCK, PSIU O-ORTHONORMAL
!       ** (USES THE HOST'S PSIU, R0, NGL, NB, NPRO)
        COMPLEX(8),INTENT(INOUT) :: X(NGL,NDIM,NB)
        COMPLEX(8),ALLOCATABLE   :: OPSIX(:,:,:),PROJX(:,:,:),CX(:,:)
        INTEGER(4)               :: IB1,JB1
        ALLOCATE(OPSIX(NGL,NDIM,NB))
        ALLOCATE(PROJX(NDIM,NB,NPRO))
        ALLOCATE(CX(NB,NB))
        CALL CG_PROJECTIONS(MAP,GSET,NAT,R0,NGL,NDIM,NB,NPRO,PSIU,PROJX)
        OPSIX=PSIU
        CALL WAVES_OPSI(NB,NB,NPRO,NAT,NGL,R0,PROJX,OPSIX)
        CALL PLANEWAVE$SCALARPRODUCT('',NGL,NDIM,NB,OPSIX,NB,X,CX)
        CALL MPE$COMBINE('K','+',CX)
        DO IB1=1,NB
          DO JB1=1,NB
            X(:,:,IB1)=X(:,:,IB1)-PSIU(:,:,JB1)*CX(JB1,IB1)
          ENDDO
        ENDDO
        DEALLOCATE(OPSIX,PROJX,CX)
        END SUBROUTINE CG_PROJECTOUT
      END SUBROUTINE EDFT$VARSTEP
