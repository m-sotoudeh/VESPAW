  INTEGER(4)           ,SAVE :: IITER
  REAL(8)              ,SAVE :: RESBEST=HUGE(1.D0) ! BEST |RES|**2 SINCE LAST RESTART
  INTEGER(4)           ,SAVE :: NVALID=0            ! #(VALID HISTORY COLUMNS, INCL. NEWEST)
  REAL(8)              ,SAVE :: G=0.5D0             ! ADAPTIVE MIXING FACTOR
  REAL(8)              ,SAVE :: RESIDUAL=0.D0  ! LAST "RHO-DIFF" -- SEE MIXER$GETR8
