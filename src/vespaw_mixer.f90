      SUBROUTINE WAVES_MIXRHO_PUL(NRL,NDIMD,G0SQ,NHISTORYIN,RHODIM,DENDIM,RHO,DENMAT,CONVTOL,TCONV,&
           CONVPSI) ! USING R AND ONLY A
!     ******************************************************************
!     ** ALLPY A PULAY MIXING SCHEME,                                 **
!     ** REF: KRESSE, FURTMUELLER COM. MATER. SCI. 6, 15 (1996)       **
!     **     EQUATIONS 83 TO 87                                       **
!     ** NOW WITH KERKER PRECONDITIONING OF THE DENSITY RESIDUAL      **
!     ** (SEE MIX_KERKERFILTER) BEFORE IT ENTERS THE HISTORY/FIT.     **
!     ******************************************************************
      ! TODO: DEALLOCATE-MECHANISM
      USE MIXPULAY_MODULE
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4) ,INTENT(IN)    :: NRL   ! #(LOCAL REAL-SPACE GRID POINTS): RHODIM=NRL*NDIMD
      INTEGER(4) ,INTENT(IN)    :: NDIMD ! #(DENSITY COMPONENTS: TOTAL, SPIN...)
      REAL(8)    ,INTENT(IN)    :: G0SQ  ! KERKER SCREENING WAVEVECTOR**2 [BOHR**-2]
      INTEGER(4) ,INTENT(IN)    :: NHISTORYIN ! MIXNHISTORY OVERRIDE (0=KEEP MODULE DEFAULT); SET ON TFIRST ONLY
      INTEGER(4) ,INTENT(IN)    :: RHODIM
      INTEGER(4) ,INTENT(IN)    :: DENDIM
      REAL(8)    ,INTENT(INOUT) :: RHO(RHODIM) !RHO(NRL,NDIMD)
      real(8)    ,INTENT(INOUT) :: DENMAT(DENDIM) !(LMNXX,LMNXX,NDIMD,NAT)
      REAL(8)    ,INTENT(IN)    :: CONVTOL ! DENSITY-RESIDUAL NORM BELOW WHICH TCONV IS DECLARED; SET
                                            ! VIA WAVES$SETR8('MIXTOL',...), !PSIDYN MIXTOL= IN .cntl
      LOGICAL(4) ,INTENT(OUT)   :: TCONV
      REAL(8)    ,INTENT(OUT)   :: CONVPSI
      REAL(8)   ,PARAMETER      :: GMIN=0.05D0,GMAX=0.5D0
      REAL(8)                   :: SVAR,c(1,1)
      REAL(8)                   :: RESVAR ! ||RAW UNMIXED DENSITY CHANGE||**2
      REAL(8)                   :: STEPVAR ! ||PROPOSED MIXED STEP||**2
      LOGICAL(4)                :: TDEBUG
      REAL(8)                   :: REGVAR ! TIKHONOV REGULARIZATION FOR A
      INTEGER(4)                :: IH1,IH2,NBACK
      INTEGER(4)                :: RHOX
      LOGICAL(4)                :: TRESTART
      INTEGER(4)                :: NTASKS,THISTASK
!     ******************************************************************
!     == CID='~' (WORLD GROUP), NOT 'NONE' -- SEE THE HEADER COMMENT AT     ==
!     == CG_SUBSPACEROTATE IN PAW_CG.F90 FOR WHY.                           ==
      CALL MPE$QUERY('~',NTASKS,THISTASK)
      TACTIVE=.TRUE.  ! SEE MIXER$GETR8('RESIDUAL',...), BELOW
      !FIRST STEP
      IF(TFIRST) THEN
         IITER=1
         NVALID=0
         RESBEST=HUGE(1.D0)
         G=GMAX
         IF(NHISTORYIN.GT.0) NHISTORY=NHISTORYIN
         IF(NHISTORY.LT.1) THEN
            CALL ERROR$MSG('NHISTORY MUST BE AT LEAST 1 (FOR LINEAR MIXING)')
            CALL ERROR$STOP('WAVES_MIXRHO')
         END IF
         ! ALLOCATE ARRAYS
         ALLOCATE(RHOOLD(RHODIM+DENDIM,NHISTORY))
         RHOOLD=0.D0
         ALLOCATE(RESOLD(RHODIM+DENDIM,NHISTORY))
         RESOLD=0.D0
         ALLOCATE(A(NHISTORY,NHISTORY))
         A=0.D0
         ALLOCATE(AINV(NHISTORY,NHISTORY))
         AINV=0.D0
         ALLOCATE(ALPHABAR(NHISTORY))
         ALPHABAR=0.D0
         ! ASSIGN FIRST DENSITY
         RHOOLD(1:RHODIM,1)=RHO(:)
         RHOOLD(RHODIM+1:RHODIM+DENDIM,1)=DENMAT(:)
         TFIRST=.FALSE.
         TCONV=.FALSE.
         CONVPSI=1.D-3 ! 3 AUCH GUT
         RETURN
      END IF
      ! AFTER FIRST STEP: DO MIXING

!!$! DO NOTHING BUT RETURNING THE START DENSITY
!!$RHO(:)=RHOOLD(1:RHODIM,1)
!!$DENMAT(:)=RHOOLD(RHODIM+1:RHODIM+DENDIM,1)
!!$CONVPSI=1.D-6 
!!$RETURN
      ALLOCATE(RHOOUT(RHODIM+DENDIM))
      IITER=IITER+1

      CALL LIB$SCALARPRODUCTR8(.TRUE.,RHODIM,1,&
           RHO(1:RHODIM)-RHOOLD(1:RHODIM,1),1,&
           RHO(1:RHODIM)-RHOOLD(1:RHODIM,1),c)
      svar=c(1,1)
      !SVAR=MAXVAL(ABS(RHO(1:RHODIM)-RHOOLD(1:RHODIM,1)))
!     == THE DENSITY GRID IS DISTRIBUTED OVER THE TASKS OF THE MONOMER: ==
!     == EVERY GRID SCALAR PRODUCT IS SUMMED OVER THEM, SO THAT ALL     ==
!     == TASKS TAKE THE SAME MIXING DECISIONS AND COEFFICIENTS.         ==
      CALL MPE$COMBINE('MONOMER','+',SVAR)
      RESIDUAL=SVAR
      CALL VERBOSITY$GETL4('DEBUG',TDEBUG)
      IF(THISTASK.EQ.1) THEN
        IF(TDEBUG) PRINT*,'CG-MIXER ITER ',IITER,' RHO-DIFF (RES) =',SVAR
      END IF
      IF(SVAR.GT.1.D-1) THEN
         CONVPSI=1.D-4 ! 4 AUCH GUT
      ELSE
         CONVPSI=1.D-6
      END IF
      IF(SVAR.LT.1.D-4) CONVPSI=1.D-8
      TCONV=(SVAR.LT.CONVTOL)
      RESVAR=SVAR
!
!     ==================================================================
!     == RESTARTED DIIS: IF THE (GLOBAL) RESIDUAL FAILED TO IMPROVE   ==
!     == ON ITS BEST VALUE SINCE THE LAST RESTART, THE HISTORY-BASED  ==
!     == EXTRAPOLATION IS LIKELY MISBEHAVING (OBSERVED ON LARGER,     ==
!     == ELECTRONICALLY HARDER SYSTEMS WITH A FIXED G=0.5, NHISTORY=3 ==
!     == PULAY FIT -- ENERGY OSCILLATING RATHER THAN CONVERGING) --   ==
!     == DISCARD THE HISTORY (FALL BACK TO PLAIN LINEAR MIXING FOR    ==
!     == THIS STEP, THEN REBUILD HISTORY FROM HERE) AND SHRINK G.     ==
!     == OTHERWISE LET G CREEP BACK TOWARDS GMAX WHILE CONVERGENCE IS ==
!     == STEADY, SO WELL-BEHAVED SYSTEMS STILL MIX AS AGGRESSIVELY AS ==
!     == BEFORE.                                                      ==
!     ==================================================================
      TRESTART=(RESVAR.GT.RESBEST)
      IF(TRESTART) THEN
         G=MAX(G*0.5D0,GMIN)
         NVALID=0
         RESBEST=RESVAR
         IF(THISTASK.EQ.1.AND.TDEBUG) PRINT*,'CG-MIXER: RESTARTING PULAY HISTORY, NEW G=',G
      ELSE
         RESBEST=RESVAR
         G=MIN(G*1.05D0,GMAX)
      END IF

      ! RESOLD(:,1) CONTAINS THE NEWEST
      RESOLD(1:RHODIM,1)=RHO(:)-RHOOLD(1:RHODIM,1)
      RESOLD(RHODIM+1:RHODIM+DENDIM,1)=DENMAT(:) &
           -RHOOLD(RHODIM+1:RHODIM+DENDIM,1)
!     == KERKER-PRECONDITION THE DENSITY PART OF THE RESIDUAL (NOT THE   ==
!     == ONE-CENTER DENMAT PART -- SEE MIX_KERKERFILTER) BEFORE IT FEEDS ==
!     == THE HISTORY/FIT BELOW. TCONV/RESVAR/THE RESTART DECISION ABOVE  ==
!     == ALREADY USED THE RAW (UNFILTERED) RESIDUAL, AS THEY SHOULD.     ==
      CALL MIX_KERKERFILTER(NRL,NDIMD,G0SQ,RESOLD(1:RHODIM,1))
      !RHOOUT=RHOOLD(:,1)+G*RESOLD(:,1)  ! LINEAR PART OF EQ. 92
      NBACK=MIN(NHISTORY,NVALID)

      RHOX=RHODIM ! USE ONLY DENSITY FOR ADJUSTING FITTING
      !RHOX=RHODIM+DENDIM ! ALSO USE DENAMT FOR FITTING
!!$      DO IH1=2,NBACK ! EQ. 91
!!$         DO IH2=IH1,NBACK
!!$            CALL LIB$SCALARPRODUCTR8(.FALSE.,RHOX,1,&
!!$                 RESOLD(1:RHOX,IH1),1,&
!!$                 RESOLD(1:RHOX,IH2),&
!!$                 A(IH1,IH2))
!!$            A(IH2,IH1)=A(IH1,IH2)
!!$         END DO
!!$      END DO
      ! EQ. 87
      CALL LIB$SCALARPRODUCTR8(.TRUE.,RHOX,NBACK,&
           RESOLD(1:RHOX,1:NBACK),NBACK,RESOLD(1:RHOX,1:NBACK),&
           A(1:NBACK,1:NBACK))
      IF(NBACK.GE.1) CALL MIX_COMBINEMONOMER(NBACK,A(1:NBACK,1:NBACK),ALPHABAR(1:NBACK))

      IF(NBACK.GE.1) THEN
!        == TIKHONOV-REGULARIZE THE HISTORY-OVERLAP MATRIX BEFORE INVERTING.
!        == UNREGULARIZED PULAY/DIIS FITTING CAN BLOW UP WHEN TWO RESIDUAL
!        == HISTORY VECTORS BECOME NEARLY PARALLEL (NBACK>=2), PRODUCING AN
!        == EXTRAPOLATION STEP MANY ORDERS OF MAGNITUDE TOO LARGE; A SMALL
!        == DIAGONAL SHIFT RELATIVE TO THE MATRIX'S OWN SCALE FIXES THAT
!        == WITHOUT AFFECTING NBACK=1 (PURE LINEAR MIXING, NO RISK THERE).
         REGVAR=0.D0
         DO IH1=1,NBACK
            REGVAR=REGVAR+A(IH1,IH1)
         END DO
         REGVAR=MAX(REGVAR/REAL(NBACK,KIND=8)*1.D-6,1.D-12)
         DO IH1=1,NBACK
            A(IH1,IH1)=A(IH1,IH1)+REGVAR
         END DO
         CALL LIB$INVERTR8(NBACK,A(1:NBACK,1:NBACK),AINV(1:NBACK,1:NBACK))
      END IF
!     == NBACK=0 RIGHT AFTER A RESTARTED-DIIS RESTART (NO HISTORY YET) --  ==
!     == JUST DO PLAIN LINEAR MIXING FOR THIS STEP; THE ALPHABAR FIT BELOW ==
!     == WOULD DIVIDE BY ZERO (EMPTY SUM) OTHERWISE.                       ==
      IF(NBACK.EQ.0) THEN
         RHOOUT=RHOOLD(:,1)+G*RESOLD(:,1)
      ELSE
      SVAR=0.D0
      DO IH1=1,NBACK ! EQ 87
         DO IH2=1,NBACK
            SVAR=SVAR+AINV(IH1,IH2)
         END DO
      END DO
      ALPHABAR=0.D0
      DO IH1=1,NBACK ! EQ 87
         DO IH2=1,NBACK
            ALPHABAR(IH1)=ALPHABAR(IH1)+AINV(IH1,IH2)
         END DO
      END DO
      ALPHABAR=ALPHABAR/SVAR
      RHOOUT=0.D0
      DO IH1=1,NBACK ! EQ 83
         RHOOUT=RHOOUT+ALPHABAR(IH1)*(RHOOLD(:,IH1)+G*RESOLD(:,IH1))
      END DO
      END IF
!     == SAFEGUARD: IF THE EXTRAPOLATED STEP IS MUCH LARGER THAN THE RAW  ==
!     == (UNMIXED) DENSITY CHANGE THIS ITERATION, THE FIT ABOVE HAS       ==
!     == OVERSHOT (RESIDUAL REGULARIZATION ALONE DOESN'T CATCH EVERY      ==
!     == ILL-CONDITIONED CASE) -- FALL BACK TO PLAIN LINEAR MIXING FOR    ==
!     == THIS STEP'S OUTPUT ONLY. HISTORY STILL RECORDS THE TRUE RESULT. ==
      CALL LIB$SCALARPRODUCTR8(.TRUE.,RHOX,1,&
           RHOOUT(1:RHOX)-RHOOLD(1:RHOX,1),1,&
           RHOOUT(1:RHOX)-RHOOLD(1:RHOX,1),c)
      STEPVAR=c(1,1)
      CALL MPE$COMBINE('MONOMER','+',STEPVAR)
      IF(STEPVAR.GT.100.D0*MAX(RESVAR,1.D-12)) THEN
         RHOOUT=RHOOLD(:,1)+G*RESOLD(:,1)
      END IF
      ! MAP RHOOLD ON RHO AND DENMAT
      RHO(:)=RHOOUT(1:RHODIM)
      DENMAT(:)=RHOOUT(RHODIM+1:RHODIM+DENDIM)
      ! PROPAGATE RHOOLD AND RESOLD
      DO IH1=NHISTORY,2,-1
         RHOOLD(:,IH1)=RHOOLD(:,IH1-1)
         RESOLD(:,IH1)=RESOLD(:,IH1-1)
      END DO
      RHOOLD(:,1)=RHOOUT
      NVALID=NVALID+1
      DEALLOCATE(RHOOUT)
      RETURN
      END
