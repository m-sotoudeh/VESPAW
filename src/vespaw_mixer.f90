      SUBROUTINE MIX_COMBINEMONOMER(N,A,B)
!     ** SUMS THE LOCAL CONTRIBUTIONS TO A HISTORY-OVERLAP MATRIX A AND **
!     ** A VECTOR B OVER THE TASKS OF THE MONOMER, WHICH SHARE THE      **
!     ** DENSITY GRID. B IS ONLY A WORK VECTOR FOR CALLERS WITHOUT ONE. **
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN)    :: N
      REAL(8)   ,INTENT(INOUT) :: A(N,N)
      REAL(8)   ,INTENT(INOUT) :: B(N)
      REAL(8)                  :: W(N*N+N)
!     ******************************************************************
      W(1:N*N)=RESHAPE(A,(/N*N/))
      W(N*N+1:N*N+N)=B
      CALL MPE$COMBINE('MONOMER','+',W)
      A=RESHAPE(W(1:N*N),(/N,N/))
      B=W(N*N+1:N*N+N)
      RETURN
      END
