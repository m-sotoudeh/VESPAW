MODULE MIXVAR_MODULE
!     ** STATE FOR WAVES_MIXPOT_VAR (MIXER='VARIATIONAL'). THE VARIABLE   **
!     ** IS THE HAMILTONIAN PARAMETER VECTOR THETA (GRID POTENTIAL, AND   **
!     ** ONE-CENTER DH), NOT THE DENSITY -- SEE WAVES_MIXPOT_VAR.         **
  INTEGER(4)           ,SAVE :: NHISTORY=4
  INTEGER(4)           ,SAVE :: NWARM=2            ! #(FIXED-THETA WARM-UP STEPS AFTER THE FIRST)
  INTEGER(4)           ,SAVE :: NREJMAX=5          ! #(CONSECUTIVE REJECTIONS BEFORE RE-ANCHORING)
  REAL(8)              ,SAVE :: ETOL=1.D-7         ! ACCEPTANCE SLACK [H] FOR DIAGONALIZATION NOISE
  REAL(8)  ,ALLOCATABLE,SAVE :: THETA(:)   ! THETA THAT PRODUCED THE CURRENT STATE
  REAL(8)  ,ALLOCATABLE,SAVE :: XH(:,:)    ! ACCEPTED THETAS, COL 1 = BEST (NEWEST ACCEPTED)
  REAL(8)  ,ALLOCATABLE,SAVE :: FH(:,:)    ! THEIR PRECONDITIONED RESIDUALS
  REAL(8)  ,ALLOCATABLE,SAVE :: RES(:)     ! WORK: RAW RESIDUAL V_OUT-THETA
  REAL(8)  ,ALLOCATABLE,SAVE :: XPROP(:)   ! WORK: NEXT THETA
  REAL(8)              ,SAVE :: ABEST=HUGE(1.D0)   ! FREE ENERGY AT XH(:,1)
  REAL(8)              ,SAVE :: BETA=0.3D0
  LOGICAL(4)           ,SAVE :: TFIRST=.TRUE.
  INTEGER(4)           ,SAVE :: NEVAL=0
  INTEGER(4)           ,SAVE :: NVALID=0            ! #(VALID HISTORY COLUMNS, INCL. BEST)
  INTEGER(4)           ,SAVE :: NREJ=0              ! #(CONSECUTIVE REJECTIONS)
  LOGICAL(4)           ,SAVE :: TCLEAN=.FALSE.      ! NO REJECTION SINCE THE LAST ACCEPTANCE
  INTEGER(4)           ,SAVE :: NACCTOT=0,NREJTOT=0,NANCHORTOT=0
  REAL(8)              ,SAVE :: RESIDUAL=0.D0  ! MEAN-SQUARE GRID POTENTIAL RESIDUAL [H**2]
  LOGICAL(4)           ,SAVE :: TACTIVE=.FALSE.
  INTEGER(4)           ,SAVE :: NSMALLDE=0   ! #(CONSECUTIVE CLEAN ACCEPTS WITH A GAIN BELOW EDIFF)
  INTEGER(4)           ,SAVE :: NACCSTREAK=0 ! #(CONSECUTIVE ACCEPTED STEPS)
  LOGICAL(4)           ,SAVE :: TBACKACC=.FALSE. ! LAST ACCEPTED STEP FOLLOWED A REJECTION
  REAL(8)              ,SAVE :: GAUGELAST=0.D0 ! UNIFORM SHIFT APPLIED TO THETA IN THE LAST CALL
  REAL(8)              ,SAVE :: GAUGETOL=0.5D0 ! [H] REALIGN THETA ONLY BEYOND THIS OFFSET
  LOGICAL(4)           ,SAVE :: TNOGAUGE=.FALSE. ! DIAGNOSTIC: NO GAUGE PROJECTION
  LOGICAL(4)           ,SAVE :: TNOAVG=.FALSE.   ! DIAGNOSTIC: PLAIN KERKER ON THE GRID
!   == GRID POINTS WITHOUT ELECTRONS (VACUUM): THERE THE DENSITY DOES NOT ==
!   == RESPOND TO THETA, SO THETA IS SET TO THE OUTPUT POTENTIAL INSTEAD OF ==
!   == BEING LINE-SEARCHED. OTHERWISE THETA DRIFTS FREELY IN THE VACUUM OF  ==
!   == A SLAB OR MOLECULE CELL UNTIL VACUUM STATES BECOME OCCUPIED (H2O     ==
!   == LAYER, 18 A CELL: SCF STUCK 75 MH ABOVE THE MINIMUM).               ==
  LOGICAL(4),ALLOCATABLE,SAVE :: TVAC(:)     ! (NRL)
  REAL(8)              ,SAVE :: RHOVAC=1.D-6  ! DENSITY THRESHOLD [E/BOHR**3]
END MODULE MIXVAR_MODULE
