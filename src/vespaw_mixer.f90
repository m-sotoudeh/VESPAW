MODULE MIXKPC_MODULE
!     ** KERKER-PRECONDITIONED HAMILTONIAN FOR THE ROUTE-2 SEARCH DIRECTION ** 
!     ** (SEE MIXKPC$TRIAL): THE LAST COMMITTED THETA AND THE PENDING TRIAL.**
  REAL(8),ALLOCATABLE,SAVE :: THETAC(:)   ! COMMITTED THETA
  REAL(8),ALLOCATABLE,SAVE :: THETAT(:)   ! TRIAL THETA FROM THE LAST MIXKPC$TRIAL
  LOGICAL(4)         ,SAVE :: TINI=.FALSE.
END MODULE MIXKPC_MODULE
!
!     ..................................................................
      SUBROUTINE MIXKPC$TRIAL(NRL,NDIMD,G0SQ,NTOT,NGRID,X,SHIFT)
!     ******************************************************************
!     ** KERKER PRECONDITIONING FOR DIRECT MINIMIZATION (ROUTE 2).     **
!     ** ON INPUT X=V_OUT, THE HAMILTONIAN PARAMETERS (GRID POTENTIAL, **
!     ** ONE-CENTER DH) OF THE CURRENT STATE; ON OUTPUT X=THETA, THE   **
!     ** HAMILTONIAN FROM WHICH THE ORBITAL SEARCH DIRECTION IS BUILT: **
!     **     THETA = THETA_C + K*(V_OUT-THETA_C),                      **
!     ** K=G**2/(G**2+G0SQ) ON THE GRID (G=0 AND DH UNFILTERED), WITH  **
!     ** THE UNIFORM-SHIFT GAUGE PROJECTED OUT. A LONG-WAVELENGTH      **
!     ** DENSITY ERROR THEN ENTERS THE DIRECTION THROUGH THE SCREENED  **
!     ** 4*PI/(G**2+G0SQ) INSTEAD OF THE BARE 4*PI/G**2 HARTREE        **
!     ** RESPONSE, WHICH IS WHAT FORCES TINY STEPS (PLATEAUS) ON LARGE **
!     ** CELLS. THE ENERGY TEST ON THE TRUE FUNCTIONAL IS UNTOUCHED.   **
!     ** THETA_C ADVANCES ONLY VIA MIXKPC$COMMIT, CALLED WHEN THE LINE **
!     ** SEARCH ACCEPTS A NEW POINT; THE FIRST CALL RETURNS V_OUT.     **
!     ******************************************************************
      USE MIXKPC_MODULE
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4),INTENT(IN)    :: NRL
      INTEGER(4),INTENT(IN)    :: NDIMD
      REAL(8)   ,INTENT(IN)    :: G0SQ
      INTEGER(4),INTENT(IN)    :: NTOT
      INTEGER(4),INTENT(IN)    :: NGRID
      REAL(8)   ,INTENT(INOUT) :: X(NTOT)
      REAL(8)   ,INTENT(IN)    :: SHIFT(NTOT)
      REAL(8)   ,ALLOCATABLE   :: R(:)
      REAL(8)                  :: CSHIFT(2),VAV(NDIMD),VAVF(NDIMD),RNRL
      INTEGER(4)               :: IDIM,I0
!     ******************************************************************
      IF(ALLOCATED(THETAT)) DEALLOCATE(THETAT)
      ALLOCATE(THETAT(NTOT))
      IF(.NOT.TINI) THEN
        THETAT=X
        RETURN
      END IF
      IF(SIZE(THETAC).NE.NTOT) THEN
        CALL ERROR$MSG('THETA SIZE CHANGED BETWEEN CALLS')
        CALL ERROR$STOP('MIXKPC$TRIAL')
      END IF
      ALLOCATE(R(NTOT))
      R=X-THETAC
      CSHIFT(1)=SUM(R(1:NGRID)*SHIFT(1:NGRID))
      CSHIFT(2)=SUM(SHIFT(1:NGRID)**2)
      CALL MPE$COMBINE('MONOMER','+',CSHIFT)
      R=R-CSHIFT(1)/CSHIFT(2)*SHIFT
!     == KERKER ON THE GRID PART, KEEPING THE (GLOBAL) G=0 COMPONENT ====
      RNRL=REAL(NRL,KIND=8)
      CALL MPE$COMBINE('MONOMER','+',RNRL)
      DO IDIM=1,NDIMD
        I0=(IDIM-1)*NRL
        VAV(IDIM)=SUM(R(I0+1:I0+NRL))
      ENDDO
      CALL MPE$COMBINE('MONOMER','+',VAV)
      CALL MIX_KERKERFILTER(NRL,NDIMD,G0SQ,R(1:NGRID))
      DO IDIM=1,NDIMD
        I0=(IDIM-1)*NRL
        VAVF(IDIM)=SUM(R(I0+1:I0+NRL))
      ENDDO
      CALL MPE$COMBINE('MONOMER','+',VAVF)
      DO IDIM=1,NDIMD
        I0=(IDIM-1)*NRL
        R(I0+1:I0+NRL)=R(I0+1:I0+NRL)+(VAV(IDIM)-VAVF(IDIM))/RNRL
      ENDDO
      X=THETAC+R
      THETAT=X
      DEALLOCATE(R)
      RETURN
      END
!
!     ..................................................................
      SUBROUTINE MIXKPC$COMMIT()
!     ** THE LAST TRIAL THETA BECOMES THE COMMITTED ONE (SEE MIXKPC$TRIAL)
      USE MIXKPC_MODULE
      IMPLICIT NONE
      IF(.NOT.ALLOCATED(THETAT)) RETURN
      IF(ALLOCATED(THETAC)) DEALLOCATE(THETAC)
      ALLOCATE(THETAC(SIZE(THETAT)))
      THETAC=THETAT
      TINI=.TRUE.
      RETURN
      END
!
!     ..................................................................
      SUBROUTINE MIXER$SETRESIDUAL(VAL_)
!     **************************************************************************
!     ** LETS A NON-MIXING VARIATIONAL OPTIMIZER (EDFT$VARSTEP, VESPAW_CG.F90)**
!     ** REPORT ITS OWN CONVERGENCE MEASURE IN THE SCF TABLE'S RESIDUAL       **
!     ** COLUMN, VIA THE SAME MIXER$GETR8('RESIDUAL',...) ACCESSOR.           **
!     **************************************************************************
      USE MIXVAR_MODULE, ONLY: RESIDUAL,TACTIVE
      IMPLICIT NONE
      REAL(8),INTENT(IN) :: VAL_
!     **************************************************************************
      RESIDUAL=VAL_
      TACTIVE=.TRUE.
      RETURN
      END
!
!     ..................................................................
      SUBROUTINE MIXER$GETI4(ID_,VAL_)
!     **************************************************************************
!     ** COUNTERS OF THE VARIATIONAL MIXER (MIXER='VARIATIONAL'): #ACCEPTED,  **
!     ** #REJECTED LINE-SEARCH STEPS AND #RE-ANCHORS SO FAR.                  **
!     **************************************************************************
      USE MIXVAR_MODULE, ONLY: NACCTOT,NREJTOT,NANCHORTOT
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN)  :: ID_
      INTEGER(4)  ,INTENT(OUT) :: VAL_
!     **************************************************************************
      IF(ID_.EQ.'NACCEPT') THEN
        VAL_=NACCTOT
      ELSE IF(ID_.EQ.'NREJECT') THEN
        VAL_=NREJTOT
      ELSE IF(ID_.EQ.'NREANCHOR') THEN
        VAL_=NANCHORTOT
      ELSE
        CALL ERROR$MSG('IDENTIFIER NOT RECOGNIZED')
        CALL ERROR$CHVAL('ID_',ID_)
        CALL ERROR$STOP('MIXER$GETI4')
      END IF
      RETURN
      END


!
!     ..................................................................
      SUBROUTINE MIXER$GETR8(ID_,VAL_)
!     **************************************************************************
!     ** EXPOSES THE ACTIVE DENSITY MIXER'S LAST "RHO-DIFF" RESIDUAL --       **
!     ** PREVIOUSLY PRINT*-ONLY (SEE THE NOW-VERBOSITY-DEBUG-GATED LINES      **
!     ** ABOVE), NEEDED BY THE COMPACT LIVE SCF TABLE (SCFREPORT$ITERATION,   **
!     ** SRC/VESPAW_DRIVER.F90). WHICHEVER MIXER (PULAY OR ANDERSON) HAS      **
!     ** ACTUALLY RUN AT LEAST ONCE (MIXPULAY_MODULE/MIXANDERSON_MODULE'S     **
!     ** OWN TACTIVE FLAG, SET UNCONDITIONALLY ON EVERY CALL) IS THE ONE      **
!     ** REPORTED -- ONLY ONE OF THE TWO IS EVER ACTIVE IN A GIVEN RUN        **
!     ** (SELECTED VIA !PSIDYN MIXER='PULAY'|'ANDERSON'), SO THERE IS NO      **
!     ** AMBIGUITY IN PRACTICE. RETURNS 0 IF NEITHER HAS RUN YET (E.G. THE    **
!     ** VERY FIRST STEP, OR AN OPTIMIZER THAT DOESN'T MIX AT ALL, LIKE 'MD').**
!     **************************************************************************
      USE MIXPULAY_MODULE, ONLY: RESIDUAL_PUL=>RESIDUAL,TACTIVE_PUL=>TACTIVE
      USE MIXANDERSON_MODULE, ONLY: RESIDUAL_AND=>RESIDUAL,TACTIVE_AND=>TACTIVE
      USE MIXVAR_MODULE, ONLY: RESIDUAL_VAR=>RESIDUAL,TACTIVE_VAR=>TACTIVE
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN)  :: ID_
      REAL(8)     ,INTENT(OUT) :: VAL_
!     **************************************************************************
      IF(ID_.EQ.'RESIDUAL') THEN
        IF(TACTIVE_PUL) THEN
          VAL_=RESIDUAL_PUL
        ELSE IF(TACTIVE_AND) THEN
          VAL_=RESIDUAL_AND
        ELSE IF(TACTIVE_VAR) THEN
          VAL_=RESIDUAL_VAR
        ELSE
          VAL_=0.D0
        END IF
      ELSE
        CALL ERROR$MSG('IDENTIFIER NOT RECOGNIZED')
        CALL ERROR$CHVAL('ID_',ID_)
        CALL ERROR$STOP('MIXER$GETR8')
      END IF
      RETURN
      END
