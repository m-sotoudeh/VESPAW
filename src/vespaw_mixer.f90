      SUBROUTINE MIX_KERKERFILTER(NRL,NDIMD,G0SQ,V)
!     ******************************************************************
!     ** APPLIES A KERKER PRECONDITIONER TO THE REAL-SPACE PLANE-WAVE **
!     ** DENSITY RESIDUAL V(NRL,NDIMD), IN PLACE: TRANSFORM TO        **
!     ** G-SPACE ON THE 'DENSITY' PLANE-WAVE GRID, MULTIPLY EACH      **
!     ** COMPONENT BY G**2/(G**2+G0SQ) (KERKER, PHYS. REV. B 23, 3082 **
!     ** (1981)) EXCEPT AT G=0, TRANSFORM BACK. DAMPS LONG-WAVELENGTH  **
!     ** CHARGE-SLOSHING MODES THAT PLAIN PULAY/ANDERSON MIXING       **
!     ** (BOTH UNPRECONDITIONED, REAL-SPACE SCHEMES) CANNOT SEE       **
!     ** COMING -- OBSERVED TO BE THE DOMINANT SCF INSTABILITY ON A   **
!     ** CORRELATED TRANSITION-METAL-OXIDE TEST CASE (SEE             **
!     ** optimizer_compare_pmo_a/ IN THE SCAN0R WORKING DIRECTORY).   **
!     **                                                              **
!     ** APPLIED IDENTICALLY TO EVERY NDIMD CHANNEL (TOTAL DENSITY    **
!     ** AND, IF PRESENT, SPIN/MAGNETIZATION) AS A SIMPLIFICATION --  **
!     ** THE CHARGE-SLOSHING INSTABILITY KERKER TARGETS IS AN         **
!     ** ELECTROSTATIC (HARTREE) EFFECT ON THE TOTAL DENSITY, SO      **
!     ** THIS IS SOMEWHAT MORE AGGRESSIVE THAN STRICTLY NECESSARY ON  **
!     ** THE SPIN CHANNEL(S), BUT NOT INCORRECT.                      **
!     **                                                              **
!     ** ONLY MEANINGFUL FOR THE PLANE-WAVE (INTERSTITIAL) DENSITY -- **
!     ** DO NOT CALL THIS ON THE ONE-CENTER DENSITY MATRIX, WHICH IS  **
!     ** A LOCALIZED ATOMIC-ORBITAL-BASIS QUANTITY WITH NO G-SPACE    **
!     ** REPRESENTATION.                                              **
!     **                                                              **
!     ** G0SQ IS SET VIA !PSIDYN MIXG0SQ=... (DEFAULT 1.5, SEE        **
!     ** READIN_PSIDYN IN paw_ioroutines.f90); PASSED IN RATHER THAN  **
!     ** HARDCODED SO IT CAN BE RETUNED PER SYSTEM WITHOUT A REBUILD. **
!     ******************************************************************
      IMPLICIT NONE
      INTEGER(4) ,INTENT(IN)    :: NRL
      INTEGER(4) ,INTENT(IN)    :: NDIMD
      REAL(8)    ,INTENT(IN)    :: G0SQ  ! KERKER SCREENING WAVEVECTOR**2 [BOHR**-2]
      REAL(8)    ,INTENT(INOUT) :: V(NRL,NDIMD)
      CHARACTER(32)             :: SAVEDID
      CHARACTER(32)             :: CENV
      LOGICAL(4),SAVE           :: TG0CHECKED=.FALSE.
      LOGICAL(4),SAVE           :: TFILTERG0=.FALSE. ! DIAGNOSTIC: OLD G=0 BUG
      INTEGER(4)                :: NGL
      REAL(8)   ,ALLOCATABLE    :: G2(:)
      COMPLEX(8),ALLOCATABLE    :: VG(:,:)
      INTEGER(4)                :: IG,IDIM
!     ******************************************************************
!     == DIAGNOSTIC SWITCH VESPAW_DIAG_KERKERG0 (ANY NONEMPTY VALUE):     ==
!     == REPRODUCES THE PRE-2026-09-23 BUG (G=0 COMPONENT FILTERED TO     ==
!     == ZERO) FOR DOCUMENTATION. NEVER USE IT FOR PRODUCTION RUNS.       ==
      IF(.NOT.TG0CHECKED) THEN
        CENV=' '
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_DIAG_KERKERG0',CENV)
        TFILTERG0=(LEN_TRIM(CENV).GT.0)
        IF(TFILTERG0) PRINT*,'DIAGNOSTIC VESPAW_DIAG_KERKERG0: G=0 FILTERED (OLD BUG)'
        TG0CHECKED=.TRUE.
      END IF
      CALL PLANEWAVE$GETCH('ID',SAVEDID)
      CALL PLANEWAVE$SELECT('DENSITY')
      CALL PLANEWAVE$GETI4('NGL',NGL)
      ALLOCATE(G2(NGL))
      CALL PLANEWAVE$GETR8A('G2',NGL,G2)
      ALLOCATE(VG(NGL,NDIMD))
      CALL PLANEWAVE$SUPFFT('RTOG',NDIMD,NGL,VG,NRL,V)
!     == THE G=0 COMPONENT IS LEFT UNFILTERED (FACTOR 1, NOT 0): IN PAW   ==
!     == THE PSEUDO-DENSITY'S AVERAGE CHANGES WHENEVER CHARGE MOVES        ==
!     == BETWEEN THE GRID AND THE AUGMENTATION SPHERES; FILTERING IT TO    ==
!     == ZERO MEANT IT WAS NEVER MIXED, AND PULAY/ANDERSON STALLED AT A    ==
!     == FROZEN RESIDUAL AND A WRONG ENERGY (SI: -7.9147 INSTEAD OF        ==
!     == -8.00703 H). FIXED 2026-09-23, SEE THE DEV NOTES.             ==
      DO IDIM=1,NDIMD
         DO IG=1,NGL
            IF(G2(IG).LT.1.D-10.AND..NOT.TFILTERG0) CYCLE
            VG(IG,IDIM)=VG(IG,IDIM)*(G2(IG)/(G2(IG)+G0SQ))
         END DO
      END DO
      CALL PLANEWAVE$SUPFFT('GTOR',NDIMD,NGL,VG,NRL,V)
      DEALLOCATE(VG)
      DEALLOCATE(G2)
      CALL PLANEWAVE$SELECT(SAVEDID)
      RETURN
      END
