      SUBROUTINE MIXVAR$GETGAUGESHIFT(VAL)
!     **  UNIFORM SHIFT (H -> H+VAL*O) APPLIED TO THETA IN THE LAST CALL;  **
!     **  THE EIGENVALUES OF THE NEXT HAMILTONIAN MOVE BY EXACTLY VAL     **
      USE MIXVAR_MODULE, ONLY: GAUGELAST
      IMPLICIT NONE
      REAL(8),INTENT(OUT) :: VAL
      VAL=GAUGELAST
      RETURN
      END
!
!     ..................................................................
      SUBROUTINE MIXVAR$SETDENSITY(NRL,RHO)
!     **  MARKS THE VACUUM POINTS OF THE (TOTAL) OUTPUT DENSITY          **
      USE MIXVAR_MODULE, ONLY: TVAC,RHOVAC
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: NRL
      REAL(8)   ,INTENT(IN) :: RHO(NRL)
      IF(ALLOCATED(TVAC)) THEN
        IF(SIZE(TVAC).NE.NRL) DEALLOCATE(TVAC)
      END IF
      IF(.NOT.ALLOCATED(TVAC)) ALLOCATE(TVAC(NRL))
      TVAC=ABS(RHO).LT.RHOVAC
      RETURN
      END
!
!     ..................................................................
      SUBROUTINE WAVES_MIXPOT_VAR(NRL,NDIMD,G0SQ,NHISTORYIN,NTOT,NGRID,X,SHIFT &
     &                           ,ENERGY,CONVTOL,EDIFF,TCONV,CONVPSI)
!     ******************************************************************
!     ** VARIATIONAL SCF (MIXER='VARIATIONAL'): MINIMIZES THE FREE     **
!     ** ENERGY A(THETA)=E_KS[PSI(THETA),F(THETA)]-TS[F(THETA)] OVER   **
!     ** THE PARAMETERS THETA OF THE KOHN-SHAM HAMILTONIAN H[THETA]    **
!     ** (PLANE-WAVE GRID POTENTIAL, OPTIONALLY VTAU, AND THE PAW      **
!     ** ONE-CENTER HAMILTONIAN DH), WHERE PSI(THETA) ARE THE (WARM-   **
!     ** STARTED, ITERATIVELY CONVERGED) EIGENSTATES OF H[THETA] AND   **
!     ** F(THETA) THEIR FERMI OCCUPATIONS AT FIXED ELECTRON NUMBER.    **
!     **                                                              **
!     ** ENERGY IS EVALUATED AT THE UNMIXED OUTPUT STATE, SO EVERY     **
!     ** VALUE IS THE ENERGY FUNCTIONAL OF AN ACTUAL ORTHONORMAL       **
!     ** ENSEMBLE AND THEREFORE AN UPPER BOUND ON ITS MINIMUM.         **
!     ** GRADIENT: DA/DTHETA = CHI*(V_OUT-THETA), CHI THE (NEGATIVE    **
!     ** SEMIDEFINITE) STATIC RESPONSE, SO THE (KERKER-PRECONDITIONED) **
!     ** SCF RESIDUAL IS A DESCENT DIRECTION WITHOUT EVER BUILDING     **
!     ** CHI (GONZE, PRB 54, 4383 (1996)). ANDERSON EXTRAPOLATION OVER **
!     ** ACCEPTED POINTS PROPOSES THE STEP; A PROPOSAL IS ACCEPTED ONLY **
!     ** IF A DOES NOT RISE (BY MORE THAN ETOL), OTHERWISE IT IS       **
!     ** HALVED BACK TOWARDS THE BEST POINT (BACKTRACKING LINE SEARCH).**
!     ** AFTER NREJMAX CONSECUTIVE REJECTIONS THE BEST POINT ITSELF IS **
!     ** RE-EVALUATED ("RE-ANCHOR") -- THE STORED ABEST MAY BE STALE   **
!     ** BECAUSE THE DIAGONALIZATION BEHIND IT WAS NOT YET CONVERGED.  **
!     **                                                              **
!     ** ON INPUT X IS V_OUT, THE HAMILTONIAN PARAMETERS BUILT FROM    **
!     ** THE CURRENT OUTPUT STATE; ON OUTPUT X IS THE THETA TO USE FOR **
!     ** THE NEXT DIAGONALIZATION. X(1:NGRID) IS THE GRID POTENTIAL    **
!     ** (KERKER-PRECONDITIONED, USED FOR THE ANDERSON FIT AND THE     **
!     ** RESIDUAL NORM); X(NGRID+1:NTOT) IS EVERYTHING ELSE (PLAIN     **
!     ** DAMPED STEPS). CONVTOL IS COMPARED WITH THE MEAN-SQUARE GRID  **
!     ** POTENTIAL RESIDUAL [H**2] AT ACCEPTED POINTS; ALTERNATIVELY   **
!     ** THE RUN IS CONVERGED WHEN TWO SUCCESSIVE ACCEPTED ENERGIES    **
!     ** DIFFER BY LESS THAN EDIFF.                                    **
!     **                                                              **
!     ** GAUGE: A UNIFORM SHIFT OF H (SHIFT, = +1 ON THE GRID AND DO   **
!     ** IN DH, SEE WAVES$ADDCONSTANTPOT) ONLY SHIFTS THE EIGENVALUES  **
!     ** AND THE FERMI LEVEL AT FIXED N, SO IT IS AN EXACT NULL        **
!     ** DIRECTION OF A(THETA). IT IS PROJECTED OUT OF EVERY RESIDUAL, **
!     ** SO THETA NEVER MOVES ALONG IT. WITHOUT THIS THE GRID AND DH   **
!     ** PARTS OF THE SHIFT (MIXED BY DIFFERENT RULES) DRIFT APART AND **
!     ** ACT AS A SPURIOUS SPHERE-VS-INTERSTITIAL POTENTIAL STEP --    **
!     ** OBSERVED ON SI (6X6X6) TO CONVERGE TO AN EXCITED STATE WITH   **
!     ** A NEGATIVE GAP, 28 MH ABOVE THE GROUND STATE.                 **
!     ******************************************************************
      USE MIXVAR_MODULE
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4) ,INTENT(IN)    :: NRL
      INTEGER(4) ,INTENT(IN)    :: NDIMD
      REAL(8)    ,INTENT(IN)    :: G0SQ
      INTEGER(4) ,INTENT(IN)    :: NHISTORYIN ! 0=KEEP MODULE DEFAULT; USED ON FIRST CALL ONLY
      INTEGER(4) ,INTENT(IN)    :: NTOT
      INTEGER(4) ,INTENT(IN)    :: NGRID   ! =NRL*NDIMD
      REAL(8)    ,INTENT(INOUT) :: X(NTOT)
      REAL(8)    ,INTENT(IN)    :: SHIFT(NTOT) ! UNIFORM-SHIFT (GAUGE) DIRECTION OF THETA
      REAL(8)    ,INTENT(IN)    :: ENERGY  ! FREE ENERGY OF THE CURRENT OUTPUT STATE
      REAL(8)    ,INTENT(IN)    :: CONVTOL
      REAL(8)    ,INTENT(IN)    :: EDIFF   ! ACCEPTED-ENERGY CHANGE BELOW WHICH TCONV
      LOGICAL(4) ,INTENT(OUT)   :: TCONV
      REAL(8)    ,INTENT(OUT)   :: CONVPSI
      REAL(8)    ,PARAMETER     :: BETAMIN=0.02D0,BETAMAX=0.5D0
      REAL(8)   ,ALLOCATABLE    :: DF(:,:),DX(:,:)
      REAL(8)   ,ALLOCATABLE    :: A(:,:),AINV(:,:),B(:),GAMMA(:)
      REAL(8)                   :: SVAR,RESNOW,STEPVAR,FVAR,RNGRID,REGVAR
      REAL(8)                   :: CSHIFT(2),AOLD,GAUGEOFF
      INTEGER(4)                :: IDIMV
      REAL(8)                   :: RESREST ! MAX|RESIDUAL| OUTSIDE THE GRID (DH, VTAU)
      INTEGER(4)                :: IH1,IH2,NBACK
      LOGICAL(4)                :: TACCEPT
      CHARACTER(10)             :: CSTATUS
      CHARACTER(32)             :: CENV
      INTEGER(4)                :: NTASKS,THISTASK,NFILO
      LOGICAL(4)                :: TDEBUG
!     ******************************************************************
      CALL MPE$QUERY('~',NTASKS,THISTASK)
      CALL VERBOSITY$GETL4('DEBUG',TDEBUG)
      GAUGELAST=0.D0
      TACTIVE=.TRUE.
      TCONV=.FALSE.
      IF(TFIRST) THEN
        IF(NHISTORYIN.GT.0) NHISTORY=NHISTORYIN
!       == EXPERT OVERRIDES (UNDOCUMENTED TUNING KNOBS) =================
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_VARMIX_NWARM',CENV)
        IF(LEN_TRIM(CENV).GT.0) READ(CENV,*) NWARM
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_VARMIX_ETOL',CENV)
        IF(LEN_TRIM(CENV).GT.0) READ(CENV,*) ETOL
        CENV=' '
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_VARMIX_RHOVAC',CENV)
        IF(LEN_TRIM(CENV).GT.0) READ(CENV,*) RHOVAC
!       == DIAGNOSTIC SWITCH VESPAW_DIAG_NOGAUGEPROJ (ANY NONEMPTY VALUE): ==
!       == THE PAW GAUGE MODE IS NEITHER PROJECTED OUT NOR REALIGNED, AS   ==
!       == BEFORE THE FIX, TO DOCUMENT THE EXCITED-STATE TRAP. NEVER USE   ==
!       == IT FOR PRODUCTION RUNS.                                         ==
        CENV=' '
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_DIAG_NOGAUGEPROJ',CENV)
        TNOGAUGE=(LEN_TRIM(CENV).GT.0)
        IF(TNOGAUGE.AND.THISTASK.EQ.1) PRINT*,'DIAGNOSTIC VESPAW_DIAG_NOGAUGEPROJ: GAUGE MODE NOT PROJECTED'
!       == DIAGNOSTIC SWITCH VESPAW_DIAG_KERKERNOAVG: THE GRID RESIDUAL IS ==
!       == FILTERED WITH THE PLAIN KERKER FORM (G=0 REMOVED), AS IN THE    ==
!       == ORIGINAL VARIATIONAL MIXER. NEVER USE IT FOR PRODUCTION RUNS.   ==
        CENV=' '
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_DIAG_KERKERNOAVG',CENV)
        TNOAVG=(LEN_TRIM(CENV).GT.0)
        IF(TNOAVG.AND.THISTASK.EQ.1) PRINT*,'DIAGNOSTIC VESPAW_DIAG_KERKERNOAVG: PLAIN KERKER (G=0 REMOVED)'
        ALLOCATE(THETA(NTOT))
        ALLOCATE(XH(NTOT,NHISTORY+1))
        ALLOCATE(FH(NTOT,NHISTORY+1))
        ALLOCATE(RES(NTOT))
        ALLOCATE(XPROP(NTOT))
        XH=0.D0
        FH=0.D0
!       == NOTHING HAS BEEN DIAGONALIZED YET: THE FIRST HAMILTONIAN IS  ==
!       == SIMPLY THE ONE BUILT FROM THE STARTING WAVE FUNCTIONS.       ==
        THETA=X
        NEVAL=1
        NVALID=0
        NREJ=0
        ABEST=HUGE(1.D0)
        BETA=0.3D0
        TFIRST=.FALSE.
        CONVPSI=1.D-3
        RETURN
      END IF
      NEVAL=NEVAL+1
!
!     ==================================================================
!     == RAW RESIDUAL R=V_OUT-THETA AND ITS MEAN-SQUARE GRID NORM     ==
!     ==================================================================
      RES=X-THETA
!     == PROJECT OUT THE GAUGE DIRECTION, MEASURED ON THE GRID PART ====
      CSHIFT(1)=SUM(RES(1:NGRID)*SHIFT(1:NGRID))
      CSHIFT(2)=SUM(SHIFT(1:NGRID)**2)
      CALL MPE$COMBINE('MONOMER','+',CSHIFT)
      IF(.NOT.TNOGAUGE) RES=RES-CSHIFT(1)/CSHIFT(2)*SHIFT
      GAUGEOFF=CSHIFT(1)/CSHIFT(2)
      SVAR=SUM(RES(1:NGRID)**2)
      CALL MPE$COMBINE('MONOMER','+',SVAR)
      RESREST=0.D0
      IF(NTOT.GT.NGRID) RESREST=MAXVAL(ABS(RES(NGRID+1:NTOT)))
      RNGRID=REAL(NGRID,KIND=8)
      CALL MPE$COMBINE('MONOMER','+',RNGRID)
      RESNOW=SVAR/RNGRID
      IF(RESNOW.GT.1.D-2) THEN
        CONVPSI=1.D-4
      ELSE IF(RESNOW.GT.1.D-6) THEN
        CONVPSI=1.D-6
      ELSE
        CONVPSI=1.D-8
      END IF
!
!     ==================================================================
!     == WARM-UP: HOLD THETA FIXED (NON-SELF-CONSISTENT DIAGONALIZATION==
!     == OF THE STARTING HAMILTONIAN) SO THAT THE FIRST ENERGY USED BY ==
!     == THE LINE SEARCH BELONGS TO REASONABLY CONVERGED EIGENSTATES.  ==
!     ==================================================================
      IF(NEVAL.LE.1+NWARM) THEN
        RESIDUAL=RESNOW
        X=THETA
        CALL MIXVAR_REPORT('WARMUP')
        RETURN
      END IF
!
!     ==================================================================
!     == LINE-SEARCH DECISION                                         ==
!     ==================================================================
!     == THE SLACK ETOL ABSORBS EIGENSOLVER NOISE FROM STEP TO STEP. IT  ==
!     == IS MEASURED FROM THE LAST ACCEPTED ENERGY. MEASURING IT FROM THE ==
!     == LOWEST ACCEPTED ENERGY (TRIED 2026-10-02, ALSO WITH A BOUNDED    ==
!     == SLACK OF 10*ETOL) LETS ONE LUCKY LOW EVALUATION BLOCK ALL LATER  ==
!     == STEPS OF NOISY RUNS: H2O IN VACUUM STALLED AT A RESIDUAL OF 1E-3.==
!     == THE PRICE IS THAT A STALLED RUN CAN CREEP UPWARD BY UP TO ETOL   ==
!     == PER ACCEPTED STEP (SEEN ONLY WITHOUT GAUGE PROJECTION).          ==
      TACCEPT=(ENERGY.LE.ABEST+ETOL)
      IF(TACCEPT) THEN
        CSTATUS='ACCEPT'
        IF(ABEST.EQ.HUGE(1.D0)) CSTATUS='START'
        NACCTOT=NACCTOT+1
        NREJ=0
        AOLD=ABEST
        ABEST=ENERGY
        RESIDUAL=RESNOW
!       == RESIDUAL CRITERION: THE MEAN-SQUARE GRID RESIDUAL BELOW       ==
!       == CONVTOL AND THE LARGEST DH/VTAU RESIDUAL BELOW SQRT(CONVTOL)   ==
!       == (THE SAME RMS SCALE). THE GRID ALONE CAN CONVERGE WHILE DH     ==
!       == STILL LAGS, LEAVING THE ENERGY TENS OF MICROHARTREE HIGH.      ==
        TCONV=(RESNOW.LT.CONVTOL).AND.(RESREST.LT.SQRT(CONVTOL))
!       == ENERGY CRITERION: TWO CONSECUTIVE CLEAN, FULL-LENGTH STEPS     ==
!       == THAT EACH GAINED LESS THAN EDIFF. AFTER BACKTRACKING OR WITH A ==
!       == COLLAPSED BETA A SMALL GAIN ONLY REFLECTS A SMALL STEP.        ==
        IF(CSTATUS.EQ.'ACCEPT'.AND.TCLEAN.AND.BETA.GE.0.25D0 &
     &     .AND.AOLD-ENERGY.LT.EDIFF) THEN
          NSMALLDE=NSMALLDE+1
        ELSE
          NSMALLDE=0
        END IF
        TCONV=TCONV.OR.(NSMALLDE.GE.2)
        TBACKACC=.NOT.TCLEAN.AND.CSTATUS.EQ.'ACCEPT'
        TCLEAN=.TRUE.
!       == PUSH (THETA, PRECONDITIONED RESIDUAL) ONTO THE HISTORY ======
!       == KERKER'S G**2/(G**2+G0SQ) VANISHES AT G=0. FOR A POTENTIAL   ==
!       == THE G=0 PART IS NOT A GAUGE BY ITSELF (ONLY TOGETHER WITH   ==
!       == ITS DO PART IN DH, ALREADY PROJECTED OUT ABOVE), E.G. FOR   ==
!       == THE SPIN CHANNEL -- SO KEEP IT UNFILTERED.                  ==
        CALL MIXVAR_KERKERKEEPAVERAGE(RES(1:NGRID))
        DO IH1=NHISTORY+1,2,-1
          XH(:,IH1)=XH(:,IH1-1)
          FH(:,IH1)=FH(:,IH1-1)
        ENDDO
        XH(:,1)=THETA
        FH(:,1)=RES
        NVALID=MIN(NVALID+1,NHISTORY+1)
!       == A THETA IDENTICAL TO THE PREVIOUS ONE (E.G. RE-EVALUATING THE ==
!       == BEST POINT AFTER A RE-ANCHOR) GIVES DX=0 WITH A NONZERO DF, A ==
!       == DEGENERATE ANDERSON COLUMN THAT CAN SEND THE EXTRAPOLATION    ==
!       == ANYWHERE -- DROP THE OLDER DUPLICATE FROM THE HISTORY.        ==
        IF(NVALID.GE.2) THEN
          STEPVAR=SUM((XH(1:NGRID,1)-XH(1:NGRID,2))**2)
          CALL MPE$COMBINE('MONOMER','+',STEPVAR)
          IF(STEPVAR.LE.1.D-24*RNGRID) THEN
            DO IH1=2,NHISTORY
              XH(:,IH1)=XH(:,IH1+1)
              FH(:,IH1)=FH(:,IH1+1)
            ENDDO
            NVALID=NVALID-1
          END IF
        END IF
!       == RECOVER THE STEP LENGTH QUICKLY ONLY WITHIN A STREAK OF CLEAN   ==
!       == ACCEPTED STEPS; RIGHT AFTER A REJECTION THE FASTER GROWTH SENT   ==
!       == MGO/SCAN0R+RMM INTO A WILD TRIAL AND AN EXCITED STATE.           ==
        IF(CSTATUS.EQ.'ACCEPT') THEN
          NACCSTREAK=NACCSTREAK+1
          IF(NACCSTREAK.GE.3) THEN
            BETA=MIN(BETA*1.5D0,BETAMAX)
          ELSE
            BETA=MIN(BETA*1.2D0,BETAMAX)
          END IF
        END IF
!
!       == ANDERSON PROPOSAL FROM THE ACCEPTED POINTS ==================
        NBACK=NVALID-1
        XPROP=XH(:,1)+BETA*FH(:,1)
        IF(NBACK.GT.0) THEN
          ALLOCATE(DF(NGRID,NBACK))
          ALLOCATE(DX(NGRID,NBACK))
          ALLOCATE(A(NBACK,NBACK))
          ALLOCATE(AINV(NBACK,NBACK))
          ALLOCATE(B(NBACK))
          ALLOCATE(GAMMA(NBACK))
          DO IH1=1,NBACK
            DF(:,IH1)=FH(1:NGRID,1)-FH(1:NGRID,IH1+1)
            DX(:,IH1)=XH(1:NGRID,1)-XH(1:NGRID,IH1+1)
          ENDDO
          DO IH1=1,NBACK
            DO IH2=IH1,NBACK
              A(IH1,IH2)=SUM(DF(:,IH1)*DF(:,IH2))
            ENDDO
            B(IH1)=SUM(DF(:,IH1)*FH(1:NGRID,1))
          ENDDO
          CALL MPE$COMBINE('MONOMER','+',A)
          CALL MPE$COMBINE('MONOMER','+',B)
          DO IH1=1,NBACK
            DO IH2=1,IH1-1
              A(IH1,IH2)=A(IH2,IH1)
            ENDDO
          ENDDO
          REGVAR=0.D0
          DO IH1=1,NBACK
            REGVAR=REGVAR+A(IH1,IH1)
          ENDDO
          REGVAR=MAX(REGVAR/REAL(NBACK,KIND=8)*1.D-6,1.D-30)
          DO IH1=1,NBACK
            A(IH1,IH1)=A(IH1,IH1)+REGVAR
          ENDDO
          CALL LIB$INVERTR8(NBACK,A,AINV)
          GAMMA=MATMUL(AINV,B)
          DO IH1=1,NBACK
            XPROP(1:NGRID)=XPROP(1:NGRID) &
     &                    -GAMMA(IH1)*(DX(:,IH1)+BETA*DF(:,IH1))
          ENDDO
!         == OVERSHOOT SAFEGUARD: FALL BACK TO THE PLAIN PRECONDITIONED==
!         == RESIDUAL STEP, WHICH IS A GUARANTEED DESCENT DIRECTION    ==
          STEPVAR=SUM((XPROP(1:NGRID)-XH(1:NGRID,1))**2)
          FVAR=SUM(FH(1:NGRID,1)**2)
          CALL MPE$COMBINE('MONOMER','+',STEPVAR)
          CALL MPE$COMBINE('MONOMER','+',FVAR)
          IF(STEPVAR.GT.100.D0*BETA**2*MAX(FVAR,1.D-30)) THEN
            XPROP(1:NGRID)=XH(1:NGRID,1)+BETA*FH(1:NGRID,1)
          END IF
          DEALLOCATE(DF,DX,A,AINV,B,GAMMA)
        END IF
      ELSE
!
!       ================================================================
!       == ENERGY WENT UP: BACKTRACK HALFWAY TOWARDS THE BEST POINT. A ==
!       == SECOND CONSECUTIVE FAILURE ALSO DISTRUSTS THE ANDERSON      ==
!       == HISTORY (DROP IT) AND SHRINKS THE STEP LENGTH FOR LATER.    ==
!       ================================================================
        NREJ=NREJ+1
        NREJTOT=NREJTOT+1
!       == A REJECTION RIGHT AFTER A SINGLE ACCEPTED BACKTRACKING STEP  ==
!       == (ACCEPT/REJECT PERIOD-2 CYCLE): THE FULL-LENGTH STEP KEEPS   ==
!       == OVERSHOOTING WHILE ITS HALF IS ACCEPTED, SO BETA NEVER SHRINKS==
!       == (NREJ NEVER REACHES 2). NIO AFM + DAVIDSON: 146 OF 299 TRIAL ==
!       == POINTS REJECTED AT BETA=0.5. SHORTEN THE STEP IN THAT CASE.  ==
        IF(NREJ.EQ.1.AND.NACCSTREAK.EQ.1.AND.TBACKACC) THEN
          BETA=MAX(0.5D0*BETA,BETAMIN)
        END IF
        NACCSTREAK=0
        TCLEAN=.FALSE.
        CSTATUS='REJECT'
!       == THE STEP LENGTH IS HALVED ONCE PER REJECTION EPISODE: THE      ==
!       == FURTHER BACKTRACKING STEPS ALREADY SHORTEN THE TRIAL STEP, AND ==
!       == HALVING BETA ON EACH OF THEM COLLAPSED IT TO BETAMIN, AFTER    ==
!       == WHICH ~20 ACCEPTED STEPS WERE NEEDED TO RECOVER (FCC AL, 72    ==
!       == IRREDUCIBLE K-POINTS: 77 INSTEAD OF 14 ITERATIONS).            ==
        IF(NREJ.EQ.2) THEN
          NVALID=MIN(NVALID,1)
          BETA=MAX(0.5D0*BETA,BETAMIN)
        END IF
        IF(NREJ.GT.NREJMAX) THEN
!         == RE-ANCHOR: RE-EVALUATE THE BEST POINT ITSELF AND ACCEPT   ==
!         == WHATEVER IT GIVES WITH THE NOW BETTER-CONVERGED STATES    ==
          CSTATUS='REANCHOR'
          NANCHORTOT=NANCHORTOT+1
          XPROP=XH(:,1)
          ABEST=HUGE(1.D0)
          NVALID=0
          NREJ=0
          BETA=MAX(0.5D0*BETA,BETAMIN)
        ELSE
          XPROP=XH(:,1)+0.5D0*(THETA-XH(:,1))
        END IF
      END IF
      CALL MIXVAR_REPORT(CSTATUS)
!     == KEEP THE GAUGE OF THETA ALIGNED WITH THE OUTPUT HAMILTONIAN.   ==
!     == A UNIFORM SHIFT DOES NOT CHANGE THE ENERGY, SO IT IS PROJECTED ==
!     == OUT OF THE RESIDUALS AND THETA WOULD KEEP ITS STARTING OFFSET. ==
!     == IN CELLS WITH MUCH VACUUM THE AVERAGE OF V_OUT MOVES BY HARTREES==
!     == DURING THE SCF; THE EIGENVALUES OF H[THETA] THEN LIE FAR OFF,  ==
!     == WHICH STALLS THE PRECONDITIONED EIGENSOLVERS (H2O LAYER IN AN  ==
!     == 18 A CELL: EIGENVALUES 66 EV TOO LOW, ENERGY STUCK 75 MH HIGH).==
!     == ONLY A LARGE OFFSET IS REMOVED: SHIFTING THETA IN EVERY STEP     ==
!     == DISTURBED RMM-DIIS IN THE STRONGLY CHANGING EARLY STEPS (MGO     ==
!     == SCAN0R: EXCITED STATE). BULK OFFSETS STAY BELOW ~0.3 H.         ==
      IF(ABS(GAUGEOFF).GT.GAUGETOL.AND..NOT.TNOGAUGE) THEN
        XPROP=XPROP+GAUGEOFF*SHIFT
        GAUGELAST=GAUGEOFF
      END IF
      IF(ALLOCATED(TVAC)) THEN
        DO IDIMV=1,NDIMD
          WHERE(TVAC) XPROP(1+NRL*(IDIMV-1):NRL*IDIMV)=X(1+NRL*(IDIMV-1):NRL*IDIMV)
        ENDDO
      END IF
      THETA=XPROP
      X=XPROP
      RETURN
      CONTAINS
!       ................................................................
        SUBROUTINE MIXVAR_KERKERKEEPAVERAGE(V)
        REAL(8),INTENT(INOUT) :: V(NRL,NDIMD)
        REAL(8)               :: VAV(NDIMD),VAVF(NDIMD),RNRL
        INTEGER(4)            :: IDIM
        RNRL=REAL(NRL,KIND=8)
        CALL MPE$COMBINE('MONOMER','+',RNRL)
        DO IDIM=1,NDIMD
          VAV(IDIM)=SUM(V(:,IDIM))
        ENDDO
        CALL MPE$COMBINE('MONOMER','+',VAV)
        VAV=VAV/RNRL
        CALL MIX_KERKERFILTER(NRL,NDIMD,G0SQ,V)
!       == SET THE (GLOBAL) G=0 COMPONENT TO ITS UNFILTERED VALUE,     ==
!       == WHETHER OR NOT THE FILTER ITSELF REMOVED IT.                ==
        DO IDIM=1,NDIMD
          VAVF(IDIM)=SUM(V(:,IDIM))
        ENDDO
        CALL MPE$COMBINE('MONOMER','+',VAVF)
        VAVF=VAVF/RNRL
!       == DIAGNOSTIC VESPAW_DIAG_KERKERNOAVG: G=0 REMOVED (PLAIN FILTER) ==
        IF(TNOAVG) VAV=0.D0
        DO IDIM=1,NDIMD
          V(:,IDIM)=V(:,IDIM)-VAVF(IDIM)+VAV(IDIM)
        ENDDO
        END SUBROUTINE MIXVAR_KERKERKEEPAVERAGE
!       ................................................................
        SUBROUTINE MIXVAR_REPORT(CSTAT)
        CHARACTER(*),INTENT(IN) :: CSTAT
        IF(THISTASK.NE.1) RETURN
        CALL FILEHANDLER$UNIT('PROT',NFILO)
        WRITE(NFILO,FMT='("VARMIX ",I5,1X,A8," A=",F20.10," ABEST=",ES18.10' &
     &                //'," DRES2=",ES10.3," MAXRDH=",ES10.3," BETA=",F6.3' &
     &                //'," GAUGE=",ES10.3)') &
     &        NEVAL,CSTAT,ENERGY,ABEST,RESNOW,RESREST,BETA,GAUGEOFF
        IF(TDEBUG) WRITE(*,FMT='("VARMIX ",I5,1X,A8," A=",F20.10' &
     &        //'," DRES2=",ES10.3," BETA=",F6.3)')NEVAL,CSTAT,ENERGY,RESNOW,BETA
        END SUBROUTINE MIXVAR_REPORT
      END
