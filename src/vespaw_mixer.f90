      SUBROUTINE WAVES_MIXRHO_ANDERSON(NRL,NDIMD,G0SQ,NHISTORYIN,RHODIM,DENDIM,RHO,DENMAT,CONVTOL,TCONV,&
           CONVPSI)
!     ******************************************************************
!     ** ANDERSON MIXING OF THE CHARGE DENSITY / ONE-CENTER DENSITY   **
!     ** MATRIX -- AN ALTERNATIVE TO WAVES_MIXRHO_PUL FOR THE         **
!     ** CG/DAV/RMM OPTIMIZERS (SELECT VIA !PSIDYN MIXER='ANDERSON'). **
!     **                                                              **
!     ** STANDARD TYPE-I ANDERSON ACCELERATION (EYERT, J. COMPUT.     **
!     ** PHYS. 124, 271 (1996); MATHEMATICALLY THE SAME FAMILY AS THE **
!     ** "DELTA-R" PULAY SCHEME OF KRESSE&FURTHMUELLER EQS. 88-92,    **
!     ** SEE WAVES_MIXRHO_PUL_DR ABOVE): FIT THE COMBINATION OF PAST  **
!     ** RESIDUAL *DIFFERENCES* THAT BEST CANCELS THE NEWEST RESIDUAL **
!     ** IN A LEAST-SQUARES SENSE, THEN APPLY THAT SAME COMBINATION   **
!     ** TO THE DENSITIES PLUS A DAMPED RESIDUAL STEP (DAMPING=BETA). **
!     **                                                              **
!     ** UNLIKE THE PLAIN PULAY FIT, BETA IS ADAPTIVE HERE: IT SHRINKS**
!     ** AND THE HISTORY IS DISCARDED ("RESTARTED DIIS") WHENEVER THE **
!     ** RESIDUAL FAILS TO IMPROVE ON ITS BEST VALUE SINCE THE LAST   **
!     ** RESTART, AND GROWS BACK TOWARDS BETAMAX WHILE CONVERGENCE IS **
!     ** STEADY. INTENDED AS A MORE ROBUST OPTION ON SYSTEMS (E.G.    **
!     ** CORRELATED TRANSITION-METAL OXIDES) WHERE A FIXED-G,         **
!     ** FIXED-HISTORY PULAY FIT WAS OBSERVED TO OSCILLATE WITHOUT    **
!     ** CONVERGING (SEE optimizer_compare_pmo_a/ IN THE SCAN0R       **
!     ** WORKING DIRECTORY FOR THE RUNS THAT MOTIVATED THIS).         **
!     ******************************************************************
      USE MIXANDERSON_MODULE
      USE MPE_MODULE
      IMPLICIT NONE
      INTEGER(4) ,INTENT(IN)    :: NRL   ! #(LOCAL REAL-SPACE GRID POINTS): RHODIM=NRL*NDIMD
      INTEGER(4) ,INTENT(IN)    :: NDIMD ! #(DENSITY COMPONENTS: TOTAL, SPIN...)
      REAL(8)    ,INTENT(IN)    :: G0SQ  ! KERKER SCREENING WAVEVECTOR**2 [BOHR**-2]
      INTEGER(4) ,INTENT(IN)    :: NHISTORYIN ! MIXNHISTORY OVERRIDE (0=KEEP MODULE DEFAULT); SET ON TFIRST ONLY
      INTEGER(4) ,INTENT(IN)    :: RHODIM
      INTEGER(4) ,INTENT(IN)    :: DENDIM
      REAL(8)    ,INTENT(INOUT) :: RHO(RHODIM)
      REAL(8)    ,INTENT(INOUT) :: DENMAT(DENDIM)
      REAL(8)    ,INTENT(IN)    :: CONVTOL ! DENSITY-RESIDUAL NORM BELOW WHICH TCONV IS DECLARED; SET
                                            ! VIA WAVES$SETR8('MIXTOL',...), !PSIDYN MIXTOL= IN .cntl
      LOGICAL(4) ,INTENT(OUT)   :: TCONV
      REAL(8)    ,INTENT(OUT)   :: CONVPSI
      REAL(8)    ,PARAMETER     :: BETAMIN=0.02D0,BETAMAX=0.5D0
      INTEGER(4)                :: NTOT
      REAL(8)                   :: SVAR,C(1,1)
      REAL(8)                   :: RESVAR ! ||RAW UNMIXED DENSITY CHANGE||**2
      INTEGER(4)                :: IH1,IH2,NBACK
      LOGICAL(4)                :: TRESTART
      INTEGER(4)                :: NTASKS,THISTASK
      LOGICAL(4)                :: TDEBUG
!     == DAV+ANDERSON SCAN0R INSTABILITY DIAGNOSTIC (2026-09-09): OPT-IN,   ==
!     == COMPANION TO THE DAVIDSON-SIDE VESPAW_DAV_COND_DIAG IN             ==
!     == VESPAW_CG.F90 -- CONDITION NUMBER OF THE RESIDUAL-DIFFERENCE GRAM  ==
!     == MATRIX A (=DF^T*DF) THAT GETS INVERTED FOR GAMMA EACH ITERATION.   ==
!     == SEE THE DEV NOTES, "WHY IS DAV+ANDERSON UNSTABLE...".          ==
      LOGICAL(4),SAVE           :: TANDCONDDIAGCHECKED=.FALSE.
      LOGICAL(4),SAVE           :: TANDCONDDIAG=.FALSE.
      CHARACTER(16)             :: CENVANDCONDDIAG
      REAL(8)   ,ALLOCATABLE    :: AIDENT(:,:),AVEC(:,:),AEIG(:)
!     ******************************************************************
      IF(.NOT.TANDCONDDIAGCHECKED) THEN
        CALL GET_ENVIRONMENT_VARIABLE('VESPAW_ANDERSON_COND_DIAG',CENVANDCONDDIAG)
        TANDCONDDIAG=(LEN_TRIM(CENVANDCONDDIAG).GT.0)
        TANDCONDDIAGCHECKED=.TRUE.
        IF(TANDCONDDIAG) THEN
          PRINT*,'VESPAW_ANDERSON_COND_DIAG SET -- PRINTING RESIDUAL-HISTORY' &
     &          ,' GRAM MATRIX CONDITION NUMBER AND ||GAMMA|| EACH ITERATION'
        END IF
      END IF
      CALL MPE$QUERY('~',NTASKS,THISTASK)
      TACTIVE=.TRUE.  ! SEE MIXER$GETR8('RESIDUAL',...), BELOW
      NTOT=RHODIM+DENDIM
      IF(TFIRST) THEN
         IITER=1
         NVALID=0
         BETA=BETAMAX
         RESBEST=HUGE(1.D0)
         IF(NHISTORYIN.GT.0) NHISTORY=NHISTORYIN
         IF(NHISTORY.LT.1) THEN
            CALL ERROR$MSG('NHISTORY MUST BE AT LEAST 1')
            CALL ERROR$STOP('WAVES_MIXRHO_ANDERSON')
         END IF
         ALLOCATE(XOLD(NTOT,NHISTORY+1))
         XOLD=0.D0
         ALLOCATE(FOLD(NTOT,NHISTORY+1))
         FOLD=0.D0
         ALLOCATE(RES(NTOT))
         ALLOCATE(XPROP(NTOT))
         ALLOCATE(DF(NTOT,NHISTORY))
         ALLOCATE(A(NHISTORY,NHISTORY))
         ALLOCATE(AINV(NHISTORY,NHISTORY))
         ALLOCATE(B(NHISTORY))
         ALLOCATE(GAMMA(NHISTORY))
         XOLD(1:RHODIM,1)=RHO(:)
         XOLD(RHODIM+1:NTOT,1)=DENMAT(:)
         TFIRST=.FALSE.
         TCONV=.FALSE.
         CONVPSI=1.D-3
         RETURN
      END IF
      IITER=IITER+1
!
!     ==================================================================
!     == RESIDUAL OF THE NEWEST STEP: RES = RHO_OUT - RHO_IN(=XOLD(:,1))
!     ==================================================================
      RES(1:RHODIM)=RHO(:)-XOLD(1:RHODIM,1)
      RES(RHODIM+1:NTOT)=DENMAT(:)-XOLD(RHODIM+1:NTOT,1)
      CALL LIB$SCALARPRODUCTR8(.TRUE.,RHODIM,1,RES(1:RHODIM),1, &
           RES(1:RHODIM),C)
      SVAR=C(1,1)
!     == THE DENSITY GRID IS DISTRIBUTED OVER THE TASKS OF THE MONOMER: ==
!     == EVERY GRID SCALAR PRODUCT IS SUMMED OVER THEM, SO THAT ALL     ==
!     == TASKS TAKE THE SAME MIXING DECISIONS AND COEFFICIENTS.         ==
      CALL MPE$COMBINE('MONOMER','+',SVAR)
      RESIDUAL=SVAR
      CALL VERBOSITY$GETL4('DEBUG',TDEBUG)
      IF(THISTASK.EQ.1) THEN
        IF(TDEBUG) PRINT*,'ANDERSON-MIXER ITER ',IITER,' RHO-DIFF (RES) =',SVAR
      END IF
      IF(TANDCONDDIAG.AND.THISTASK.EQ.1) THEN
        PRINT*,'VESPAW_ANDERSON_COND_DIAG CALLTRACE IITER=',IITER &
     &        ,' NVALID=',NVALID,' SVAR=',SVAR
      END IF
      RESVAR=SVAR
      IF(SVAR.GT.1.D-1) THEN
         CONVPSI=1.D-4
      ELSE
         CONVPSI=1.D-6
      END IF
      IF(SVAR.LT.1.D-4) CONVPSI=1.D-8
      TCONV=(SVAR.LT.CONVTOL)
!
!     ==================================================================
!     == RESTARTED DIIS: SEE WAVES_MIXRHO_PUL FOR THE RATIONALE       ==
!     ==================================================================
      TRESTART=(RESVAR.GT.RESBEST)
      IF(TRESTART) THEN
         BETA=MAX(BETA*0.5D0,BETAMIN)
         NVALID=0
         RESBEST=RESVAR
         IF(THISTASK.EQ.1.AND.TDEBUG) PRINT*,'ANDERSON-MIXER: RESTARTING HISTORY, NEW BETA=',BETA
      ELSE
         RESBEST=RESVAR
         BETA=MIN(BETA*1.1D0,BETAMAX)
      END IF
!
!     == KERKER-PRECONDITION THE DENSITY PART OF THE RESIDUAL (NOT THE   ==
!     == ONE-CENTER DENMAT PART -- SEE MIX_KERKERFILTER) BEFORE IT ENTERS==
!     == THE HISTORY. TCONV/RESVAR/THE RESTART DECISION ABOVE ALREADY    ==
!     == USED THE RAW (UNFILTERED) RESIDUAL, AS THEY SHOULD.             ==
      CALL MIX_KERKERFILTER(NRL,NDIMD,G0SQ,RES(1:RHODIM))
      FOLD(:,1)=RES(:)   ! NEWEST RESIDUAL
      NBACK=MIN(NHISTORY,NVALID)
!
!     ==================================================================
!     == LEAST-SQUARES FIT: MINIMIZE ||RES - SUM_I GAMMA_I*DF_I||**2, ==
!     == DF_I = RES - FOLD(:,I+1) (RESIDUAL DIFFERENCE TO HISTORY I)  ==
!     ==================================================================
      IF(NBACK.EQ.0) THEN
!        == NO HISTORY YET (E.G. RIGHT AFTER A RESTART) -- PLAIN DAMPED ==
!        == MIXING. AVOIDS THE EMPTY-SUM DIVIDE-BY-ZERO THE FIT BELOW  ==
!        == WOULD HIT.                                                 ==
         XPROP=XOLD(:,1)+BETA*RES(:)
      ELSE
         DO IH1=1,NBACK
            DF(:,IH1)=FOLD(:,1)-FOLD(:,IH1+1)
         END DO
         CALL LIB$SCALARPRODUCTR8(.TRUE.,RHODIM,NBACK,DF(1:RHODIM,1:NBACK),&
              NBACK,DF(1:RHODIM,1:NBACK),A(1:NBACK,1:NBACK))
         DO IH1=1,NBACK
            CALL LIB$SCALARPRODUCTR8(.FALSE.,RHODIM,1,DF(1:RHODIM,IH1),1,&
                 RES(1:RHODIM),B(IH1))
         END DO
         CALL MIX_COMBINEMONOMER(NBACK,A(1:NBACK,1:NBACK),B(1:NBACK))
!        == TIKHONOV REGULARIZATION, SAME RATIONALE AS THE PULAY MIXER ==
         SVAR=0.D0
         DO IH1=1,NBACK
            SVAR=SVAR+A(IH1,IH1)
         END DO
         SVAR=MAX(SVAR/REAL(NBACK,KIND=8)*1.D-6,1.D-12)
         DO IH1=1,NBACK
            A(IH1,IH1)=A(IH1,IH1)+SVAR
         END DO
         IF(TANDCONDDIAG) THEN
           ALLOCATE(AIDENT(NBACK,NBACK));ALLOCATE(AVEC(NBACK,NBACK))
           ALLOCATE(AEIG(NBACK))
           AIDENT=0.D0
           DO IH1=1,NBACK
             AIDENT(IH1,IH1)=1.D0
           END DO
           CALL LIB$GENERALEIGENVALUER8(NBACK,A(1:NBACK,1:NBACK),AIDENT,AEIG,AVEC)
           PRINT*,'VESPAW_ANDERSON_COND_DIAG ITER=',IITER,' NBACK=',NBACK &
     &           ,' A_COND=',MAXVAL(AEIG)/MAX(MINVAL(AEIG),1.D-300) &
     &           ,' BETA=',BETA
           DEALLOCATE(AIDENT,AVEC,AEIG)
         END IF
         CALL LIB$INVERTR8(NBACK,A(1:NBACK,1:NBACK),AINV(1:NBACK,1:NBACK))
         GAMMA=0.D0
         DO IH1=1,NBACK
            DO IH2=1,NBACK
               GAMMA(IH1)=GAMMA(IH1)+AINV(IH1,IH2)*B(IH2)
            END DO
         END DO
         IF(TANDCONDDIAG) THEN
           PRINT*,'VESPAW_ANDERSON_COND_DIAG ITER=',IITER &
     &           ,' ||GAMMA||=',SQRT(SUM(GAMMA(1:NBACK)**2))
         END IF
         XPROP=XOLD(:,1)+BETA*RES(:)
!        == APPLY THE HISTORY CORRECTION TO THE PLANE-WAVE DENSITY (RHODIM) ==
!        == ONLY -- GAMMA WAS FITTED PURELY FROM THE RHODIM PART OF THE     ==
!        == HISTORY (ABOVE), SO IT IS A SAFE-SIZED CORRECTION *THERE*, BUT  ==
!        == UNJUSTIFIED FOR THE ONE-CENTER DENSITY MATRIX (DENDIM), WHOSE   ==
!        == OWN DELTA-X/DELTA-F IT NEVER SAW. FOUND 2026-09-07              ==
!        == (THE DEV NOTES): APPLYING GAMMA THERE TOO (THE ORIGINAL     ==
!        == CODE) COULD BLOW UP THE DENDIM STEP TO UNPHYSICAL MAGNITUDE     ==
!        == (NORM~3, ON A QUANTITY THAT SHOULD BE O(1)) EVEN WHEN THE       ==
!        == RHODIM STEP LOOKED PERFECTLY SANE -- CORRUPTING THE PAW         ==
!        == AUGMENTATION POTENTIAL AND DRIVING THE NEXT DAVIDSON            ==
!        == DIAGONALIZATION TO MILLION-HARTREE EIGENVALUES. A THRESHOLD-    ==
!        == BASED SAFEGUARD ON THE DENDIM STEP (TRIED FIRST) DOES NOT WORK  ==
!        == EITHER: THE *RAW*, UNMIXED DENDIM RESIDUAL ITSELF IS ALREADY    ==
!        == LARGE/NOISY EARLY IN THE SCF, SO "STEP > 100X RAW RESIDUAL"     ==
!        == NEVER TRIPS. LEAVING DENDIM ON PLAIN DAMPED MIXING (THE SAME    ==
!        == SAFE FALLBACK NBACK=0 ALREADY USES EVERYWHERE) SIDESTEPS THE    ==
!        == PROBLEM ENTIRELY -- MATCHING WHAT THE PULAY MIXER GETS FOR      ==
!        == FREE AT NBACK=1 (ITS NORMALIZED ALPHABAR DEGENERATES EXACTLY    ==
!        == TO LINEAR MIXING THERE; ANDERSON'S UNCONSTRAINED GAMMA HAS NO   ==
!        == SUCH BOUND).                                                    ==
         DO IH1=1,NBACK
            XPROP(1:RHODIM)=XPROP(1:RHODIM) &
                 -GAMMA(IH1)*((XOLD(1:RHODIM,1)-XOLD(1:RHODIM,IH1+1))+BETA*DF(1:RHODIM,IH1))
         END DO
      END IF
!
!     ==================================================================
!     == OVERSHOOT SAFEGUARD, SAME IDEA AS THE PULAY MIXER (RHODIM ONLY  ==
!     == -- DENDIM IS ALWAYS PLAIN DAMPED MIXING NOW, SEE ABOVE, SO IT   ==
!     == NEEDS NO SEPARATE CHECK)                                        ==
!     ==================================================================
      CALL LIB$SCALARPRODUCTR8(.TRUE.,RHODIM,1,&
           XPROP(1:RHODIM)-XOLD(1:RHODIM,1),1,&
           XPROP(1:RHODIM)-XOLD(1:RHODIM,1),C)
      CALL MPE$COMBINE('MONOMER','+',C)
      IF(C(1,1).GT.100.D0*MAX(RESVAR,1.D-12)) THEN
         XPROP(1:RHODIM)=XOLD(1:RHODIM,1)+BETA*RES(1:RHODIM)
      END IF
!
      RHO(:)=XPROP(1:RHODIM)
      DENMAT(:)=XPROP(RHODIM+1:NTOT)
!
!     ==================================================================
!     == PROPAGATE HISTORY                                            ==
!     ==================================================================
      DO IH1=NHISTORY+1,2,-1
         XOLD(:,IH1)=XOLD(:,IH1-1)
         FOLD(:,IH1)=FOLD(:,IH1-1)
      END DO
      XOLD(:,1)=XPROP
      NVALID=NVALID+1
      RETURN
      END
