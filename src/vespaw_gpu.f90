      SUBROUTINE VESPAW$GPU_INIT(MPIRANK,MPISIZE)
      IMPLICIT NONE
      INTEGER(4),INTENT(IN) :: MPIRANK,MPISIZE
#IF DEFINED(CPPVAR_GPU_CUDA)
      INTEGER(C_INT)        :: IEN,IDEV
      CALL C_VESPAW_GPU_INIT(INT(MPIRANK,C_INT),INT(MPISIZE,C_INT),IEN,IDEV)
