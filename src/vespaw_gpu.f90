      SUBROUTINE VESPAW$GPU_FFT_1D(DIR,LEN,NFFT,X,Y)
      IMPLICIT NONE
      CHARACTER(*),INTENT(IN)           :: DIR
      INTEGER(4)  ,INTENT(IN)           :: LEN,NFFT
      COMPLEX(8)  ,INTENT(INOUT),TARGET :: X(LEN,NFFT)
      COMPLEX(8)  ,INTENT(OUT)  ,TARGET :: Y(LEN,NFFT)
#IF DEFINED(CPPVAR_GPU_CUDA)
      INTEGER(C_INT)                    :: ISIGN
      IF(.NOT.TGPU_ACTIVE) RETURN
      IF(LEN.LE.0.OR.NFFT.LE.0) RETURN
      ISIGN=1_C_INT
      IF(DIR.EQ.'RTOG') ISIGN=-1_C_INT
      CALL C_VESPAW_GPU_FFT_1D(ISIGN,INT(LEN,C_INT),INT(NFFT,C_INT) &
     &                        ,C_LOC(X(1,1)),C_LOC(Y(1,1)))
#ENDIF
      RETURN
      END SUBROUTINE VESPAW$GPU_FFT_1D

